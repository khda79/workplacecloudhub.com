# Private stable V1 adapter. Preserve existing matching; do not choose attribute winners.
function Get-CISourceEvidence {
    param([string]$RawRootPath, $RawContract, $Identity, $CIIndex, $CISystems, $CorrelationIndex, $State, $Context=$null)
    $adapters=@(
        @{File='Entra_Users.csv';Type='User';System='MicrosoftEntraID';Id='SourceUserId';Kind='EntraUserObjectId';Join='SourceUserId'},
        @{File='Entra_Groups.csv';Type='Group';System='MicrosoftEntraID';Id='SourceGroupId';Kind='EntraGroupObjectId';Join='SourceGroupId'},
        @{File='Entra_Devices.csv';Type='Device';System='MicrosoftEntraID';Id='SourceObjectId';Kind='EntraDeviceObjectId';Join='SourceDeviceId'},
        @{File='Intune_ManagedDevices.csv';Type='Device';System='MicrosoftIntune';Id='ManagedDeviceId';Kind='IntuneManagedDeviceId';Join='AzureAdDeviceId'},
        @{File='M365_SubscribedSkus.csv';Type='License';System='MicrosoftGraph';Id='SubscribedSkuId';Kind='SubscribedSkuId';Join='SkuId'},
        @{File='ExchangeOnline_Mailboxes.csv';Type='Mailbox';System='ExchangeOnline';Id='SourceMailboxId';Kind='SourceMailboxId';Join='SourceMailboxId'}
    )
    $seen=@{}
    foreach ($adapter in $adapters) {
        $table=@($RawContract.tables | Where-Object name -ceq $adapter.File)
        if ($table.Count -ne 1 -or $table[0].area -cnotmatch '^Raw\\[A-Za-z0-9]+$') { throw 'Unsupported raw evidence contract.' }
        $path=Join-Path (Join-Path $RawRootPath $table[0].area.Substring(4)) $adapter.File
        if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { throw 'Missing required evidence file.' }
        $State.Hashes[$path]=(Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash
        Test-CIExactHeader -Path $path -Columns $table[0].columns
        Import-Csv -LiteralPath $path | ForEach-Object {
            $row=$_
            foreach ($field in $Identity.Keys) {
                if ([string]$row.$field -cne [string]$Identity[$field]) { throw 'Source evidence tenant identity mismatch.' }
            }
            if ([string]$row.SourceSystem -cne $adapter.System) { throw 'Unexpected native SourceSystem.' }
            $sourceId=[string]$row.($adapter.Id)
            if ([string]::IsNullOrWhiteSpace($sourceId)) { throw 'Missing native source object identity.' }
            $correlation=([string]$row.($adapter.Join)).Trim().ToLowerInvariant()
            if ($adapter.System -ceq 'MicrosoftIntune' -and (-not $correlation -or $correlation -ceq '00000000-0000-0000-0000-000000000000')) {
                $correlation='intune:'+$sourceId.Trim().ToLowerInvariant()
            }
            if (-not $correlation) { throw 'Missing native correlation key.' }
            if ($adapter.Type -ceq 'Mailbox') {
                # This is the existing mailbox normalizer's ID derivation.
                $ciId=$Identity.TenantKey+'|exo-mailbox|'+$correlation
            } else {
                $joinKey=ConvertTo-Json -InputObject @($adapter.Type,$correlation) -Compress
                $ciId=[string]$CorrelationIndex[$joinKey]
            }
            if (-not $ciId -or -not $CIIndex.ContainsKey($ciId) -or $CIIndex[$ciId] -cne $adapter.Type) { throw 'Unmapped native source object.' }
            if ($adapter.System -cnotin @($CISystems[$ciId].Split('+'))) { throw 'Native source does not match curated provenance.' }
            $sourceKey=ConvertTo-Json -InputObject @($Identity.TenantKey,$adapter.System,$adapter.Kind,$sourceId.Trim().ToLowerInvariant()) -Compress
            if ($seen.ContainsKey($sourceKey)) { throw 'Duplicate native source identity.' }
            $seen[$sourceKey]=$true
            $record=[ordered]@{}
            foreach ($field in $Identity.Keys) { $record[$field]=$Identity[$field] }
            $record.CI_ID=$ciId; $record.SourceSystem=$adapter.System
            $record.SourceID=$sourceId; $record.SourceIDKind=$adapter.Kind
            $record.CorrelationKey=$correlation; $record.MappingStatus='Correlated'
            $record.SourceCollectedDateTime=[string]$row.SourceCollectedDateTime
            $State.Count++; $State.ByCI[$ciId]=$true
            if ($State.ContainsKey('HardwareIndex') -and $adapter.System -ceq 'MicrosoftIntune') {
                $State.HardwareIndex[$sourceId.Trim().ToLowerInvariant()]=@{CI_ID=$ciId;Correlation=$correlation;Collected=[string]$row.SourceCollectedDateTime}
            }
            if ($null -ne $Context -and $adapter.Type -ceq 'Device') {
                Write-CIDeviceSourceContext -Context $Context -SourceRow $row -Mapping ([pscustomobject]$record)
            }
            [pscustomobject]$record
        }
    }
}

