<#
.SYNOPSIS
Offline coverage for DATA-ALL and DATA-LAST uploads from both legacy CSV exporters.
.VERSION
1.0.0
#>
[CmdletBinding()]
param()
$ErrorActionPreference='Stop'
$root=Split-Path $PSScriptRoot -Parent
$manifest=if($PSVersionTable.PSVersion.Major -lt 7){Join-Path $root 'Modules/SmartM365.Core/Compatibility/WindowsPowerShell5/SmartM365-WindowsPowerShell5.psd1'}else{Join-Path $root 'Modules/SmartM365.Core/SmartM365.Core.psd1'}
$temp=Join-Path ([IO.Path]::GetTempPath()) ('SmartM365LegacyUpload-'+[guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $temp | Out-Null
$names=@('EnableSharePointUpload','SmartM365CollectorUploadPolicies','SmartM365CollectorUploadRoots','RetentionMaxCSV','csvGeneratedPaths','SmartM365TenantKey','SmartM365CsvValidationRules','SmartM365MaxItems','SmartM365TestMaxItems','SmartM365IsMaxItemsRun','LogTextFile')
$saved=@{};foreach($name in $names){$v=Get-Variable -Name $name -Scope Global -ErrorAction SilentlyContinue;if($v){$saved[$name]=@{Value=$v.Value}}}
try {
    $m=Import-Module $manifest -Force -PassThru
    $checks=& $m {
        param($base)
        $all=Join-Path $base 'DATA-ALL';$last=Join-Path $base 'DATA-LAST';New-Item -ItemType Directory -Path $all,$last -Force | Out-Null
        $global:RetentionMaxCSV=0;$global:EnableSharePointUpload=$true;$global:SmartM365TenantKey='synthetic'
        $global:SmartM365CsvValidationRules=@{};$global:SmartM365MaxItems=0;$global:SmartM365TestMaxItems=0;$global:SmartM365IsMaxItemsRun=$false;$global:LogTextFile=''
        function script:WriteLog {param($Message,$Level)}
        function script:Invoke-SmartM365WeeklyInventoryHistoryForCsv {param($SourceFiles,$TimestampedPath)}
        function script:Invoke-SmartM365SharePointCsvUpload {
            param($LocalFilePath)
            $category=Get-SmartM365SharePointUploadCategory -Path $LocalFilePath -DataAllRoot $script:all -DataLastRoot $script:last
            if(Test-SmartM365CollectorUploadEnabled -Category $category -Policies $global:SmartM365CollectorUploadPolicies -RunEnabled $global:EnableSharePointUpload){$script:uploads.Add($category)}
        }
        $script:all=$all;$script:last=$last;$count=0
        foreach($fn in @('ExportAndCopyCsv','ExportAndCopyCsvFromConvert')){
            foreach($mask in 0..3){
                $global:csvGeneratedPaths=$null
                $global:SmartM365CollectorUploadPolicies=@{DataAll=[pscustomobject]@{Enabled=[bool]($mask -band 1)};DataLast=[pscustomobject]@{Enabled=[bool]($mask -band 2)};LogAll=[pscustomobject]@{Enabled=$false}}
                $script:uploads=New-Object 'System.Collections.Generic.List[string]'
                & $fn -BaseFileName ('Synthetic'+$mask+$fn) -OutputPath $all -GlobalPath $last -Data @([pscustomobject]@{Id='synthetic'}) -NoTenantKey -SkipWeeklyHistory
                if(($script:uploads.Contains('DataAll')) -ne [bool]($mask -band 1)){throw "DATA-ALL mismatch: $fn/$mask"}
                if(($script:uploads.Contains('DataLast')) -ne [bool]($mask -band 2)){throw "DATA-LAST mismatch: $fn/$mask"}
                $count+=2
            }
        }
        if($PSVersionTable.PSVersion.Major -ge 7){
            function script:Resolve-SmartM365SourcePublicationPath {param($Path) return (Join-Path $script:all 'synthetic-stage.csv')}
            function script:Add-SmartM365StagedPublicationAction {param($Path,$TimestampedPath,[switch]$SharePointUpload,[switch]$WeeklyHistory) $script:actions.Add([pscustomobject]@{Path=$Path;TimestampedPath=$TimestampedPath;SharePointUpload=[bool]$SharePointUpload;WeeklyHistory=[bool]$WeeklyHistory;Callback=$null;ArgumentList=@()})}
            foreach($fn in @('ExportAndCopyCsv','ExportAndCopyCsvFromConvert')){
                foreach($mask in 0..3){
                    $global:csvGeneratedPaths=$null
                    $global:SmartM365CollectorUploadPolicies=@{DataAll=[pscustomobject]@{Enabled=[bool]($mask -band 1)};DataLast=[pscustomobject]@{Enabled=[bool]($mask -band 2)};LogAll=[pscustomobject]@{Enabled=$false}}
                    $script:uploads=New-Object 'System.Collections.Generic.List[string]';$script:actions=New-Object 'System.Collections.Generic.List[object]'
                    & $fn -BaseFileName ('Staged'+$mask+$fn) -OutputPath $all -GlobalPath $last -Data @([pscustomobject]@{Id='synthetic'}) -NoTenantKey -SkipWeeklyHistory
                    if(($script:uploads.Contains('DataAll')) -ne [bool]($mask -band 1) -or $script:uploads.Contains('DataLast') -or $script:actions.Count -ne 1){throw "Staged export mismatch: $fn/$mask"}
                    Copy-Item -LiteralPath (Join-Path $all 'synthetic-stage.csv') -Destination $script:actions[0].Path -Force
                    Invoke-SmartM365StagedPublicationFollowUp -Context @{StagedActions=$script:actions}
                    if(($script:uploads.Contains('DataLast')) -ne [bool]($mask -band 2)){throw "Staged DATA-LAST mismatch: $fn/$mask"}
                    $count+=2
                }
            }
        }
        $count
    } $temp
    "PASS: $checks legacy exporter upload checks; PowerShell $($PSVersionTable.PSVersion); no network."
} finally {
    if($m){Remove-Module $m -Force}
    foreach($name in $names){if($saved.ContainsKey($name)){Set-Variable -Name $name -Scope Global -Value $saved[$name].Value}else{Remove-Variable -Name $name -Scope Global -ErrorAction SilentlyContinue}}
    if(Test-Path -LiteralPath $temp){Remove-Item -LiteralPath $temp -Recurse -Force}
}

