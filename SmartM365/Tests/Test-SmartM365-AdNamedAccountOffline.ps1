<#
.SYNOPSIS
    Checks optional Named Account SAM pattern behavior without running AD collection.
#>

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$inventoryRoot = Join-Path (Split-Path -Parent $PSScriptRoot) 'SmartInventory'
$templatePath = Join-Path $inventoryRoot 'Config\AccountClassification.local.json.template'
$enrichmentPath = Join-Path $inventoryRoot 'ActiveDirectoryInventory\SmartM365-ActiveDirectory-UsersEnrichment.ps1'
$accountTypeRules = (Get-Content -LiteralPath $templatePath -Raw | ConvertFrom-Json -AsHashtable).AccountTypeRules
if (-not $accountTypeRules.NamedAccount.ContainsKey('LongSamNumericSuffixPattern') -or
    $accountTypeRules.NamedAccount['LongSamNumericSuffixPattern'] -cne '') {
    throw 'The published template must define an empty optional SAM naming pattern.'
}

$tokens = $null
$parseErrors = $null
$ast = [System.Management.Automation.Language.Parser]::ParseFile($enrichmentPath, [ref]$tokens, [ref]$parseErrors)
if (@($parseErrors).Count -gt 0) { throw 'AD users enrichment has PowerShell parse errors.' }
foreach ($name in 'Test-SmartM365TextRule', 'Get-SmartM365AccountType') {
    $definitions = @($ast.FindAll({ param($node) $node -is [System.Management.Automation.Language.FunctionDefinitionAst] -and $node.Name -eq $name }, $true))
    if ($definitions.Count -ne 1) { throw "Expected one $name function in AD users enrichment." }
    . ([scriptblock]::Create($definitions[0].Extent.Text))
}

function Assert-AccountType {
    param([hashtable]$Account, [string]$Expected)
    $actual = Get-SmartM365AccountType @Account
    if ($actual -ne $Expected) { throw "Expected '$Expected' for SAM '$($Account.SAM)', got '$actual'." }
}

$account = @{
    UPN = 'different@example.test'
    SAM = 'EXAMPLE99'
    DN = 'CN=Example,OU=People,DC=example,DC=test'
    RecipientType = 'UserMailbox'
    GivenName = 'Jane'
    Surname = 'Doe'
    GivenNameClean = 'JANE'
    SurnameClean = 'DOE'
}

Assert-AccountType -Account $account -Expected 'Unclassified Account'
$accountTypeRules.NamedAccount.Remove('LongSamNumericSuffixPattern')
Assert-AccountType -Account $account -Expected 'Unclassified Account'
$accountTypeRules.NamedAccount['LongSamNumericSuffixPattern'] = ''
Assert-AccountType -Account $account -Expected 'Unclassified Account'
$accountTypeRules.NamedAccount['LongSamNumericSuffixPattern'] = '   '
Assert-AccountType -Account $account -Expected 'Unclassified Account'
$accountTypeRules.NamedAccount['LongSamNumericSuffixPattern'] = '^EXAMPLE[0-9]{2}$'
Assert-AccountType -Account $account -Expected 'Named Account'
$account.SAM = 'OTHER99'
Assert-AccountType -Account $account -Expected 'Unclassified Account'
$accountTypeRules.NamedAccount.Remove('LongSamNumericSuffixPattern')
$account.SAM = 'JANDOE'
Assert-AccountType -Account $account -Expected 'Named Account'
$account.SAM = 'SVC_EXAMPLE'
Assert-AccountType -Account $account -Expected 'Service Account'

# External source types: a non-human population or a configured type is Non-IT staff in JobFamily.
$jobFamilyDefinition = @($ast.FindAll({ param($node) $node -is [System.Management.Automation.Language.FunctionDefinitionAst] -and $node.Name -eq 'Get-SmartM365CombinedJobFamily' }, $true))
if ($jobFamilyDefinition.Count -ne 1) { throw 'Expected one Get-SmartM365CombinedJobFamily function in AD users enrichment.' }
. ([scriptblock]::Create($jobFamilyDefinition[0].Extent.Text))
$personaLabels = [pscustomobject]@{ NoMatch = 'Unclassified' }
$externalNonItStaffTypes = @('TEST-X')
$jobFamilyCases = @(
    @('MDM-X', 'Non-human', 'Care staff', 'Non-IT staff'),
    @('TEST-X', 'Review required', 'Care staff', 'Non-IT staff'),
    @('Named Account', 'Human', 'Care staff', 'Care staff'),
    @('Service Account', 'Non-human', 'Care staff', 'Non-IT staff')
)
foreach ($case in $jobFamilyCases) {
    $family = Get-SmartM365CombinedJobFamily -AccountType $case[0] -TypeEntity 'INTEGRATED' -UserPrincipalName 'user@example.test' -NoLastLogonInOnComputer $true -PersonaCategory $case[2] -AccountPopulation $case[1]
    if ($family -ne $case[3]) { throw "JobFamily for $($case[0]) is '$family' instead of '$($case[3])'." }
}
$enrichmentText = Get-Content -LiteralPath $enrichmentPath -Raw
foreach ($marker in 'Get-SmartM365ExternalAccountTypeSource', 'Resolve-SmartM365ExternalAccountType', "'AccountTypeSource'", "'RulesAccountType'", "'WorkforcePersona'") {
    if (-not $enrichmentText.Contains($marker)) { throw "AD users enrichment does not use $marker." }
}

Write-Output 'Optional Named Account SAM pattern and external account type offline tests passed.'

