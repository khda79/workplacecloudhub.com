# Offline tests for Graph scope-to-module selection in both Core variants.
# Version: 1.0
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$variants = @(
    (Join-Path $root 'Modules/SmartM365.Core/SmartM365.Core.psm1'),
    (Join-Path $root 'Modules/SmartM365.Core/Compatibility/WindowsPowerShell5/SmartM365-WindowsPowerShell5.psm1')
)
$known = @('Microsoft.Graph.Authentication','Microsoft.Graph.Users','Microsoft.Graph.Groups','Microsoft.Graph.Reports','Microsoft.Graph.Identity.DirectoryManagement','Microsoft.Graph.Identity.SignIns')
$script:imports = @(); $script:missingModule = ''; $script:connectCount = 0
function Get-Module {
    [CmdletBinding()] param([string]$Name, [switch]$ListAvailable)
    if ($Name -eq 'Microsoft.Graph.Authentication') { return [pscustomobject]@{Name=$Name;Version=[version]'2.41.2';Path=$Name} }
    if ($ListAvailable -and $Name -in $known -and $Name -ne $script:missingModule) { return [pscustomobject]@{Name=$Name;Version=[version]'2.41.2';Path=$Name} }
}
function Import-Module { [CmdletBinding()] param([Parameter(Position=0)][string]$Name) $script:imports += $Name }
function WriteLog { param($Message,$Level) }
function Get-SmartM365ModuleDiagnosticText { param($Name) return $Name }
function Set-SmartM365InventoryConnectionOwnership { param($Connection,$Owned) }
function Disconnect-MgGraph { [CmdletBinding()] param() }
function Connect-MgGraph { [CmdletBinding()] param($Scopes,[switch]$NoWelcome) $script:connectCount++ }
function Get-MgContext { [CmdletBinding()] param() return [pscustomobject]@{TenantId='synthetic'} }
function Get-SmartM365ExceptionDetails { param($Exception) return $Exception.Message }

foreach ($path in $variants) {
    $tokens=$null; $errors=$null
    $ast=[System.Management.Automation.Language.Parser]::ParseFile($path,[ref]$tokens,[ref]$errors)
    if ($errors.Count) { throw "Parse failed: $path" }
    $fn=$ast.Find({param($n) $n -is [System.Management.Automation.Language.FunctionDefinitionAst] -and $n.Name -eq 'Connect-SmartM365CloudSession'},$true)
    if (-not $fn) { throw "Connection function missing: $path" }
    . ([scriptblock]::Create($fn.Extent.Text))
    $cases=@(
        @{Scope='Device.Read.All'; Module='Microsoft.Graph.Identity.DirectoryManagement'},
        @{Scope='Organization.Read.All'; Module='Microsoft.Graph.Identity.DirectoryManagement'},
        @{Scope='Policy.Read.All'; Module='Microsoft.Graph.Identity.SignIns'},
        @{Scope='User.Read.All'; Module='Microsoft.Graph.Users'},
        @{Scope='Group.Read.All'; Module='Microsoft.Graph.Groups'},
        @{Scope='Reports.Read.All'; Module='Microsoft.Graph.Reports'}
    )
    foreach($case in $cases) {
        $script:imports=@(); $script:missingModule=''; $script:connectCount=0
        $result=Connect-SmartM365CloudSession -ExchangeOnline:$false -Graph:$true -GraphScopes @($case.Scope)
        if (-not $result.GraphConnected -or $script:connectCount -ne 1 -or $script:imports.Count -ne 1 -or $script:imports[0] -ne $case.Module) { throw "Wrong module for $($case.Scope): $path" }
        $script:imports=@(); $script:missingModule=$case.Module; $script:connectCount=0
        $result=Connect-SmartM365CloudSession -ExchangeOnline:$false -Graph:$true -GraphScopes @($case.Scope)
        if (($result -and $result.GraphConnected) -or $script:connectCount -ne 0) { throw "Missing module did not block connection: $($case.Scope), $path" }
    }
    $script:missingModule=''; $script:imports=@(); $script:connectCount=0
    $result=Connect-SmartM365CloudSession -ExchangeOnline:$false -Graph:$true -GraphScopes @('Device.Read.All','Organization.Read.All','Policy.Read.All')
    if (-not $result.GraphConnected -or $script:imports.Count -ne 2 -or @($script:imports | Where-Object { $_ -eq 'Microsoft.Graph.Identity.DirectoryManagement' }).Count -ne 1 -or 'Microsoft.Graph.Identity.SignIns' -notin $script:imports) { throw "Mixed scopes or deduplication failed: $path" }
}
Write-Host 'Graph module mapping offline checks passed for both Core variants.'

