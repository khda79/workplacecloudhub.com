#requires -Version 7.0
[CmdletBinding()]
param()
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot '../Config/SmartM365-TenantContext.ps1')
$inventory = Join-Path $PSScriptRoot '../SmartInventory'
$fixtureRoot = Join-Path ([IO.Path]::GetTempPath()) ('SmartM365-JsonReaders-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory $fixtureRoot | Out-Null
$passed = 0
foreach ($file in Get-ChildItem -LiteralPath $inventory -Recurse -File -Filter '*.ps1') {
    if ($file.FullName -match '\\Tests\\') { continue }
    $tokens=$null; $errors=$null
    $ast = [Management.Automation.Language.Parser]::ParseFile($file.FullName, [ref]$tokens, [ref]$errors)
    if ($errors) { throw "Parse error: $($file.FullName)" }
    $functions = @($ast.FindAll({param($node) $node -is [Management.Automation.Language.FunctionDefinitionAst] -and $node.Name -in @('Get-ScriptLocalConfig','Get-SmartM365ScriptLocalConfig','LocalConfig')}, $true))
    if ($functions.Count -eq 0) { continue }
    $folder = Join-Path $fixtureRoot $file.BaseName
    New-Item -ItemType Directory $folder | Out-Null
    $syntheticScript = Join-Path $folder $file.Name
    $path = Join-Path $folder ($file.BaseName + '.local.json')
    [IO.File]::WriteAllText(($path + '.txt'), '{"JsonReaderProbe":"preferred"}')
    $functionText = ($functions | ForEach-Object {$_.Extent.Text}) -join [Environment]::NewLine
    $functionName = $functions[0].Name
    # Execute only extracted config function definitions, never an inventory entry point.
    $contextPath = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../Config/SmartM365-TenantContext.ps1')).Replace("'", "''")
    $fixtureCode = ". '$contextPath'" + [Environment]::NewLine + '$ScriptRoot = $PSScriptRoot' + [Environment]::NewLine + 'function Log { param($Message) }' + [Environment]::NewLine + $functionText + [Environment]::NewLine + $functionName
    [IO.File]::WriteAllText($syntheticScript, $fixtureCode)
    $result = & $syntheticScript
    if ($result.JsonReaderProbe -ne 'preferred') { throw "Preferred config not used: $($file.Name)" }
    if (Test-Path -LiteralPath $path) { throw "Legacy config recreated: $($file.Name)" }
    $passed++
    [IO.File]::WriteAllText($path, '{"JsonReaderProbe":"legacy"}')
    [IO.File]::WriteAllText(($path + '.txt'), '{')
    $rejected=$false
    try { & $syntheticScript | Out-Null } catch { $rejected=$true }
    if (-not $rejected) {throw "Invalid preferred config was ignored: $($file.Name)"}
    $passed++
    [IO.File]::Delete($path);[IO.File]::Delete($path+'.txt')
    $template=$path+'.template'
    [IO.File]::WriteAllText($template,'{"JsonReaderProbe":"created"}',[Text.UTF8Encoding]::new($true))
    $created=& $syntheticScript
    if($created.JsonReaderProbe -ne 'created'){throw "Configuration creation failed: $($file.Name)"}
    if((Get-FileHash $path).Hash -ne (Get-FileHash $template).Hash){throw "Configuration template bytes changed: $($file.Name)"}
    $passed++
}
[pscustomobject]@{Passed=$passed;FixtureRoot=$fixtureRoot;Evidence='Extracted configuration functions only; no collector execution'}

