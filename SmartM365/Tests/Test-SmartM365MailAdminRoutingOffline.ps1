    function ConvertToRecipientArray {param($Recipients) @($Recipients -split '[;,]' | Where-Object {$_})}
    $route=Resolve-SmartM365MaintenanceMailRecipientRoute -To 'person@example.com' -Cc 'copy@example.com' -MailPurpose Report
