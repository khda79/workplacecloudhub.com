function Assert-Route($Condition,[string]$Message) { if(-not $Condition){throw $Message} }
$normal=Resolve-SmartM365AdminMailRoute -To 'report@example.com' -Cc 'copy@example.com' -Bcc 'hidden@example.com' -Smart365Administrators 'admin@example.com' -AdministratorsOnly $false
Assert-Route ($normal.To -eq 'report@example.com;admin@example.com' -and $normal.Cc -eq 'copy@example.com' -and $normal.Bcc -eq 'hidden@example.com') 'Normal mode did not preserve recipients and add administrator.'
