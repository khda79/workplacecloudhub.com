    $body=$child.Replace('__SCOPE__','AllUsers').Replace('__MODE__',$mode).Replace('__TRUST__','$false').Replace('__REPOSITORY__',[Convert]::ToBase64String([Text.Encoding]::UTF8.GetBytes('PSGallery')))
    $encoded=[Convert]::ToBase64String([Text.Encoding]::Unicode.GetBytes($fixture+"`n"+$body))
    $output=@(& $legacy -NoProfile -NonInteractive -EncodedCommand $encoded 2>&1);$exit=$LASTEXITCODE
    if($mode -eq 'Audit' -and ($exit -ne 1 -or @($output|Where-Object {$_ -match '^MISSING WindowsPowerShell5'}).Count -ne 2)){throw 'Missing 5.1 prerequisites were not reported.'}
    if($mode -eq 'Install' -and ($exit -ne 0 -or @($output|Where-Object {$_ -match '^AVAILABLE WindowsPowerShell5'}).Count -ne 2)){throw "5.1 installation fixture failed: $($output -join '; ')"}
}
'PASS: Windows PowerShell 5.1 prerequisite audit and installation fixtures.'

