# Run the actual 5.1 prerequisite child with synthetic module discovery and installation.
$ErrorActionPreference='Stop'
$path=Join-Path $PSScriptRoot '../Setup/Install-SmartM365-SmartInventoryPrerequisites.ps1'
$tokens=$null;$errors=$null
$ast=[Management.Automation.Language.Parser]::ParseFile((Resolve-Path $path),[ref]$tokens,[ref]$errors)
if($errors.Count){throw ($errors.Message -join '; ')}
$function=$ast.Find({param($n) $n -is [Management.Automation.Language.FunctionDefinitionAst] -and $n.Name -eq 'Invoke-SmartM365WindowsPowerShellPrerequisites'},$true)
$assignment=$function.Find({param($n) $n -is [Management.Automation.Language.AssignmentStatementAst] -and $n.Left.Extent.Text -eq '$child'},$true)
if(-not $assignment){throw 'Windows PowerShell prerequisite child is missing.'}
