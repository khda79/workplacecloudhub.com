if(-not $literal){throw 'Windows PowerShell prerequisite child literal is missing.'}
$child=[string]$literal.Value
$legacy=Join-Path $env:WINDIR 'System32/WindowsPowerShell/v1.0/powershell.exe'
foreach($mode in @('Audit','Install')) {
    $fixture=@'
$script:installed=@{}
function Get-Module { [CmdletBinding()]param([switch]$ListAvailable,[string]$Name) if($script:installed.ContainsKey($Name)){[pscustomobject]@{Version=[version]'2.41.2';Path=$Name}} }
function Get-PackageProvider { [CmdletBinding()]param($Name) [pscustomobject]@{Name='NuGet'} }
function Install-Module { [CmdletBinding()]param($Name,$Repository,$Scope,[switch]$Force,[switch]$AllowClobber,$RequiredVersion) if($Name -eq 'Microsoft.Graph.Authentication' -and $RequiredVersion -ne '2.41.2'){throw 'Graph version not pinned'}; $script:installed[$Name]=$true }
function Import-Module { [CmdletBinding()]param($Name) if(-not $script:installed.ContainsKey($Name)){throw 'Imported unexpected module'} }
