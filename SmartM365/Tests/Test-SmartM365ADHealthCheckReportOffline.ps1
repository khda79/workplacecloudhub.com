<#
.SYNOPSIS
Tests AD health report rendering with synthetic unavailable domain measurements.
.VERSION
1.0.0
.NOTES
Extracts helper functions only; no collector, AD, mail, upload or tenant call is executed.
#>
[CmdletBinding()]
param([string]$SourceRoot)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
if (-not $SourceRoot) { $SourceRoot = Split-Path $PSScriptRoot -Parent }
$path = Join-Path $SourceRoot 'SmartInventory/ActiveDirectoryInventory/SmartM365-ActiveDirectory-HealthCheck.ps1'
$tokens = $null; $parseErrors = $null
$ast = [Management.Automation.Language.Parser]::ParseFile($path, [ref]$tokens, [ref]$parseErrors)
if ($parseErrors.Count) { throw 'AD health collector source failed parsing.' }
$definitions = foreach ($name in @('ConvertTo-IsoUtc','ConvertTo-HtmlSafe','Worst','Rank','ConvertTo-ReportHtml')) {
    $node = $ast.Find({ param($n) $n -is [Management.Automation.Language.FunctionDefinitionAst] -and $n.Name -eq $name }, $true)
    if (-not $node) { throw "Missing report helper: $name" }
    $node.Extent.Text
}
$module = New-Module -ScriptBlock ([scriptblock]::Create($definitions -join "`n"))
try {
    & $module {
        Set-StrictMode -Version Latest
        $script:RunId = 'synthetic-report'
        $script:DomainFacts = [Collections.ArrayList]::new()
        $script:Cases = 0
        function Assert-Report([bool]$Condition, [string]$Message) {
            if (-not $Condition) { throw $Message }
        }
        function New-TestRow([string]$Category, [string]$Check, [string]$Status, [string]$Domain = 'domain.test', [string]$Value = '') {
            [pscustomobject]@{ Forest='forest.test'; Domain=$Domain; DC=''; Category=$Category; Check=$Check; Status=$Status; NumericValue=$Value; Threshold='Synthetic'; Details='Synthetic evidence' }
        }
        function Render-TestReport([object[]]$Rows, [object[]]$Facts = @(), [object]$Forest = $null, [string]$Status = 'Critical') {
            $script:DomainFacts.Clear()
            foreach ($fact in $Facts) { [void]$script:DomainFacts.Add($fact) }
            $before = ConvertTo-Json -InputObject @($Rows) -Depth 5 -Compress
            $html = ConvertTo-ReportHtml -r $Rows -status $Status -started ([datetime]'2026-01-01T00:00:00Z') -ended ([datetime]'2026-01-01T00:01:00Z') -csv 'synthetic.csv' -forestInfo $Forest
            Assert-Report ($html.StartsWith('<!doctype html>') -and $html.TrimEnd().EndsWith('</body></html>')) 'Report is incomplete.'
            Assert-Report ($before -ceq (ConvertTo-Json -InputObject @($Rows) -Depth 5 -Compress)) 'Rendering changed source rows.'
            Assert-Report ($script:DomainFacts.Count -eq $Facts.Count) 'Rendering changed domain facts.'
            $script:Cases++
            $html
        }

        $failed = New-TestRow 'Domain' 'DomainScan' 'Critical'
        $html = Render-TestReport @($failed)
        Assert-Report ($html.Contains('<td>domain.test</td><td>NotMeasured</td>')) 'Missing domain facts became a measured DC count.'
        Assert-Report ($html.Contains("<td>NotMeasured</td><td class='riskNotMeasured'>NotMeasured</td><td class='riskNotMeasured'>NotMeasured</td><td class='riskNotMeasured'>NotMeasured</td>")) 'Missing locked-account or category measurements became healthy values.'

        $fact = [pscustomobject]@{Domain='domain.test'; DCCount=2; GlobalCatalogCount=1}
        $html = Render-TestReport @($failed) @($fact)
        Assert-Report ($html.Contains('<td>domain.test</td><td>2</td>')) 'Known domain controller count was lost.'

        $rows = @(
            (New-TestRow 'DomainStats' 'LockedUserAccounts' 'OK' 'domain.test' '0'),
            (New-TestRow 'FSMO' 'PDCEmulator' 'OK'),
            (New-TestRow 'Replication' 'ReplicationFailures' 'Warning'),
            (New-TestRow 'SYSVOL' 'SYSVOL' 'OK')
        )
        $forest = [pscustomobject]@{Name='forest.test';RootDomain='domain.test';ForestMode='Synthetic';Domains=@('domain.test')}
        $html = Render-TestReport $rows @($fact) $forest 'Warning'
        Assert-Report ($html.Contains("<td>0</td><td class='riskOK'>OK</td><td class='riskWarning'>Warning</td><td class='riskOK'>OK</td>")) 'Measured zero or category severity changed.'

        $html = Render-TestReport @($rows + (New-TestRow 'Domain' 'DomainScan' 'Critical' 'unavailable.test')) @($fact) $forest
        Assert-Report ($html.Contains('<td>unavailable.test</td><td>NotMeasured</td>')) 'Mixed measured/unavailable report lost the unavailable domain.'

        $html = Render-TestReport @((New-TestRow 'Replication' 'ReplicationFailureQuery' 'NotMeasured')) @() $null 'NotMeasured'
        Assert-Report ($html.Contains("<td class='riskNotMeasured'>NotMeasured</td>") -and -not $html.Contains("<td class='riskOK'>OK</td>")) 'Unavailable measurements were rendered healthy.'

        $html = Render-TestReport @((New-TestRow 'Script' 'UnhandledError' 'Critical' ''))
        Assert-Report ($html.Contains('NotAvailable')) 'Error-only report did not show unavailable forest metadata.'

        $html = Render-TestReport @() @() $null 'Critical'
        Assert-Report ($html.Contains('<th>Forest</th><td>NotAvailable</td>')) 'Empty failure report did not render safely.'
        Assert-Report ($html.Contains('No health measurements are available.') -and -not $html.Contains('No critical or warning findings.')) 'Empty failure report implied a healthy scan.'

        $html = Render-TestReport @((New-TestRow 'Domain' 'DomainScan' 'Critical' 'domain<&>.test'))
        Assert-Report ($html.Contains('domain&lt;&amp;&gt;.test') -and -not $html.Contains('domain<&>.test')) 'Domain text was not HTML encoded.'

        $html = Render-TestReport @((New-TestRow 'DomainStats' 'LockedUserAccounts' 'OK' 'domain.test' '0')) @($fact) $forest 'OK'
        Assert-Report ($html.Contains('<tr class="rowOK"><td colspan="8">No critical or warning findings.</td></tr>')) 'Healthy measured report changed its findings contract.'
        Write-Host "PASS: $script:Cases offline AD health report cases. No collector, AD, mail, upload or tenant calls."
    }
}
finally { Remove-Module $module -Force }

