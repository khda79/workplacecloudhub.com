#requires -Version 7.0
[CmdletBinding()]
param([Parameter(Mandatory)][string]$DriveId,[Parameter(Mandatory)][string]$TestParentFolderId,[switch]$AllowSyntheticRemoteWrites)
$ErrorActionPreference='Stop'
if(-not $AllowSyntheticRemoteWrites){throw 'This real SharePoint qualification requires explicit -AllowSyntheticRemoteWrites after approval.'}
Import-Module Microsoft.Graph.Authentication -ErrorAction Stop
if(-not(Get-MgContext)){throw 'Establish the already approved Graph test connection first. This script never changes permissions.'}
Import-Module (Join-Path $PSScriptRoot '../Modules/SmartM365.Core/SmartM365.SharePointJsonTransition.psd1') -Force
$transition=Get-Module SmartM365.SharePointJsonTransition
$root=Join-Path ([IO.Path]::GetTempPath()) ('SmartM365-SharePointProbe-'+[guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory $root|Out-Null
$base='https://graph.microsoft.com/v1.0/drives/'+[uri]::EscapeDataString($DriveId)
$request={
    param($method,$uri,$body,$headers)
    $parameters=@{Method=$method;Uri=$uri;ErrorAction='Stop';OutputType='PSObject'}
    if($headers.Count){$parameters.Headers=$headers}
    if($null -ne $body){$parameters.Body=$body;$parameters.ContentType='application/json'}
    try{return Invoke-MgGraphRequest @parameters}
    catch{
        $original=$_.Exception;$status=$null
        if($original.PSObject.Properties['Response'] -and $original.Response -and $original.Response.PSObject.Properties['StatusCode']){$status=[int]$original.Response.StatusCode}
        elseif($original.PSObject.Properties['StatusCode']){$status=[int]$original.StatusCode}
        if($null -ne $status){$failure=[IO.IOException]::new('Graph qualification HTTP '+$status,$original);$failure.Data['StatusCode']=$status;throw $failure}
        throw
    }
}.GetNewClosure()
$download={param($uri,$path)Invoke-MgGraphRequest -Method GET -Uri $uri -OutputFilePath $path -ErrorAction Stop|Out-Null}
$parent=& $request GET ($base+'/items/'+[uri]::EscapeDataString($TestParentFolderId)) $null @{}
if(-not $parent.PSObject.Properties['folder'] -or $parent.name -cne 'SmartM365-Qualification'){throw 'Parent must be an existing dedicated folder named SmartM365-Qualification.'}
$probeName='JsonTransport-'+[guid]::NewGuid().ToString('N')
$body=@{name=$probeName;folder=@{};'@microsoft.graph.conflictBehavior'='fail'}|ConvertTo-Json
$folder=& $request POST ($base+'/items/'+[uri]::EscapeDataString($TestParentFolderId)+'/children') $body @{}
if(-not $folder.id -or $folder.name -cne $probeName){throw 'Synthetic folder creation not confirmed.'}
$folderItem=& $request GET ($base+'/items/'+[uri]::EscapeDataString([string]$folder.id)) $null @{}
$parentRemote=[string]$folderItem.parentReference.path
if($parentRemote -notmatch '/root:(.*)$'){throw 'Synthetic folder path cannot be resolved; fixture retained.'}
$relative=([uri]::UnescapeDataString($Matches[1]).Trim('/')+'/'+$probeName).Trim('/')
$encoded=($relative.Split('/')|ForEach-Object{[uri]::EscapeDataString($_)}) -join '/'
$local=Join-Path $root 'state.json.txt'
$payload='{"Owner":"SmartM365-Qualification","Generation":2}'
[IO.File]::WriteAllText($local,$payload,[Text.UTF8Encoding]::new($false))
try{
    # Only this just-created folder is mutated. Both versions are synthetic.
    $old=& $request PUT ($base+'/items/'+[uri]::EscapeDataString([string]$folder.id)+':/state.json:/content') '{"Owner":"SmartM365-Qualification","Generation":1}' @{}
    $old=& $request PUT ($base+'/items/'+[uri]::EscapeDataString([string]$old.id)+'/content') $payload @{}
    $oldId=[string]$old.id
    $beforeVersions=& $request GET ($base+'/items/'+[uri]::EscapeDataString($oldId)+'/versions') $null @{}
    if(@($beforeVersions.value).Count -lt 2){throw 'Two synthetic versions are required to qualify history preservation; inspect library versioning without changing its policy.'}
    & $transition {param($id)$script:ProbeDrive=$id;function script:Get-SmartM365JsonTransportPolicy {@{Mode='JsonText';QualifiedSharePointDrives=@($script:ProbeDrive)}}} $DriveId
    $result=Invoke-SmartM365SharePointJsonNameTransition -LocalFilePath $local -DriveId $DriveId -EncodedTargetPath ($encoded+'/state.json.txt') -Request $request -Download $download
    if($result.Item.id -ne $oldId -or $result.Item.name -ne 'state.json.txt'){throw 'Remote rename failed identity check.'}
    $bytes=Receive-SmartM365SharePointJsonBytes -DriveId $DriveId -EncodedTargetPath ($encoded+'/state.json') -Request $request -Download $download
    if([Text.Encoding]::UTF8.GetString($bytes) -cne $payload){throw 'Remote bytes changed.'}
    $null=Invoke-SmartM365SharePointJsonNameTransition -LocalFilePath $local -DriveId $DriveId -EncodedTargetPath ($encoded+'/state.json.txt') -Request $request -Download $download
    # Recreate a second, identical legacy item to test preservation of both histories.
    $duplicate=& $request PUT ($base+'/items/'+[uri]::EscapeDataString([string]$folder.id)+':/state.json:/content') $payload @{}
    $result=Invoke-SmartM365SharePointJsonNameTransition -LocalFilePath $local -DriveId $DriveId -EncodedTargetPath ($encoded+'/state.json.txt') -Request $request -Download $download
    if($result.Item.id -ne $duplicate.id -or $result.Item.name -notmatch '^state\.legacy-[A-F0-9]{16}\.json\.txt$'){throw 'Duplicate history was not preserved.'}
    $versions=& $request GET ($base+'/items/'+[uri]::EscapeDataString($oldId)+'/versions') $null @{}
    $report=[pscustomobject]@{Computer=$env:COMPUTERNAME;DriveId=$DriveId;SyntheticFolderId=$folder.id;SyntheticFolder=$folder.webUrl;OriginalItemId=$oldId;DuplicateItemId=$duplicate.id;VisibleVersionCount=@($versions.value).Count;BytesPreserved=$true;IdsPreserved=$true;PriorVersionsVerified=$true;DeletionPerformed=$false;AutomaticPolicyActivated=$false;LocalJournal=$root}
    $report|Add-Member -NotePropertyName ExpectedSHA256 -NotePropertyValue (Get-FileHash -LiteralPath $local -Algorithm SHA256).Hash
    $report|Export-Csv -LiteralPath (Join-Path $root 'qualification.csv') -NoTypeInformation -Encoding UTF8
    $report
}finally{
    & $transition {Remove-Item Function:script:Get-SmartM365JsonTransportPolicy -ErrorAction SilentlyContinue}
    Write-Host "Synthetic SharePoint folder retained for inspection: $($folder.webUrl)"
    Write-Host "Local evidence retained: $root"
}

