[CmdletBinding()]
param()
$ErrorActionPreference='Stop'
Import-Module (Join-Path $PSScriptRoot '../Modules/SmartM365.Core/SmartM365.JsonTransport.psd1') -Force
$transport=Get-Module SmartM365.JsonTransport
$policy=& $transport { (Get-Command Get-SmartM365JsonTransportPolicy).ScriptBlock }
$tokens=$null;$errors=$null
$ast=[Management.Automation.Language.Parser]::ParseFile((Join-Path $PSScriptRoot '../SmartInventory/ActiveDirectoryInventory/SmartM365-ActiveDirectory-Inventory.ps1'),[ref]$tokens,[ref]$errors)
if($errors.Count){throw ($errors|Out-String)}
foreach($name in @('Save-WeeklyInventoryHistory','Publish-WeeklyInventoryHistoryToSharePoint')) {
    $definition=$ast.Find({param($node) $node -is [Management.Automation.Language.FunctionDefinitionAst] -and $node.Name -eq $name},$true)
    . ([scriptblock]::Create($definition.Extent.Text))
}
function WriteLog { param($Message,$Level) }
function Copy-SmartM365FileAtomically { param($SourcePath,$DestinationPath) Copy-Item -LiteralPath $SourcePath -Destination $DestinationPath }
function Invoke-SmartM365SharePointCsvUpload { param($LocalFilePath) $script:uploads += $LocalFilePath; if(!$script:failUpload){[pscustomobject]@{Path=$LocalFilePath}} }
$root=Join-Path ([IO.Path]::GetTempPath()) ('SmartM365-JsonAD-' + [guid]::NewGuid().ToString('N'))
$OutputPath=Join-Path $root 'AD'
$history=Join-Path $OutputPath 'WeeklyHistory'
$null=New-Item -ItemType Directory $OutputPath -Force
$source=Join-Path $OutputPath 'AD_Users_AllDomains.csv'
[IO.File]::WriteAllText($source,"Id`r`n42`r`n")
$script:passed=0;$script:uploads=@();$script:failUpload=$false
function Check([bool]$Value,[string]$Message){if(!$Value){throw $Message};$script:passed++}
function Reject([scriptblock]$Action,[string]$Message){$failed=$false;try{& $Action|Out-Null}catch{$failed=$true};Check $failed $Message}
try {
    $global:EnableSharePointUpload=$false
    & $transport { function script:Get-SmartM365JsonTransportPolicy { @{Mode='Readers';QualifiedUncRoots=@();QualifiedLocalDataRoots=@()} } }
    Save-WeeklyInventoryHistory -SourceFiles $source -RequiredSourceFiles $source -HistoryRootPath $history -RetentionWeeks 0
    $legacy=(Get-ChildItem $history -Recurse -Filter manifest.json -File).FullName
    $hash=(Get-FileHash $legacy).Hash
    & $transport { function script:Get-SmartM365JsonTransportPolicy { @{Mode='JsonText';QualifiedUncRoots=@();QualifiedLocalDataRoots=@()} } }
    Save-WeeklyInventoryHistory -SourceFiles $source -RequiredSourceFiles $source -HistoryRootPath $history -RetentionWeeks 0
    Check ((Get-FileHash "$legacy.txt").Hash -eq $hash) 'AD conversion changed historical bytes.'
    Check (!(Test-Path $legacy)) 'AD conversion left legacy file.'
    Save-WeeklyInventoryHistory -SourceFiles $source -RequiredSourceFiles $source -HistoryRootPath $history -RetentionWeeks 0
    Check ((Get-FileHash "$legacy.txt").Hash -eq $hash) 'AD retry recalculated history.'
    $global:EnableSharePointUpload=$true;$script:failUpload=$true
    Reject { Save-WeeklyInventoryHistory -SourceFiles $source -RequiredSourceFiles $source -HistoryRootPath $history -RetentionWeeks 1 } 'AD migration upload failure was ignored.'
    Check ((Get-FileHash "$legacy.txt").Hash -eq $hash) 'Failed upload changed historical content.'
    Copy-Item "$legacy.txt" $legacy
    [IO.File]::WriteAllText("$legacy.txt",'{')
    Reject { Save-WeeklyInventoryHistory -SourceFiles $source -RequiredSourceFiles $source -HistoryRootPath $history -RetentionWeeks 0 } 'Invalid AD preferred manifest was rebuilt.'
    Check ((Get-FileHash $legacy).Hash -eq $hash) 'Invalid AD preferred manifest destroyed valid legacy.'
    # A relocated workspace keeps tenant-relative AD history; another tenant identity is still refused.
    $global:EnableSharePointUpload=$false;$script:failUpload=$false
    $OutputPath=Join-Path $root 'old-share\Tenants\fixture\DATA-ALL\ActiveDirectory\Inventory'
    $null=New-Item -ItemType Directory $OutputPath -Force
    $movedSource=Join-Path $OutputPath 'AD_Users_AllDomains.csv'
    [IO.File]::WriteAllText($movedSource,"Id`r`n42`r`n")
    Save-WeeklyInventoryHistory -SourceFiles $movedSource -RequiredSourceFiles $movedSource -HistoryRootPath (Join-Path $OutputPath 'WeeklyHistory') -RetentionWeeks 0
    $newOutput=Join-Path $root 'new-share\Tenants\fixture\DATA-ALL\ActiveDirectory\Inventory'
    $null=New-Item -ItemType Directory (Split-Path $newOutput -Parent) -Force
    Copy-Item -LiteralPath $OutputPath -Destination $newOutput -Recurse
    $OutputPath=$newOutput
    $movedSource=Join-Path $OutputPath 'AD_Users_AllDomains.csv'
    $movedManifest=(Get-ChildItem (Join-Path $OutputPath 'WeeklyHistory') -Recurse -Filter manifest.json.txt -File).FullName
    $movedHash=(Get-FileHash $movedManifest).Hash
    Save-WeeklyInventoryHistory -SourceFiles $movedSource -RequiredSourceFiles $movedSource -HistoryRootPath (Join-Path $OutputPath 'WeeklyHistory') -RetentionWeeks 0
    Check ((Get-FileHash $movedManifest).Hash -eq $movedHash) 'Relocated AD history was rewritten.'
    $foreignOutput=Join-Path $root 'other-share\Tenants\other\DATA-ALL\ActiveDirectory\Inventory'
    $null=New-Item -ItemType Directory (Split-Path $foreignOutput -Parent) -Force
    Copy-Item -LiteralPath $OutputPath -Destination $foreignOutput -Recurse
    $OutputPath=$foreignOutput
    $foreignSource=Join-Path $OutputPath 'AD_Users_AllDomains.csv'
    Reject { Save-WeeklyInventoryHistory -SourceFiles $foreignSource -RequiredSourceFiles $foreignSource -HistoryRootPath (Join-Path $OutputPath 'WeeklyHistory') -RetentionWeeks 0 } 'Foreign tenant AD history was accepted.'
    [pscustomobject]@{Passed=$script:passed;FixtureRoot=$root;Evidence='Synthetic AD history functions; uploads mocked'}
} finally { & $transport { param($original) Set-Item Function:script:Get-SmartM365JsonTransportPolicy -Value $original } $policy }

