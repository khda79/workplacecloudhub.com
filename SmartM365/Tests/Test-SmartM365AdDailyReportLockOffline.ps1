# Synthetic tests for daily report completion; no AD, tenant, mail or SharePoint access.
$ErrorActionPreference = 'Stop'
$producer = Join-Path $PSScriptRoot '../SmartInventory/ActiveDirectoryInventory/SmartM365-ActiveDirectory-Inventory.ps1'
$tokens = $null; $errors = $null
$ast = [Management.Automation.Language.Parser]::ParseFile((Resolve-Path $producer), [ref]$tokens, [ref]$errors)
if ($errors.Count) { throw ($errors.Message -join '; ') }
$function = $ast.Find({ param($node) $node -is [Management.Automation.Language.FunctionDefinitionAst] -and $node.Name -eq 'Invoke-ActiveDirectoryDailyReport' }, $true)
if (-not $function) { throw 'Daily report function not found.' }
. ([scriptblock]::Create($function.Extent.Text))
$SkipDailyReport = $false; $EnableDailyReport = $true
function WriteLog { param($Message, $Level) }
function Get-InventoryDailyReportSource { param($SourceFolder, $AllowedOS, $TargetDomains) return $script:source }
function Write-DailyReportCsv {
    param($Rows, $OutputFilePath, $LatestFolderPath)
    $script:writes++
    if (-not ($script:omitComputer -and $OutputFilePath -like '*Computers*')) { Set-Content -LiteralPath $OutputFilePath -Value 'synthetic' }
}
$root = Join-Path ([IO.Path]::GetTempPath()) ('SmartM365-AdDaily-' + [guid]::NewGuid().ToString('N'))
try {
    New-Item -ItemType Directory -Path $root | Out-Null
    $computer = [pscustomobject]@{ADDomain='example.test';Enabled=$true;SimpleOS='Windows 11'}
    $user = [pscustomobject]@{ADDomain='example.test';Enabled=$true;LastLogonDate=Get-Date}
    foreach ($scenario in @('NoComputers','NoUsers','MissingOutput','Complete','ExistingLock')) {
        $dir = Join-Path $root $scenario; $locks = Join-Path $dir 'locks'
        New-Item -ItemType Directory -Path $dir, $locks | Out-Null
        $lock = Join-Path $locks ('daily-SUCCESS-{0}.lock' -f (Get-Date -Format 'yyyy-MM-dd'))
        $script:source = [pscustomobject]@{Computers=@($computer);Users=@($user)}
        $script:writes=0; $script:omitComputer=$false
        switch ($scenario) {
            'NoComputers' { $script:source.Computers=@(); Set-Content (Join-Path $dir 'AD_Computers_DailyStats.csv') 'old' }
            'NoUsers' { $script:source.Users=@() }
            'MissingOutput' { $script:omitComputer=$true }
            'ExistingLock' { New-Item -ItemType File -Path $lock | Out-Null }
        }
        $result=Invoke-ActiveDirectoryDailyReport -SourceFolder $dir -ReportOutputPath $dir -LockRoot $locks -LockName 'daily'
        if ($scenario -eq 'Complete') {
            if (-not $result -or -not (Test-Path $lock) -or $script:writes -ne 2) { throw 'Complete reports must write both files and a success lock.' }
        } elseif ($scenario -eq 'ExistingLock') {
            if ($result -or $script:writes -ne 0) { throw 'Existing success lock must suppress another append.' }
        } else {
            if ($result -or (Test-Path $lock)) { throw "$scenario must not create a success lock." }
            if ($scenario -in @('NoComputers','NoUsers') -and $script:writes -ne 0) { throw "$scenario must not partially append the other daily report." }
        }
    }
    'PASS: AD daily report lock scenarios.'
} finally {
    if (Test-Path -LiteralPath $root) { Remove-Item -LiteralPath $root -Recurse -Force }
}

