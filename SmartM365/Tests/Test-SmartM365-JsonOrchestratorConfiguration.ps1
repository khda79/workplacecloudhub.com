#requires -Version 7.0
[CmdletBinding()]
param()
$ErrorActionPreference='Stop'
$orchestrator=Join-Path $PSScriptRoot '../SmartInventory/Orchestrator'
Import-Module (Join-Path $orchestrator 'SmartM365.Orchestrator.Management.psm1') -Force
$transport=Get-Module SmartM365.JsonTransport
$management=Get-Module SmartM365.Orchestrator.Management
$policy=& $transport { (Get-Command Get-SmartM365JsonTransportPolicy).ScriptBlock }
$root=Join-Path ([IO.Path]::GetTempPath()) ('SmartM365-JsonOrchConfig-' + [guid]::NewGuid().ToString('N'))
$null=New-Item -ItemType Directory $root
$script:passed=0
function Check([bool]$Value,[string]$Message){if(!$Value){throw $Message};$script:passed++}
function Reject([scriptblock]$Action,[string]$Message){$failed=$false;try{& $Action|Out-Null}catch{$failed=$true};Check $failed $Message}
try {
    & $transport { function script:Get-SmartM365JsonTransportPolicy { @{Mode='Readers';QualifiedUncRoots=@()} } }
    $cluster=Get-Content (Join-Path $orchestrator 'Orchestrator-Cluster.json.template') -Raw|ConvertFrom-Json
    $snapshot=Initialize-SmartM365OrchestratorCentralConfiguration -SharedDataFolderPath $root -BootstrapJobsPath (Join-Path $orchestrator 'Orchestrator-Jobs.json.template') -BootstrapClusterDocument $cluster
    $oldJobs=$snapshot.Paths.JobsPath;$oldCluster=$snapshot.Paths.ClusterPath
    $version=Join-Path $snapshot.Paths.VersionsFolderPath '20260927T120000000Z_12345678'
    $null=New-Item -ItemType Directory $version -Force
    $historical=Join-Path $version 'Orchestrator-Jobs.before.json'
    Copy-Item $oldJobs $historical
    $historyHash=(Get-FileHash $historical).Hash
    & $transport { function script:Get-SmartM365JsonTransportPolicy { @{Mode='JsonText';QualifiedUncRoots=@()} } }
    & $management { function script:Get-SmartM365JsonTransportPolicy { @{Mode='JsonText';QualifiedUncRoots=@()} } }
    $current=Get-SmartM365OrchestratorConfigurationSnapshot $root
    Check ($current.JobsHash -eq $snapshot.JobsHash -and $current.ClusterHash -eq $snapshot.ClusterHash) 'Configuration migration changed content.'
    Check ($current.Paths.JobsPath.EndsWith('.json.txt') -and !(Test-Path $oldJobs) -and !(Test-Path $oldCluster)) 'Configuration paths did not migrate.'
    Check ((Get-FileHash "$historical.txt").Hash -eq $historyHash -and !(Test-Path $historical)) 'Historical version bytes changed.'
    $request=Request-SmartM365OrchestratorRebalance -SharedDataFolderPath $root -Reason 'Synthetic'
    Check ($request.RequestPath.EndsWith('.json.txt')) 'New rebalance request uses legacy extension.'
    Check ((Read-SmartM365OrchestratorJson $request.RequestPath).RequestId -eq $request.RequestId) 'Rebalance request ID lost.'
    $newJobs=$current.Jobs|ConvertTo-Json -Depth 100|ConvertFrom-Json -Depth 100
    $newJobs.Jobs[0].Enabled = -not [bool]$newJobs.Jobs[0].Enabled
    $published=Publish-SmartM365OrchestratorConfiguration -SharedDataFolderPath $root -JobsDocument $newJobs -ClusterDocument $current.Cluster -ExpectedJobsHash $current.JobsHash -ExpectedClusterHash $current.ClusterHash -ChangeSummary 'Synthetic JSON transition'
    Check (@(Get-ChildItem $published.VersionFolderPath -File -Filter '*.json').Count -eq 0) 'New configuration snapshots use legacy extension.'
    Check ((Get-FileHash (Join-Path $published.VersionFolderPath 'Orchestrator-Jobs.before.json.txt')).Hash -eq $current.JobsHash) 'Before version did not preserve exact bytes.'
    Copy-Item $current.Paths.JobsPath $oldJobs
    $validHash=(Get-FileHash $oldJobs).Hash
    [IO.File]::WriteAllText($current.Paths.JobsPath,'{')
    Reject {Get-SmartM365OrchestratorConfigurationSnapshot $root} 'Invalid preferred configuration fell back.'
    Check ((Get-FileHash $oldJobs).Hash -eq $validHash) 'Failed read modified legacy configuration.'
    [pscustomobject]@{Passed=$script:passed;FixtureRoot=$root;Evidence='Synthetic configuration, history and rebalance; no resident orchestrator'}
} finally {
    & $management { Remove-Item Function:script:Get-SmartM365JsonTransportPolicy -ErrorAction SilentlyContinue }
    & $transport {param($original) Set-Item Function:script:Get-SmartM365JsonTransportPolicy -Value $original} $policy
}

