$partial=Join-Path $root 'Intune_DiscoveredApps_AppDeviceRelations_20260927_120000.partial.csv'
$timestamped=Join-Path $root 'Intune_DiscoveredApps_AppDeviceRelations_20260927_120000.csv'
[IO.File]::WriteAllText($partial,"AppId,DeviceId`r`napp1,device1`r`n")
