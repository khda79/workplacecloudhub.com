<#
.SYNOPSIS
Tests large-file upload range arithmetic without network calls or large files.
#>
[CmdletBinding()]
param(
    [string]$ModulePath
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
if (-not $ModulePath) { $ModulePath = Join-Path $PSScriptRoot '../Modules/SmartM365.Core/SmartM365.Core.psm1' }
$script:checks = 0
function Check([bool]$Condition, [string]$Message) {
    if (-not $Condition) { throw $Message }
    $script:checks++
}

# Execute only arithmetic statements extracted from the production function.
# Do not import the module, open an upload session or invoke the uploader.
$parseErrors = $null
$ast = [Management.Automation.Language.Parser]::ParseFile($modulePath, [ref]$null, [ref]$parseErrors)
Check ($parseErrors.Count -eq 0) 'Core module contains syntax errors.'
$function = $ast.Find({ param($node)
    $node -is [Management.Automation.Language.FunctionDefinitionAst] -and
    $node.Name -eq 'Invoke-SmartM365SharePointLargeFileUpload'
}, $true)
Check ($null -ne $function) 'Large-file upload function was not found.'
$statements = @{}
foreach ($variable in @('remaining', 'readSize', 'rangeEnd', 'offset')) {
    $assignments = @($function.FindAll({ param($node)
        $node -is [Management.Automation.Language.AssignmentStatementAst] -and
        $node.Left -is [Management.Automation.Language.VariableExpressionAst] -and
        $node.Left.VariablePath.UserPath -eq $variable -and
        ($variable -ne 'offset' -or $node.Operator.ToString() -eq 'PlusEquals')
    }, $true))
    Check ($assignments.Count -eq 1) "Expected one production arithmetic statement for $variable."
    $statements[$variable] = [scriptblock]::Create($assignments[0].Extent.Text)
}

$chunkSizeBytes = [int]10485760
$remaining = [int64]2595017609
$legacyFailed = $false
try { $null = [int][math]::Min($chunkSizeBytes, $remaining) }
catch { $legacyFailed = $true }
Check $legacyFailed 'The legacy expression did not reproduce the Int32 overload regression.'

$sizes = @(
    [int64]0, [int64]1, [int64]($chunkSizeBytes - 1), [int64]$chunkSizeBytes,
    [int64]($chunkSizeBytes + 1), ([int64][int]::MaxValue - 1),
    [int64][int]::MaxValue, ([int64][int]::MaxValue + 1),
    [int64]2595017609, ([int64]5 * 1024 * 1024 * 1024 + 17)
)
foreach ($size in $sizes) {
    $fileSize = [int64]$size
    $offset = [int64]0
    $chunks = 0
    $lastRead = 0
    while ($offset -lt $fileSize) {
        . $statements['remaining']
        . $statements['readSize']
        $expectedRead = if (($fileSize - $offset) -gt $chunkSizeBytes) { $chunkSizeBytes } else { [int]($fileSize - $offset) }
        Check ($readSize -is [int] -and $readSize -eq $expectedRead) "Invalid buffer read size for $size at $offset."
        Check ($readSize -gt 0 -and $readSize -le $chunkSizeBytes) 'Read size is outside the buffer bounds.'
        $bytesRead = $readSize
        . $statements['rangeEnd']
        Check ($rangeEnd -eq ($offset + [int64]$readSize - 1) -and $rangeEnd -lt $fileSize) 'Invalid inclusive range end.'
        if ($rangeEnd -lt ($fileSize - 1)) {
            Check (($readSize % 327680) -eq 0) 'A non-final chunk is not aligned.'
        }
        . $statements['offset']
        Check ($offset -is [int64] -and $offset -eq ($rangeEnd + 1)) 'Offsets contain a gap, overlap or narrowing conversion.'
        $lastRead = $readSize
        $chunks++
    }
    $expectedChunks = [int][math]::Ceiling($fileSize / [double]$chunkSizeBytes)
    Check ($offset -eq $fileSize -and $chunks -eq $expectedChunks) "Incomplete range coverage for $size."
    if ($fileSize -gt 0) {
        $expectedTail = $fileSize % $chunkSizeBytes
        if ($expectedTail -eq 0) { $expectedTail = $chunkSizeBytes }
        Check ($lastRead -eq $expectedTail) 'Final partial chunk is incorrect.'
    }
}

# Exercise a short stream read and a final one-byte range beyond Int32 offsets.
$fileSize = [int64]2595017609
$offset = [int64]2147483648
. $statements['remaining']
. $statements['readSize']
$stream = [IO.MemoryStream]::new([byte[]](1, 2, 3))
try {
    $buffer = New-Object byte[] $readSize
    $bytesRead = $stream.Read($buffer, 0, $readSize)
    . $statements['rangeEnd']
    . $statements['offset']
    Check ($bytesRead -eq 3 -and $rangeEnd -eq 2147483650 -and $offset -eq 2147483651) 'Range advancement ignored actual bytes read.'
} finally { $stream.Dispose() }
$fileSize = [int64]2595017609
$offset = $fileSize - 1
. $statements['remaining']
. $statements['readSize']
$bytesRead = $readSize
. $statements['rangeEnd']
$range = 'bytes {0}-{1}/{2}' -f $offset, $rangeEnd, $fileSize
Check ($range -ceq 'bytes 2595017608-2595017608/2595017609') 'Final Content-Range lost Int64 precision.'

[pscustomobject]@{
    Passed = $script:checks
    FileSizesTested = $sizes.Count
    Evidence = 'Production arithmetic only; no network, collectors, preparation or disk fixtures.'
}

