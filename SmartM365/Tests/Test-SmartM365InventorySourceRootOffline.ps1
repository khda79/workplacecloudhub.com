$ErrorActionPreference='Stop'
$source=Join-Path $PSScriptRoot '../SmartInventory/Orchestrator/SmartM365.Inventory.Launch.psm1'
$t=$null;$e=$null;$ast=[Management.Automation.Language.Parser]::ParseFile((Resolve-Path $source),[ref]$t,[ref]$e)
if($e.Count){throw ($e.Message -join '; ')}
foreach($name in @('Invoke-SmartM365InventoryLaunch','Invoke-SmartM365InventoryOrchestratedLaunch')){
 $def=$ast.Find({param($n)$n -is [Management.Automation.Language.FunctionDefinitionAst] -and $n.Name -eq $name},$true)
 if(-not $def){throw "Missing $name"}; . ([scriptblock]::Create($def.Extent.Text))
}
function Initialize-SmartM365InventoryLaunch {param($Plan,$Catalog,$CacheBaseCandidates,[switch]$Orchestrated) [pscustomobject]@{EnginePath=(Get-Process -Id $PID).Path;Arguments=@('-NoProfile','-Command','Write-Output $env:SMARTM365_SOURCE_REPOSITORY_ROOT');WorkingDirectory=''}}
function Invoke-SmartM365InventoryProcess {param($FilePath,$Arguments,$WorkingDirectory) if($env:SMARTM365_SOURCE_REPOSITORY_ROOT -ne $expected){throw 'Normal child did not inherit repository root.'};0}
function Get-SmartM365InventoryCatalog {param($SmartInventoryRoot) $catalog}
function Resolve-SmartM365InventoryLaunch {param($Catalog,$Name,$Tenant,$ExecutionMode,$ExecutionModeSource,$JobArguments,[switch]$NoAutoConnect) $plan}
function Write-SmartM365InventoryLaunchMessage {param($Level,$Message)}
$expected=Split-Path -Parent ([IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..')))
$catalog=[pscustomobject]@{SmartM365Root=(Join-Path $expected 'SmartM365')}
$plan=[pscustomobject]@{Detached=$false;Name='synthetic';Runtime='PowerShell7';ScriptPath='synthetic'}
$old=$env:SMARTM365_SOURCE_REPOSITORY_ROOT;$env:SMARTM365_SOURCE_REPOSITORY_ROOT='before-test'
$log=Join-Path ([IO.Path]::GetTempPath()) ('si-source-root-'+[guid]::NewGuid().ToString('N')+'.log')
try {
 if((Invoke-SmartM365InventoryLaunch -Plan $plan -Catalog $catalog) -ne 0 -or $env:SMARTM365_SOURCE_REPOSITORY_ROOT -ne 'before-test'){throw 'Normal launcher did not restore environment.'}
 if((Invoke-SmartM365InventoryOrchestratedLaunch -SmartInventoryRoot 'synthetic' -Name 'synthetic' -Tenant 'test' -LogPath $log) -ne 0 -or $env:SMARTM365_SOURCE_REPOSITORY_ROOT -ne 'before-test'){throw 'Orchestrated launcher did not restore environment.'}
 if((Get-Content -Raw $log).Trim() -ne $expected){throw 'Orchestrated child did not inherit repository root.'}
 'Launcher source repository inheritance and restoration passed.'
}finally{$env:SMARTM365_SOURCE_REPOSITORY_ROOT=$old;Remove-Item -LiteralPath $log -Force -ErrorAction SilentlyContinue}

