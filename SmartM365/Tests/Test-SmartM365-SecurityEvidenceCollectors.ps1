<#
.SYNOPSIS
Runs offline contract tests for the three new Microsoft 365 security evidence collectors.
.VERSION
1.0.3
#>
[CmdletBinding()]param()
$ErrorActionPreference='Stop'
# Collector functions call exported Core helpers (Graph error classification, export download), as in production.
Import-Module (Join-Path (Split-Path $PSScriptRoot -Parent) 'Modules/SmartM365.Core/SmartM365.Core.psd1') -MinimumVersion '1.0.99' -Force -Global -WarningAction SilentlyContinue
$scripts=@(
    'SmartInventory\M365Inventory\Security\SecureScore\SmartM365-SecureScore-Inventory.ps1',
    'SmartInventory\M365Inventory\Security\AuthenticationMethods\SmartM365-AuthenticationMethodsRegistration-Inventory.ps1',
    'SmartInventory\M365Inventory\Security\ConditionalAccess\SmartM365-ConditionalAccess-Inventory.ps1'
)
$root=Split-Path $PSScriptRoot -Parent
foreach($relative in $scripts){$output=& (Join-Path $root $relative) -SelfTest;if([string]$output-notmatch'PASS'){throw "Offline collector test failed: $relative"};Write-Output $output}

$modulePath=Join-Path $root 'SmartInventory\Common\SmartM365.EvidenceCollector.Common.psd1'
Import-Module $modulePath -MinimumVersion '1.0.0' -Force
$script:page=0
$paged=Get-SmartM365EvidenceGraphCollection -Uri 'https://example.invalid/page1' -Invoker {
    param($Method,$Uri,$Body)
    $script:page++
    if($script:page-eq 1){return [pscustomobject]@{value=@([pscustomobject]@{id='1'});'@odata.nextLink'='https://example.invalid/page2'}}
    return [pscustomobject]@{value=@([pscustomobject]@{id='2'})}
}
if(@($paged).Count-ne 2-or $paged[1].id-ne'2'){throw 'Graph pagination simulation failed.'}
$empty=Get-SmartM365EvidenceGraphCollection -Uri 'https://example.invalid/empty' -Invoker { [pscustomobject]@{value=@()} }
if(@($empty).Count-ne 0){throw 'Empty Graph collection simulation failed.'}
$script:retry=0
$retryResult=Invoke-SmartM365EvidenceGraphRequest -Uri 'https://example.invalid/retry' -MaxRetryCount 2 -NoSleep -Invoker {
    $script:retry++
    if($script:retry-eq 1){throw [System.Exception]::new('HTTP 429 throttled')}
    return [pscustomobject]@{ok=$true}
}
if($script:retry-ne 2-or -not $retryResult.ok){throw 'Graph 429 retry simulation failed.'}
$symbolicThrottleMessage='Too many retries performed. More than 3 retries encountered while sending the request. (HTTP request failed with status code: TooManyRequests.{"error":{"code":"TooManyRequests"}})'
$symbolicThrottleStatus=0
try{throw [System.Exception]::new($symbolicThrottleMessage)}catch{$symbolicThrottleStatus=Get-SmartM365EvidenceStatusCode $_}
if($symbolicThrottleStatus-ne 429){throw "Graph symbolic TooManyRequests classification failed: $symbolicThrottleStatus"}
$script:symbolicRetry=0
$symbolicRetryResult=Invoke-SmartM365EvidenceGraphRequest -Uri 'https://example.invalid/symbolic-retry' -MaxRetryCount 2 -NoSleep -Invoker {
    $script:symbolicRetry++
    if($script:symbolicRetry-eq 1){throw [System.Exception]::new($symbolicThrottleMessage)}
    return [pscustomobject]@{ok=$true}
}
if($script:symbolicRetry-ne 2-or -not $symbolicRetryResult.ok){throw 'Graph symbolic TooManyRequests retry simulation failed.'}
$symbolicUnavailableMessage='Too many retries performed. More than 3 retries encountered while sending the request. (HTTP request failed with status code: ServiceUnavailable.{"error":{"code":"ServiceUnavailable"}})'
$symbolicUnavailableStatus=0
try{throw [System.Exception]::new($symbolicUnavailableMessage)}catch{$symbolicUnavailableStatus=Get-SmartM365EvidenceStatusCode $_}
if($symbolicUnavailableStatus-ne 503){throw "Graph symbolic ServiceUnavailable classification failed: $symbolicUnavailableStatus"}
$script:unavailableRetry=0
$unavailableResult=Invoke-SmartM365EvidenceGraphRequest -Uri 'https://example.invalid/unavailable' -MaxRetryCount 2 -NoSleep -Invoker {
    $script:unavailableRetry++
    if($script:unavailableRetry-eq 1){throw [System.Exception]::new($symbolicUnavailableMessage)}
    return [pscustomobject]@{ok=$true}
}
if($script:unavailableRetry-ne 2-or -not $unavailableResult.ok){throw 'Graph symbolic ServiceUnavailable retry simulation failed.'}
$retryHeaderSeconds=& (Get-Module SmartM365.EvidenceCollector.Common) {
    $exception=[System.Exception]::new('HTTP 503')
    $exception | Add-Member -NotePropertyName ResponseHeaders -NotePropertyValue @{'Retry-After'='17'}
    try{throw $exception}catch{Get-SmartM365EvidenceRetryAfterSeconds $_}
}
if($retryHeaderSeconds-ne 17){throw 'Graph Retry-After header parsing failed.'}
$script:terminalAttempts=0
try{
    Invoke-SmartM365EvidenceGraphRequest -Uri 'https://example.invalid/unavailable-terminal' -MaxRetryCount 2 -NoSleep -Invoker {
        $script:terminalAttempts++
        throw [System.Exception]::new($symbolicUnavailableMessage)
    } | Out-Null
    throw 'Expected terminal ServiceUnavailable failure.'
}catch{if($_.Exception.Message-ne $symbolicUnavailableMessage){throw}}
if($script:terminalAttempts-ne 2){throw 'Graph ServiceUnavailable retries were not bounded.'}
$accessDenied=$false
try{Invoke-SmartM365EvidenceGraphRequest -Uri 'https://example.invalid/denied' -NoSleep -Invoker {throw [System.Exception]::new('HTTP 403 forbidden')}|Out-Null}catch{$accessDenied=$true}
if(-not $accessDenied){throw 'Graph 403 terminal-error simulation failed.'}
Write-Output 'PASS: pagination, empty, numeric and symbolic throttling, ServiceUnavailable, Retry-After, bounded retries, and access-denied simulations'

