#Requires -Version 5.1
<#
.SYNOPSIS
One offline acceptance run for the Exchange A/B/C closure, on both PowerShell engines.
.DESCRIPTION
Executes only synthetic test scripts in child hosts. Never launches a collector,
Exchange connection, task, runner, tenant initialization or server command.
.VERSION
1.0.1
#>
[CmdletBinding()]
param(
    [string]$ReportDirectory = (Join-Path ([IO.Path]::GetTempPath()) ('ExchangeClosure-' + [guid]::NewGuid().ToString('N')))
)
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$smartRoot = Split-Path $PSScriptRoot -Parent
$hosts = @(
    (Join-Path $env:SystemRoot 'System32/WindowsPowerShell/v1.0/powershell.exe'),
    (Get-Command pwsh.exe -ErrorAction Stop).Source
)
foreach ($hostPath in $hosts) {
    if (-not (Test-Path -LiteralPath $hostPath -PathType Leaf)) { throw "Required offline host unavailable: $hostPath" }
}
$tests = @(
    'Tests/Test-SmartM365ExchangeOnPremSessionOffline.ps1',
    'Tests/Test-SmartM365ExchangeOnPremRemoteObjectsOffline.ps1',
    'Tests/Test-SmartM365ExchangeCalendarBackendOffline.ps1',
    'Tests/Test-SmartM365ExchangeCertificatesOffline.ps1',
    'Tests/Test-SmartM365ExchangeHealthCheckerOffline.ps1',
    'Tests/Test-SmartM365CmdbProducerReceipts.ps1',
    'Tests/Test-SmartM365SourceReceiptsOffline.ps1',
    'Tests/Test-SmartM365SourceReceiptReadersOffline.ps1',
    'Tests/Test-SmartM365InventoryLifecycleOffline.ps1',
    'Tests/Test-SmartM365InventoryLaunchOffline.ps1',
    'Tests/Test-SmartM365-JsonWeeklyHistory.ps1',
    'Tests/Test-SmartM365NonGraphCollectorsOffline.ps1',
    'SmartInventory/ExchangeInventory/OnPremises/Mailboxes/Tests/Test-SmartM365-Exchange-MailHtmlRegression.ps1'
)
foreach ($test in $tests) {
    if (-not (Test-Path -LiteralPath (Join-Path $smartRoot $test) -PathType Leaf)) { throw "Missing offline suite: $test" }
}
$null = New-Item -ItemType Directory -Path $ReportDirectory -Force
$results = New-Object 'System.Collections.Generic.List[object]'
foreach ($hostPath in $hosts) {
    $engine = [IO.Path]::GetFileNameWithoutExtension($hostPath)
    foreach ($test in $tests) {
        # This existing reader suite also parses Licensing, whose runtime requires PS7.
        # It is executed on pwsh below, not reported as a PS5.1 pass.
        if ($engine -eq 'powershell' -and $test -eq 'Tests/Test-SmartM365SourceReceiptReadersOffline.ps1') { continue }
        $log = Join-Path $ReportDirectory ($engine + '-' + [IO.Path]::GetFileNameWithoutExtension($test) + '.log')
        $timer = [Diagnostics.Stopwatch]::StartNew()
        & $hostPath -NoProfile -ExecutionPolicy Bypass -File (Join-Path $smartRoot $test) *> $log
        $code = $LASTEXITCODE
        $timer.Stop()
        $results.Add([pscustomobject]@{Engine=$engine;Test=$test;Passed=($code -eq 0);ExitCode=$code;Seconds=$timer.Elapsed.TotalSeconds;Log=$log})
        Write-Output ("{0}: {1}: {2}" -f $engine, $(if ($code -eq 0) {'PASS'} else {'FAIL'}), $test)
        $results | ConvertTo-Json -Depth 4 | Set-Content -LiteralPath (Join-Path $ReportDirectory 'results.json') -Encoding UTF8
    }
}
$failed = @($results | Where-Object {-not $_.Passed})
Write-Output ("Offline acceptance: {0}/{1} passed. Evidence: {2}" -f ($results.Count - $failed.Count), $results.Count, $ReportDirectory)
if ($failed.Count) { exit 1 }

