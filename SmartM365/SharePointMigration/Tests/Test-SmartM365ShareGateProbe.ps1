<#
.SYNOPSIS
    Offline Windows PowerShell 5.1 probe contract test with a fake ShareGate module.
.VERSION
    1.0.2
#>
#Requires -Version 5.1
[CmdletBinding()]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$testsRoot = (Resolve-Path -LiteralPath $PSScriptRoot).Path
$root = Join-Path $testsRoot ('.probe-test-' + [guid]::NewGuid().ToString('N'))
if (-not $root.StartsWith($testsRoot + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) { throw 'Unsafe test path.' }
$oldModulePath = $env:PSModulePath
try {
    $moduleDir = Join-Path $root 'Modules\ShareGate'
    $analysis = Join-Path $root 'Project\ShareGate\Diagnostics\Analysis'
    New-Item -ItemType Directory -Path $moduleDir,$analysis -Force | Out-Null
    @'
@{ RootModule='ShareGate.psm1'; ModuleVersion='99.0.0'; GUID='05b6f370-c0de-4c9a-a90a-42b99e26dfee'; FunctionsToExport=@('Find-CopySessions','Export-Report','Connect-Site','Get-List','Copy-Content','New-CopySettings','Wait-ImportCompletion','Get-UserAndGroupMapping') }
'@ | Set-Content -LiteralPath (Join-Path $moduleDir 'ShareGate.psd1') -Encoding UTF8
    @'
function Find-CopySessions { [CmdletBinding()] param([datetime]$From,[datetime]$To) if (-not $env:SPMIG_TEST_EMPTY_SESSIONS) { [pscustomobject]@{ SessionId='260930-6'; Result='Success' } } }
function Export-Report { [CmdletBinding()] param([string]$SessionId,[string]$Path) throw 'Must not be invoked' }
function Connect-Site { [CmdletBinding()] param([string]$Url,[switch]$Browser,[switch]$ModernAuth) if ($Url -match 'target' -and -not $Browser) { throw 'Destination must use Browser' }; if ($Url -match 'source' -and $env:SPMIG_TEST_SOURCE_FORBIDDEN) { throw 'Source must not be called' }; if ($Url -match 'denied') { throw 'Access denied' }; [pscustomobject]@{ Url=$Url } }
function Get-List { [CmdletBinding()] param($Site,[string[]]$Name) [pscustomobject]@{ Title=$Name[0] } }
function Copy-Content { [CmdletBinding()] param() throw 'Copy must not be invoked' }
function New-CopySettings { [CmdletBinding()] param() throw 'Copy settings must not be invoked' }
function Wait-ImportCompletion { [CmdletBinding()] param() throw 'Import wait must not be invoked' }
function Get-UserAndGroupMapping { [CmdletBinding()] param() throw 'Mapping must not be invoked' }
Export-ModuleMember -Function *
'@ | Set-Content -LiteralPath (Join-Path $moduleDir 'ShareGate.psm1') -Encoding UTF8
    @'
SessionId,RowId,RuleId,SourceUrl,SourceList,DestinationUrl,DestinationList
260930-6,1,SG-ACCESS-UNKNOWN,https://source.denied/site,Documents,https://target.good/site,Documents
260930-6,2,SG-ACCESS-UNKNOWN,https://source.good/site,Documents,https://target.denied/site,Documents
260930-6,3,SG-ACCESS-UNKNOWN,https://source.good/site,Documents,https://target.good/site,Documents
'@ | Set-Content -LiteralPath (Join-Path $analysis 'ClassifiedRows.csv') -Encoding UTF8
    $env:PSModulePath = (Join-Path $root 'Modules') + [IO.Path]::PathSeparator + $oldModulePath
    $probe = Join-Path $testsRoot '..\Scripts\Diagnostics\SmartM365-SharePointMigration-ShareGateProbe.ps1'
    $emptyProject = Join-Path $root 'NoAnalysis'
    New-Item -ItemType Directory -Path $emptyProject -Force | Out-Null
    try {
        & $probe -ProjectRoot $emptyProject -DryRun | Out-Null
        throw 'Expected a clear missing-analysis error.'
    }
    catch {
        if ($_.Exception.Message -notmatch 'No phase 2a analysis exists') { throw }
    }
    & $probe -ProjectRoot (Join-Path $root 'Project') -AnalysisDirectory $analysis -SessionId '260930-6' -ProbeSource -Run | Out-Null
    $output = Get-ChildItem -LiteralPath (Join-Path $root 'Project\ShareGate\Diagnostics') -Directory -Filter 'Probe-*' | Select-Object -First 1
    if (-not $output) { throw 'Probe output was not created.' }
    $rows = @(Import-Csv -LiteralPath (Join-Path $output.FullName 'Probe-Access.csv'))
    if ($rows.Count -ne 3) { throw "Expected 3 access rows, got $($rows.Count)." }
    if (($rows | ForEach-Object Attribution) -join ',' -ne 'Source,Destination,Undetermined') { throw 'Access attribution did not match the fake endpoint reads.' }
    $cmdlets = @(Import-Csv -LiteralPath (Join-Path $output.FullName 'Probe-CmdletParameters.csv'))
    if (-not @($cmdlets | Where-Object Cmdlet -EQ 'Copy-Content').Count) { throw 'Copy-Content parameter metadata was not captured.' }
    $sessionProperties = @(Import-Csv -LiteralPath (Join-Path $output.FullName 'Probe-SessionProperties.csv'))
    if (-not @($sessionProperties | Where-Object Property -EQ 'SessionId').Count) { throw 'Session object properties were not captured.' }
    $env:SPMIG_TEST_EMPTY_SESSIONS = '1'
    $env:SPMIG_TEST_SOURCE_FORBIDDEN = '1'
    & $probe -ProjectRoot (Join-Path $root 'Project') -AnalysisDirectory $analysis -SessionId '260930-6' -Run | Out-Null
    $second = Get-ChildItem -LiteralPath (Join-Path $root 'Project\ShareGate\Diagnostics') -Directory -Filter 'Probe-*' | Where-Object FullName -NE $output.FullName | Select-Object -First 1
    if (-not $second) { throw 'Second probe output was not created.' }
    $secondRows = @(Import-Csv -LiteralPath (Join-Path $second.FullName 'Probe-Access.csv'))
    if (@($secondRows | Where-Object { $_.Attribution -ne 'Undetermined' -or $_.SourceStatus -ne 'Skipped - source unreachable' }).Count) { throw 'Source was not skipped by default.' }
    $secondResults = @(Import-Csv -LiteralPath (Join-Path $second.FullName 'Probe-Results.csv'))
    if (-not @($secondResults | Where-Object { $_.Area -eq 'Session' -and $_.Status -eq 'No local history' }).Count) { throw 'Empty local history was not reported.' }
    Write-Output 'ShareGate probe offline contract test passed.'
}
finally {
    $env:PSModulePath = $oldModulePath
    Remove-Item Env:SPMIG_TEST_EMPTY_SESSIONS,Env:SPMIG_TEST_SOURCE_FORBIDDEN -ErrorAction SilentlyContinue
    if ((Test-Path -LiteralPath $root) -and $root.StartsWith($testsRoot + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) {
        Remove-Item -LiteralPath $root -Recurse -Force
    }
}

