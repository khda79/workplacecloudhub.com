<#
.SYNOPSIS
    Offline safety and result contract for the ShareGate -WhatIf pre-check.
.VERSION
    1.0.0
#>
#Requires -Version 5.1
[CmdletBinding()]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$testsRoot = (Resolve-Path -LiteralPath $PSScriptRoot).Path
$root = Join-Path $testsRoot ('.precheck-test-' + [guid]::NewGuid().ToString('N'))
if (-not $root.StartsWith($testsRoot + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) { throw 'Unsafe test path.' }
$oldModulePath = $env:PSModulePath
try {
    $moduleDir = Join-Path $root 'Modules\ShareGate'
    $analysis = Join-Path $root 'Project\ShareGate\Diagnostics\Analysis'
    New-Item -ItemType Directory -Path $moduleDir,$analysis -Force | Out-Null
    @'
@{ RootModule='ShareGate.psm1'; ModuleVersion='99.0.0'; GUID='cb851a44-6ef6-4fbd-9719-eb19f6cc06fe'; FunctionsToExport=@('Connect-Site','Get-List','Copy-Content','Export-Report') }
'@ | Set-Content -LiteralPath (Join-Path $moduleDir 'ShareGate.psd1') -Encoding UTF8
    @'
function Connect-Site { [CmdletBinding()] param([string]$Url,[switch]$Browser) if ($Url -match 'target' -and -not $Browser) { throw 'Destination Browser missing' }; if ($Url -match 'source' -and $Browser) { throw 'Source must use current Windows user' }; [pscustomobject]@{ Url=$Url } }
function Get-List { [CmdletBinding()] param($Site,[string[]]$Name) [pscustomobject]@{ Title=$Name[0]; Site=$Site } }
function Copy-Content { [CmdletBinding()] param($SourceList,$DestinationList,[int[]]$SourceItemId,[switch]$WhatIf) if (-not $WhatIf) { throw 'Copy-Content without WhatIf' }; [pscustomobject]@{ Id=('precheck-'+$SourceItemId[0]); SourceId=$SourceItemId[0] } }
function Export-Report { [CmdletBinding()] param($CopyResult,[string]$Path) $errorText=if($CopyResult.SourceId -eq 1){ "401 Unauthorized. URL 'https://source.example/sites/a/_vti_bin/client.svc/ProcessQuery' was not authorized" }else{ '' }; [pscustomobject]@{ 'Source ID'=[string]$CopyResult.SourceId; Status=$(if($errorText){'Error'}else{'Success'}); Errors=$errorText } | Export-Csv -LiteralPath $Path -NoTypeInformation -Encoding UTF8 }
Export-ModuleMember -Function *
'@ | Set-Content -LiteralPath (Join-Path $moduleDir 'ShareGate.psm1') -Encoding UTF8
    @'
SessionId,RowId,RuleId,ItemKey,SourceUrl,SourceList,SourceItemId,DestinationUrl,DestinationList
260930-6,1,SG-ACCESS-SOURCE,one,https://source.example/sites/a,Documents,1,https://target.example/sites/a,Documents
260930-6,2,SG-ACCESS-SOURCE,two,https://source.example/sites/a,Documents,2,https://target.example/sites/a,Documents
260930-6,3,SG-ACCESS-SOURCE,two,https://source.example/sites/a,Documents,2,https://target.example/sites/a,Documents
'@ | Set-Content -LiteralPath (Join-Path $analysis 'ClassifiedRows.csv') -Encoding UTF8
    $env:PSModulePath = (Join-Path $root 'Modules') + [IO.Path]::PathSeparator + $oldModulePath
    $scriptPath = Join-Path $testsRoot '..\Scripts\Diagnostics\SmartM365-SharePointMigration-ShareGatePrecheck.ps1'
    try {
        & $scriptPath -ProjectRoot (Join-Path $root 'Project') -AnalysisDirectory $analysis -SessionId '260930-6' -Run | Out-Null
        throw 'Expected mandatory WhatIf guard.'
    }
    catch { if ($_.Exception.Message -notmatch 'WhatIf is mandatory') { throw } }
    & $scriptPath -ProjectRoot (Join-Path $root 'Project') -AnalysisDirectory $analysis -SessionId '260930-6' -WhatIf -DryRun | Out-Null
    if (@(Get-ChildItem -LiteralPath (Join-Path $root 'Project\ShareGate\Diagnostics') -Directory -Filter 'Precheck-*').Count) { throw 'DryRun created a pre-check output.' }
    & $scriptPath -ProjectRoot (Join-Path $root 'Project') -AnalysisDirectory $analysis -SessionId '260930-6' -WhatIf -Run | Out-Null
    $output = Get-ChildItem -LiteralPath (Join-Path $root 'Project\ShareGate\Diagnostics') -Directory -Filter 'Precheck-*' | Select-Object -First 1
    if (-not $output) { throw 'Pre-check output was not created.' }
    $items = @(Import-Csv -LiteralPath (Join-Path $output.FullName 'Precheck-Items.csv'))
    if ($items.Count -ne 2) { throw "Expected 2 distinct items, got $($items.Count)." }
    if ($items[0].Status -ne 'Source 401 observed' -or $items[1].Status -ne 'No 401 observed in pre-check') { throw 'Per-item pre-check statuses are incorrect.' }
    if (@(Get-ChildItem -LiteralPath (Join-Path $output.FullName 'Reports') -File -Filter '*.csv').Count -ne 2) { throw 'Export-Report did not create one CSV per item.' }
    Write-Output 'ShareGate pre-check offline contract test passed.'
}
finally {
    $env:PSModulePath = $oldModulePath
    if ((Test-Path -LiteralPath $root) -and $root.StartsWith($testsRoot + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) {
        Remove-Item -LiteralPath $root -Recurse -Force
    }
}

