<#
.SYNOPSIS
    Sets the lock state of one SharePoint Server site collection.
.DESCRIPTION
    Run on a SharePoint Server farm host with Windows PowerShell 5.1. The site
    URL must exactly match the resolved site collection URL. WhatIfMode reads
    and reports the current state without changing it.
.VERSION
    1.0.2
#>
#Requires -Version 5.1
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][ValidateNotNullOrEmpty()][string]$SiteUrl,
    [Parameter(Mandatory = $true)][ValidateSet('ReadOnly', 'Unlock', 'NoAccess')][string]$LockState,
    [switch]$WhatIfMode
)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot '..\Launchers\SmartM365-SharePointMigration-ConsoleLifecycle.ps1')
$script:SourceLockContext = Start-SmartM365MigrationConsoleLifecycle -ScriptPath $PSCommandPath -Action 'Set SharePoint Server site collection lock state'
$script:SourceLockFailure = $null
$script:SourceLockStatus = 'SUCCESS'
$scriptName = 'SmartM365-SharePointSource-SiteLockStateSet'
$runId = '{0}-{1}' -f (Get-Date -Format 'yyyyMMdd-HHmmss'), ([guid]::NewGuid().ToString('N'))
$logDirectory = Join-Path $PSScriptRoot 'logs'
$outputDirectory = Join-Path $PSScriptRoot 'Output'
$logPath = Join-Path $logDirectory ("$scriptName-$runId.log")
$csvPath = Join-Path $outputDirectory ("$scriptName-$runId.csv")
$result = [ordered]@{
    RunId = $runId
    Timestamp = (Get-Date -Format 'yyyy-MM-dd HH:mm:ss')
    ComputerName = $env:COMPUTERNAME
    SiteUrl = $SiteUrl
    RequestedLockState = $LockState
    PreviousLockState = ''
    NewLockState = ''
    Status = 'Pending'
    Message = ''
}

function Write-SourceLockLog {
    param([string]$Message, [ValidateSet('INFO','WARN','ERROR','SUCCESS')][string]$Level = 'INFO')
    $line = '{0} [{1}] {2}' -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'), $Level, $Message
    Microsoft.PowerShell.Utility\Write-Host $line
    Add-Content -LiteralPath $logPath -Value $line -Encoding UTF8
}

function Get-ExactSiteId {
    param([string]$Url)
    $site = Get-SPSite -Identity $Url -ErrorAction Stop
    if ($null -eq $site) { throw "Site collection was not found: $Url" }
    try {
        if ([string]::IsNullOrWhiteSpace([string]$site.Url)) {
            throw "Site collection URL was not returned for: $Url"
        }
        $actualUrl = ([uri][string]$site.Url).AbsoluteUri.TrimEnd('/')
        $requestedUrl = ([uri]$Url).AbsoluteUri.TrimEnd('/')
        if (-not [string]::Equals($actualUrl, $requestedUrl, [StringComparison]::OrdinalIgnoreCase)) {
            throw "Selected URL is not the exact site collection URL. Selected: $requestedUrl; collection: $actualUrl"
        }
        if ($null -eq $site.ID -or [guid]$site.ID -eq [guid]::Empty) {
            throw "Site collection ID was not returned for: $Url"
        }
        return [guid]$site.ID
    }
    finally {
        if ($site -is [IDisposable]) { $site.Dispose() }
    }
}

function Get-SiteLockState {
    param([guid]$SiteId)
    $site = Get-SPSiteAdministration -Identity $SiteId -ErrorAction Stop
    if ($null -eq $site) { throw "Site administration object was not found for: $SiteId" }
    try {
        foreach ($property in @('ReadLocked', 'ReadOnly', 'WriteLocked')) {
            if ($null -eq $site.PSObject.Properties[$property]) {
                throw "Site administration object does not expose '$property'; lock state cannot be verified."
            }
        }
        if ($site.ReadLocked) { return 'NoAccess' }
        if ($site.ReadOnly) { return 'ReadOnly' }
        if ($site.WriteLocked) { return 'NoAdditions' }
        return 'Unlock'
    }
    finally {
        if ($site -is [IDisposable]) { $site.Dispose() }
    }
}

try {
    [IO.Directory]::CreateDirectory($logDirectory) | Out-Null
    [IO.Directory]::CreateDirectory($outputDirectory) | Out-Null
    Write-SourceLockLog "Site collection URL: $SiteUrl"
    Write-SourceLockLog "Requested lock state: $LockState; WhatIfMode: $WhatIfMode"
    if ($PSVersionTable.PSEdition -ne 'Desktop' -or $PSVersionTable.PSVersion.Major -ne 5) {
        throw 'Run this operation with Windows PowerShell 5.1 on a SharePoint Server farm host.'
    }
    if (-not (Get-Command Get-SPSite -ErrorAction SilentlyContinue)) {
        Add-PSSnapin Microsoft.SharePoint.PowerShell -ErrorAction Stop
    }
    if (-not (Get-Command Get-SPSite -ErrorAction SilentlyContinue) -or
        -not (Get-Command Get-SPSiteAdministration -ErrorAction SilentlyContinue) -or
        -not (Get-Command Set-SPSite -ErrorAction SilentlyContinue)) {
        throw 'SharePoint Server PowerShell cmdlets are unavailable on this host.'
    }

    $siteId = Get-ExactSiteId -Url $SiteUrl
    $before = Get-SiteLockState -SiteId $siteId
    $result.PreviousLockState = $before
    Write-SourceLockLog "Current lock state: $before"
    if ($before -ieq $LockState) {
        $result.Status = 'AlreadySet'
        $result.NewLockState = $before
        $result.Message = "Site collection lock state is already '$LockState'."
    }
    elseif ($WhatIfMode) {
        $result.Status = 'WhatIf'
        $result.NewLockState = $before
        $result.Message = "No change applied. Site collection lock state would be set to '$LockState'."
    }
    else {
        Write-SourceLockLog "Setting site collection lock state to '$LockState'."
        Set-SPSite -Identity $SiteUrl -LockState $LockState -Confirm:$false -ErrorAction Stop
        $after = Get-SiteLockState -SiteId $siteId
        $result.NewLockState = $after
        if ($after -ine $LockState) {
            throw "Lock state read-back failed. Requested '$LockState'; observed '$after'."
        }
        $result.Status = 'Success'
        $result.Message = "Site collection lock state set to '$after'."
    }
    Write-SourceLockLog $result.Message 'SUCCESS'
    [pscustomobject]$result | Export-Csv -LiteralPath $csvPath -NoTypeInformation -Encoding UTF8 -Delimiter ';'
    Write-SourceLockLog "CSV report: $csvPath" 'SUCCESS'
}
catch {
    $result.Status = 'Error'
    $result.Message = $_.Exception.Message
    if (Test-Path -LiteralPath $outputDirectory -PathType Container) {
        [pscustomobject]$result | Export-Csv -LiteralPath $csvPath -NoTypeInformation -Encoding UTF8 -Delimiter ';'
    }
    if (Test-Path -LiteralPath $logDirectory -PathType Container) {
        Write-SourceLockLog $_.Exception.Message 'ERROR'
    }
    $script:SourceLockFailure = $_
    throw
}
finally {
    Complete-SmartM365MigrationConsoleLifecycle -Context $script:SourceLockContext -Failure $script:SourceLockFailure -Status $script:SourceLockStatus -LogPath $logPath
}

