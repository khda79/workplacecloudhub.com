#Requires -Version 5.1
Set-StrictMode -Version Latest

function ConvertTo-SmartM365ShareGateRelativePath {
    param([Parameter(Mandatory)][string]$Path, [Parameter(Mandatory)][string]$Side)
    $normalized = $Path.Trim().Replace('\', '/')
    if (-not $normalized -or $normalized.StartsWith('/') -or $normalized.Contains('://') -or
        $normalized.Contains('?') -or $normalized.Contains('#')) {
        throw "$Side path must be a nonempty library-relative file path: $Path"
    }
    $parts = @($normalized.Split('/'))
    if (@($parts | Where-Object { -not $_ -or $_ -eq '.' -or $_ -eq '..' -or $_.Contains(':') }).Count) {
        throw "$Side path has an unsafe or ambiguous segment: $Path"
    }
    return ($parts -join '/')
}

function Resolve-SmartM365ShareGateDestinationPath {
    param([Parameter(Mandatory)]$Row)
    if ([string]$Row.ObjectType -ne 'File') {
        throw "Only File rows can use item-scoped destination routing: $($Row.ItemKey)"
    }
    $source = ConvertTo-SmartM365ShareGateRelativePath -Path ([string]$Row.'Raw: Source path') -Side Source
    $destination = ConvertTo-SmartM365ShareGateRelativePath -Path ([string]$Row.'Raw: Destination path') -Side Destination
    $sourceLeaf = @($source.Split('/'))[-1]
    $destinationParts = @($destination.Split('/'))
    if (-not [string]::Equals($sourceLeaf, $destinationParts[-1], [StringComparison]::OrdinalIgnoreCase)) {
        throw "Source and destination filenames differ for item $($Row.ItemKey); Copy-Content cannot be assumed to rename it."
    }
    $folder = if ($destinationParts.Count -gt 1) {
        ($destinationParts[0..($destinationParts.Count - 2)] -join '/')
    } else { '' }
    return [pscustomobject]@{
        SourceFilePath=$source
        DestinationFilePath=$destination
        DestinationFolder=$folder
        FileName=$destinationParts[-1]
    }
}

function Assert-SmartM365ShareGateDestinationFolder {
    param([Parameter(Mandatory)]$DestinationList, [AllowEmptyString()][string]$DestinationFolder)
    if (-not $DestinationFolder) { return }
    $folders = @(ShareGate\Get-Folder -List $DestinationList -Path $DestinationFolder -ErrorAction Stop)
    if ($folders.Count -ne 1 -or -not $folders[0]) {
        throw "Destination folder does not exist or is ambiguous: $DestinationFolder"
    }
}

