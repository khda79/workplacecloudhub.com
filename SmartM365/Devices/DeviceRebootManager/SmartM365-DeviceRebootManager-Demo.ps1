#Requires -Version 5.1
<#
.SYNOPSIS
In-memory demonstration scenes for the existing Device Reboot Manager WPF window.
.VERSION
1.0.0
.NOTES
No device discovery, runtime configuration, state files or restart commands.
#>

function Set-RebootManagerDemoScene {
    param([ValidateSet('Recommended','Required','Postponed')][string]$Scenario)

    $script:RebootDemoScenario = $Scenario
    $script:ForceMode = $Scenario -ne 'Recommended'
    $script:DaysSinceReboot = if ($script:ForceMode) { 9 } else { 6 }
    $script:LastBoot = [datetime]'2026-10-18T09:30:00'
    $script:LastBoot = $script:LastBoot.AddDays(-$script:DaysSinceReboot)
    $script:PostponeCount = if ($Scenario -eq 'Postponed') { 1 } else { 0 }
    $script:InitialSeconds = if ($Scenario -eq 'Postponed') { 1500 } else { 900 }
    $script:SecondsRemaining = $script:InitialSeconds
    Apply-LocalizedUi
}

function Invoke-RebootManagerDemo {
    param(
        [ValidateSet('Recommended','Required','Postponed')][string]$Scenario,
        [int]$Width,
        [int]$Height,
        [switch]$ValidateOnly
    )

    if ([Threading.Thread]::CurrentThread.GetApartmentState() -ne [Threading.ApartmentState]::STA) {
        throw 'The demo requires STA. Use the Demo CMD launcher.'
    }
    # Built-in settings only. Never call Read-AppConfig, preference or reminder loaders.
    $script:Effective = $null
    Initialize-EffectiveSettings
    $script:Effective.CompanyName = 'Contoso'
    $script:Effective.WindowTitle = ''
    $script:Effective.WindowIconPath = 'WorkplaceCloudHub.ico'
    $script:Effective.LanguageCatalogPath = ''
    $script:Effective.DefaultLanguage = if ($script:CliBoundParameters.ContainsKey('DefaultLanguage')) { $DefaultLanguage } else { 'en' }
    $script:Effective.ForceLanguage = $false
    $script:Effective.RecommendedRestartAfterDays = 5
    $script:Effective.RequiredRestartAfterDays = 7
    $script:Effective.RestartCountdownMinutes = 15
    $script:Effective.MaxPostponeCount = 2
    $script:Effective.PostponeOptionsMinutes = @(10,30,60)
    $script:PreviewOnly = $true
    $script:DetectedCompanyName = 'Contoso'
    $script:AllowClose = $true
    $script:Strings = Get-AppStrings
    $script:Window = New-RebootManagerWindow
    $script:Window.Width = $Width
    $script:Window.Height = $Height
    # The product window sizes its height to the content; keep that in the demo.
    $script:Window.SizeToContent = 'Height'
    $script:Window.Topmost = $false
    $script:Window.UseLayoutRounding = $true

    $body = $script:Window.Content
    $script:Window.Content = $null
    $dock = New-Object System.Windows.Controls.DockPanel
    $bar = New-Object System.Windows.Controls.StackPanel
    $bar.Orientation = 'Horizontal'
    $bar.Margin = '18,12,18,0'
    [System.Windows.Controls.DockPanel]::SetDock($bar, 'Top')
    $label = New-Object System.Windows.Controls.TextBlock
    $label.Text = 'DEMO - Sample data | Scene'
    $label.VerticalAlignment = 'Center'
    $label.Margin = '0,0,12,0'
    [void]$bar.Children.Add($label)
    $sceneCombo = New-Object System.Windows.Controls.ComboBox
    $sceneCombo.Width = 180
    $sceneCombo.ItemsSource = @('Recommended','Required','Postponed')
    $sceneCombo.SelectedItem = $Scenario
    $script:Ui.DemoScenarioCombo = $sceneCombo
    [void]$bar.Children.Add($sceneCombo)
    [void]$dock.Children.Add($bar)
    [void]$dock.Children.Add($body)
    $script:Window.Content = $dock
    $icon = Join-Path $PSScriptRoot 'WorkplaceCloudHub.ico'
    if (Test-Path -LiteralPath $icon) {
        $script:Window.Icon = [System.Windows.Media.Imaging.BitmapFrame]::Create([uri]$icon)
    }
    foreach ($minutes in @(10,30,60)) { [void]$script:Ui.PostponeCombo.Items.Add("$minutes min") }
    $script:Ui.PostponeCombo.SelectedIndex = 0
    Set-RebootManagerDemoScene -Scenario $Scenario

    $sceneCombo.Add_SelectionChanged({
        Set-RebootManagerDemoScene -Scenario ([string]$script:Ui.DemoScenarioCombo.SelectedItem)
    })
    $script:Ui.LanguageCombo.Add_SelectionChanged({
        if ($script:IsUpdatingLanguageSelector -or -not $script:Ui.LanguageCombo.SelectedItem) { return }
        $script:Effective.DefaultLanguage = [string]$script:Ui.LanguageCombo.SelectedItem.Code
        $script:Strings = Get-AppStrings
        Apply-LocalizedUi
    })
    $script:Ui.RestartButton.Add_Click({
        Invoke-SafeRestart -Reason 'Demo button'
        $script:Ui.NextActionText.Text = 'DEMO: restart completed successfully. The device was not restarted.'
    })
    $script:Ui.PostponeButton.Add_Click({
        if ($script:PostponeCount -ge 2) { return }
        $minutes = [int]([regex]::Match([string]$script:Ui.PostponeCombo.SelectedItem, '\d+').Value)
        $script:SecondsRemaining += $minutes * 60
        $script:InitialSeconds += $minutes * 60
        $script:PostponeCount++
        Set-PostponeState
        Update-CountdownUi
        Write-AppLog -Message ("DEMO: postponed by {0} minutes. State remains in memory." -f $minutes)
    })
    $script:Ui.LaterButton.Add_Click({
        Write-AppLog -Message 'DEMO: reminder deferred. No reminder state was saved.'
        $script:Ui.NextActionText.Text = 'DEMO: a reminder would be shown later.'
    })
    $script:Ui.CloseButton.Add_Click({ $script:Window.Close() })

    if ($ValidateOnly) {
        return [pscustomobject]@{ Mode='Demo'; Window=$script:Window; Controls=$script:Ui; Scenario=$Scenario }
    }
    $splash = $null
    try {
        . (Join-Path $PSScriptRoot 'SmartM365.GuiSplash.ps1')
        $splash = Start-SmartM365GuiSplash -ProductName 'Device Reboot Manager' -Subtitle 'DEMO - Sample data' -MinimumDurationMs 6000
        $script:RebootDemoSplash = $splash
        $script:Window.Add_ContentRendered({ Hide-SmartM365GuiSplash -Splash $script:RebootDemoSplash })
        [void]$script:Window.ShowDialog()
    }
    finally {
        if ($splash) { Close-SmartM365GuiSplash -Splash $splash }
    }
}

