#Requires -Version 5.1
<#
.SYNOPSIS
Previews or repairs only the console host of an existing Device Reboot Manager task.
.DESCRIPTION
The default is read-only. With -Apply, backs up the task XML and replaces a direct
PowerShell action with conhost --headless. Keeps the existing arguments, working
directory, triggers, principal and settings. Never creates or starts a task.
.VERSION
1.1.2
#>
[CmdletBinding(SupportsShouldProcess = $true, ConfirmImpact = 'High')]
param(
    [string]$TaskPath = '\SmartM365\',
    [string]$TaskName = 'Device Reboot Manager',
    [string]$BackupRoot = (Join-Path $env:ProgramData 'WCH\Smart365\InstallBackups\TaskLauncher'),
    [switch]$Apply
)

$ErrorActionPreference = 'Stop'
$task = Get-ScheduledTask -TaskPath $TaskPath -TaskName $TaskName -ErrorAction Stop
$actions = @($task.Actions)
if ($actions.Count -ne 1) { throw 'Expected exactly one task action; nothing changed.' }
$oldAction = $actions[0]
$executable = ([string]$oldAction.Execute).Trim('"')
$arguments = [string]$oldAction.Arguments
$workingDirectory = [string]$oldAction.WorkingDirectory
$leaf = [IO.Path]::GetFileName($executable)

if ($arguments -notmatch '(?i)(?:^|\s)-File\s+(?:"[^"]*SmartM365-DeviceRebootManager-GUI\.ps1"|[^\s]*SmartM365-DeviceRebootManager-GUI\.ps1)(?=\s|$)') {
    throw 'The action does not directly identify the Device Reboot Manager GUI; nothing changed.'
}
if ($leaf -ieq 'conhost.exe' -and $arguments -match '(?i)^\s*--headless(?:\s|$)') {
    return [pscustomobject]@{ Mode = 'NoChange'; TaskPath = $TaskPath; TaskName = $TaskName; AlreadyHeadless = $true; Changed = $false }
}
if ($leaf -notin @('powershell.exe', 'pwsh.exe')) {
    throw 'Only a direct PowerShell task action can be repaired; nothing changed.'
}
# Read the actual Windows build, independent of the caller executable's manifest.
$os = Get-CimInstance -ClassName Win32_OperatingSystem -ErrorAction Stop
$conhost = Join-Path $env:SystemRoot 'System32\conhost.exe'
$conhostProbe = $conhost
if ([Environment]::Is64BitOperatingSystem -and -not [Environment]::Is64BitProcess) {
    $conhostProbe = Join-Path $env:SystemRoot 'Sysnative\conhost.exe'
}
if ([int]$os.BuildNumber -lt 19041 -or -not (Test-Path -LiteralPath $conhostProbe -PathType Leaf)) {
    throw 'This repair requires Windows build 19041 or later and conhost.exe; nothing changed.'
}
$newArguments = '--headless "{0}" {1}' -f $executable, $arguments
$result = [ordered]@{
    Mode = 'Preview'; TaskPath = $TaskPath; TaskName = $TaskName
    OldExecute = [string]$oldAction.Execute; OldArguments = $arguments
    NewExecute = $conhost; NewArguments = $newArguments
    WorkingDirectory = $workingDirectory; Changed = $false; BackupPath = $null
}
if (-not $Apply -or -not $PSCmdlet.ShouldProcess(($TaskPath + $TaskName), 'Back up task and replace only its console host')) {
    return [pscustomobject]$result
}

$identity = [Security.Principal.WindowsIdentity]::GetCurrent()
if (-not ([Security.Principal.WindowsPrincipal]::new($identity)).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    throw 'Run -Apply from an elevated PowerShell session; nothing changed.'
}
# Password-based tasks cannot be restored from exported XML without their secret.
$logonType = [string]$task.Principal.LogonType
if ($logonType -notin @('Group', 'Interactive', 'InteractiveToken')) {
    throw 'Only an interactive user/group task is supported; nothing changed.'
}
$xmlBefore = Export-ScheduledTask -TaskPath $TaskPath -TaskName $TaskName -ErrorAction Stop
[xml]$definitionBefore = $xmlBefore
if ($definitionBefore.SelectSingleNode("//*[local-name()='RegistrationTrigger']")) {
    throw 'A registration trigger could start the task during repair; nothing changed.'
}
$directory = Join-Path $BackupRoot (([datetime]::UtcNow.ToString('yyyyMMddTHHmmssZ')) + '-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $directory -Force | Out-Null
$backupAcl = Get-Acl -LiteralPath $directory
$backupAcl.SetAccessRuleProtection($true, $false)
foreach ($sid in @('S-1-5-18', 'S-1-5-32-544')) {
    $backupAcl.AddAccessRule([Security.AccessControl.FileSystemAccessRule]::new(
        [Security.Principal.SecurityIdentifier]::new($sid), 'FullControl',
        'ContainerInherit,ObjectInherit', 'None', 'Allow'))
}
Set-Acl -LiteralPath $directory -AclObject $backupAcl
$backup = Join-Path $directory 'Task-before.xml'
# Task Scheduler exports UTF-16 XML. Preserve its declaration and encoding.
[IO.File]::WriteAllText($backup, $xmlBefore, [Text.Encoding]::Unicode)
if ([IO.File]::ReadAllText($backup) -cne $xmlBefore) { throw 'Task backup verification failed; nothing changed.' }
$result.BackupPath = $backup
$result.BackupSHA256 = (Get-FileHash -LiteralPath $backup -Algorithm SHA256).Hash
$actionParameters = @{ Execute = $conhost; Argument = $newArguments }
if (-not [string]::IsNullOrWhiteSpace($workingDirectory)) { $actionParameters.WorkingDirectory = $workingDirectory }
$newAction = New-ScheduledTaskAction @actionParameters

try {
    Set-ScheduledTask -TaskPath $TaskPath -TaskName $TaskName -Action $newAction -ErrorAction Stop | Out-Null
    [xml]$definitionAfter = Export-ScheduledTask -TaskPath $TaskPath -TaskName $TaskName -ErrorAction Stop
    foreach ($section in @('Triggers', 'Principals', 'Settings', 'RegistrationInfo')) {
        $beforeNode = $definitionBefore.DocumentElement.SelectSingleNode("*[local-name()='$section']")
        $afterNode = $definitionAfter.DocumentElement.SelectSingleNode("*[local-name()='$section']")
        $beforeText = if ($beforeNode) { $beforeNode.OuterXml } else { '' }
        $afterText = if ($afterNode) { $afterNode.OuterXml } else { '' }
        if ($beforeText -cne $afterText) { throw "Unexpected change to task section: $section" }
    }
    $verifiedTask = Get-ScheduledTask -TaskPath $TaskPath -TaskName $TaskName -ErrorAction Stop
    $verifiedActions = @($verifiedTask.Actions)
    if ($verifiedActions.Count -ne 1 -or $verifiedActions[0].Execute -ine $conhost -or
        [string]$verifiedActions[0].Arguments -cne $newArguments -or
        [string]$verifiedActions[0].WorkingDirectory -cne $workingDirectory) {
        throw 'Task action read-back did not match the reviewed repair.'
    }
}
catch {
    $failure = $_.Exception.Message
    try {
        Register-ScheduledTask -TaskPath $TaskPath -TaskName $TaskName -Xml $xmlBefore -Force -ErrorAction Stop | Out-Null
    }
    catch { throw "Repair failed ($failure); automatic restoration also failed. Restore the protected backup: $backup" }
    throw "Repair failed and the original task was restored: $failure. Backup: $backup"
}
$result.Mode = 'Applied'
$result.Changed = $true
$result.PreservedSections = @('Triggers', 'Principals', 'Settings', 'RegistrationInfo')
$result.TaskStarted = $false
[pscustomobject]$result

