[CmdletBinding()]param()
$ErrorActionPreference='Stop'
$app=Split-Path -Parent $PSScriptRoot
$gui=Join-Path $app 'SmartM365-EndpointDiagnosticsAnalyzer-GUI.ps1'
$tokens=$null;$errors=$null;$ast=[Management.Automation.Language.Parser]::ParseFile($gui,[ref]$tokens,[ref]$errors)
if($errors.Count){throw 'Application parse failed'}
foreach($name in @('ConvertTo-SedaProcessArgument','Start-SedaAnalysisProcess','Complete-SedaAnalysisProcess','Stop-SedaProcessTree','ConvertFrom-SedaTerminalText','Get-SedaTextContent')){
 $node=$ast.Find({param($n)$n -is [Management.Automation.Language.FunctionDefinitionAst] -and $n.Name -eq $name},$true)
 if(-not $node){throw "Missing function $name"};Invoke-Expression $node.Extent.Text
}
$reader=$ast.Find({param($n)$n -is [Management.Automation.Language.FunctionDefinitionAst] -and $n.Name -eq 'Get-SedaAnalysisErrorText'},$true)
if($reader){Invoke-Expression $reader.Extent.Text}else{function Get-SedaAnalysisErrorText([string]$Path){ConvertFrom-SedaTerminalText (Get-SedaTextContent -Path $Path)}}
$root=Join-Path ([IO.Path]::GetTempPath()) ('seda-encoding-'+[guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory $root|Out-Null
$worker=$null;$checks=0
try {
 $invalid=Join-Path $root 'invalid.zip';[IO.File]::WriteAllText($invalid,'synthetic invalid archive')
 $result=Join-Path $root 'result.clixml';$stderr=Join-Path $root 'stderr.txt'
 $copy=Join-Path $root 'Analyzer-café-déjà.ps1';Copy-Item -LiteralPath $gui -Destination $copy
 $escapedGui=$copy.Replace("'","''");$escapedZip=$invalid.Replace("'","''");$escapedResult=$result.Replace("'","''")
 # Reproduce a French Windows console using OEM850; production must establish its own worker contract.
 $command="[Console]::OutputEncoding=[Text.Encoding]::GetEncoding(850);[Threading.Thread]::CurrentThread.CurrentCulture=[Globalization.CultureInfo]::GetCultureInfo('fr-FR');[Threading.Thread]::CurrentThread.CurrentUICulture=[Globalization.CultureInfo]::GetCultureInfo('fr-FR'); & '$escapedGui' -Cli -ZipPath '$escapedZip' -ExportAnalysisClixmlPath '$escapedResult'"
 $bootstrap=Join-Path $root 'bootstrap.ps1';[IO.File]::WriteAllText($bootstrap,$command,[Text.UTF8Encoding]::new($true))
 $worker=Start-SedaAnalysisProcess -FilePath (Get-Process -Id $PID).Path -ArgumentList @('-NoProfile','-ExecutionPolicy','Bypass','-File',$bootstrap) -StandardOutputPath (Join-Path $root 'stdout.txt') -StandardErrorPath $stderr
 if(-not $worker.Process.WaitForExit(30000)){throw 'Actual invalid ZIP worker timed out'}
 $code=Complete-SedaAnalysisProcess $worker;$worker=$null
 if($code -eq 0 -or (Test-Path $result)){throw 'Invalid ZIP reported success'};$checks++
 $utf8=[Text.UTF8Encoding]::new($false,$true)
 $native=[IO.File]::ReadAllText($stderr,$utf8)
 if($native -notmatch 'End of Central Directory' -or $native -notmatch 'Analyzer-café-déjà'){throw ('Missing real worker error with Unicode path: '+$native)};$checks++
 $actual=Get-SedaAnalysisErrorText -Path $stderr
 if($actual -cne (ConvertFrom-SedaTerminalText $native)){throw 'GUI error differs from correctly decoded native stderr'};$checks++
 if($actual.Contains([string][char]27) -or $actual.Contains([string][char]0xfffd)){throw 'Error contains terminal escapes or replacement characters'};$checks++
 $sample=([string][char]27)+"[31mÉchec café déjà — l’appel «OpenRead»; 日本語; literal Ã / Â"+([string][char]27)+'[0m'
 [IO.File]::WriteAllText((Join-Path $root 'unicode.txt'),$sample,$utf8)
 if((Get-SedaAnalysisErrorText (Join-Path $root 'unicode.txt')) -cne "Échec café déjà — l’appel «OpenRead»; 日本語; literal Ã / Â"){throw 'Known UTF8 punctuation/accents/non-Latin text was changed'};$checks++
 [pscustomobject]@{Result='PASS';Checks=$checks;Engine=[string]$PSVersionTable.PSVersion;ActualWorkerExitCode=$code;CollectionRun=$false;Utf8Error=$actual}
} finally {
 if($worker){Stop-SedaProcessTree $worker.Process.Id;[void](Complete-SedaAnalysisProcess $worker)}
 if([IO.Directory]::Exists($root)){[IO.Directory]::Delete($root,$true)}
}

