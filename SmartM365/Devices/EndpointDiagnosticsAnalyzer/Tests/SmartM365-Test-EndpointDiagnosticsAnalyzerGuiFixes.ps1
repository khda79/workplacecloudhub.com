#Requires -Version 5.1
<#
.SYNOPSIS
    Regressions for visible-grid exports, long-path extraction cleanup and worker errors.
.VERSION
    1.0.0
#>
[CmdletBinding()]param()
$ErrorActionPreference='Stop'
$app=Split-Path -Parent $PSScriptRoot
$gui=Join-Path $app 'SmartM365-EndpointDiagnosticsAnalyzer-GUI.ps1'
$tokens=$null;$errors=$null
$ast=[Management.Automation.Language.Parser]::ParseFile($gui,[ref]$tokens,[ref]$errors)
if($errors.Count){throw ($errors.Message -join '; ')}
foreach($name in @('Remove-SedaAnalysisExtraction','ConvertFrom-SedaTerminalText','Get-SedaVisibleGrid','get-selected-grid','export-grid-csv','ConvertTo-SedaProcessArgument','Start-SedaAnalysisProcess','Complete-SedaAnalysisProcess','Stop-SedaProcessTree')){
    $node=$ast.Find({param($n)$n -is [Management.Automation.Language.FunctionDefinitionAst] -and $n.Name -eq $name},$true)
    if(-not $node){throw "Missing function $name"}
    Invoke-Expression $node.Extent.Text
}
$script:warnings=@()
function Write-SedaLog {param($Level,$Message,$Exception) $script:warnings+=@($Message)}
$script:checks=0
function Assert-GuiFix([bool]$Condition,[string]$Message){if(-not $Condition){throw "FAIL: $Message"};$script:checks++}
$root=Join-Path ([IO.Path]::GetTempPath()) ('seda_diag_'+[guid]::NewGuid().ToString('N'))
$outside=Join-Path ([IO.Path]::GetTempPath()) ('seda_guard_'+[guid]::NewGuid().ToString('N'))
$worker=$null
try {
    [IO.Directory]::CreateDirectory($root)|Out-Null
    [IO.Directory]::CreateDirectory($outside)|Out-Null
    [IO.File]::WriteAllText((Join-Path $outside 'preserve.txt'),'preserve')
    $long=$root+'\'+('a'*90)+'\'+('b'*90)+'\'+('c'*90)
    [IO.Directory]::CreateDirectory('\\?\'+$long)|Out-Null
    [IO.File]::WriteAllText(('\\?\'+$long+'\readonly.txt'),'fixture')
    [IO.File]::SetAttributes(('\\?\'+$long+'\readonly.txt'),[IO.FileAttributes]::ReadOnly)
    $junction=Join-Path $root 'outside-junction'
    New-Item -ItemType Junction -Path $junction -Target $outside|Out-Null
    Remove-SedaAnalysisExtraction $outside
    Assert-GuiFix (Test-Path (Join-Path $outside 'preserve.txt')) 'Unowned root refused'
    Remove-SedaAnalysisExtraction $root
    Assert-GuiFix (-not [IO.Directory]::Exists($root)) 'Long paths and readonly files removed'
    Assert-GuiFix (([IO.File]::ReadAllText((Join-Path $outside 'preserve.txt'))) -eq 'preserve') 'Junction target preserved'
    Assert-GuiFix ($script:warnings.Count -eq 0) 'Successful cleanup has no suppressed failures'

    $hidden=[pscustomobject]@{IsVisible=$false;ItemsSource=@(1..38);SelectedItem=1;Tag=@(1..38)}
    $rows=@(1..22|ForEach-Object {[pscustomobject]@{Category='collection_errors';File="file$_.txt"}})
    $visible=[pscustomobject]@{IsVisible=$true;ItemsSource=$rows[0..2];SelectedItem=$null;Tag=$rows}
    $controls=@{EnrollmentsGrid=$hidden;ZipFilesGrid=$visible}
    $script:CurrentGrid=$hidden
    $selected=get-selected-grid
    Assert-GuiFix ([object]::ReferenceEquals($selected,$visible)) 'Changed tab ignores stale hidden grid'
    $csv=Join-Path $outside 'grid.csv'
    export-grid-csv -Grid $selected -Path $csv
    $export=@(Import-Csv $csv)
    Assert-GuiFix ($export.Count -eq 22 -and @($export|Where-Object Category -ne 'collection_errors').Count -eq 0) 'CSV contains all matching rows beyond display limit'
    Assert-GuiFix (-not ($export[0].PSObject.Properties.Name -contains 'GUID')) 'CSV belongs to visible ZIP grid'
    $visible.IsVisible=$false
    Assert-GuiFix ($null -eq (get-selected-grid)) 'No visible grid never falls back to hidden data'
    $visible.IsVisible=$true;$visible.SelectedItem=$rows[0];$script:CurrentGrid=$visible
    Assert-GuiFix ([object]::ReferenceEquals((get-selected-grid),$visible)) 'Focused visible grid retained'

    $esc=[string][char]27
    $colored=$esc+'[31;1mErreur café 日本語'+$esc+'[0m'+"`r`n"+'End of Central Directory record could not be found.'
    $plain=ConvertFrom-SedaTerminalText $colored
    Assert-GuiFix ($plain -eq "Erreur café 日本語`r`nEnd of Central Directory record could not be found.") 'ANSI removed without altering Unicode or newlines'
    Assert-GuiFix ((ConvertFrom-SedaTerminalText ($esc+']8;;https://example.invalid'+[char]7+'label'+$esc+']8;;'+[char]7)) -eq 'label') 'OSC control sequence removed'
    $encoded=[Convert]::ToBase64String([Text.Encoding]::Unicode.GetBytes('[Console]::OutputEncoding=[Text.UTF8Encoding]::new($false);[Console]::Error.Write(([string][char]27)+"[31;1mError café 日本語"+([string][char]27)+"[0m");exit 7'))
    $worker=Start-SedaAnalysisProcess -FilePath (Get-Process -Id $PID).Path -ArgumentList @('-NoProfile','-EncodedCommand',$encoded) -StandardOutputPath (Join-Path $outside 'stdout.txt') -StandardErrorPath (Join-Path $outside 'stderr.txt')
    if(-not $worker.Process.WaitForExit(15000)){throw 'Worker test timeout'}
    $exitCode=Complete-SedaAnalysisProcess $worker;$worker=$null
    Assert-GuiFix ($exitCode -eq 7) 'Real native failing worker exit preserved'
    $actual=ConvertFrom-SedaTerminalText ([IO.File]::ReadAllText((Join-Path $outside 'stderr.txt')))
    Assert-GuiFix ($actual -eq 'Error café 日本語') ("Real redirected worker error is plain Unicode; actual="+$actual)
    [pscustomobject]@{Result='PASS';Checks=$script:checks;Engine=[string]$PSVersionTable.PSVersion;LongPathLength=$long.Length}
} finally {
    if($worker){Stop-SedaProcessTree -ProcessId $worker.Process.Id;[void](Complete-SedaAnalysisProcess $worker)}
    Remove-SedaAnalysisExtraction $root
    if([IO.Directory]::Exists($outside)){[IO.Directory]::Delete($outside,$true)}
}

