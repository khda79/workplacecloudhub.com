$script:SemtDemoPackageRoot = Split-Path -Path $script:SmartM365Demo.AppRoot -Parent
Import-Module (Join-Path $script:SemtDemoPackageRoot 'Modules\SmartEndpointMigration.Core\SmartEndpointMigration.Core.psd1') -MinimumVersion 1.0.0 -Force
foreach ($functionText in @(Get-SmartM365DemoFunctionText -Path $script:SmartM365Demo.GuiPath -Names @('Register-NumericStepper','Add-SemtGuiOptionControls'))) { . ([scriptblock]::Create(([regex]::Replace($functionText, '^function\s+', 'function script:')))) }
$script:window = $script:SmartM365Demo.Window
$script:CategoryOrder = @('Mode','Actions','Setup','Safety','Schedule','Parallelism','Network','Inventory','Evidence')
$script:SemtDemoCatalog = Import-SemtOptionCatalog -PackageRoot $script:SemtDemoPackageRoot
$script:SemtDemoCampaigns = [ordered]@{ HybridJoin = 'Hybrid Join and Intune enrollment'; Windows11Upgrade = 'Windows 11 upgrade' }

function script:Get-SemtDemoCampaign {
    $item = $script:SmartM365Demo.Controls.CampaignCombo.SelectedItem
    if ($null -eq $item) { return 'HybridJoin' }
    if ($item -is [Windows.Controls.ComboBoxItem]) { return [string]$item.Tag }
    foreach ($key in $script:SemtDemoCampaigns.Keys) { if ($script:SemtDemoCampaigns[$key] -eq [string]$item) { return $key } }
    return 'HybridJoin'
}

function script:Get-SemtDemoWaves {
    param([string]$Campaign)
    $s = $script:SmartM365Demo
    $key = 'Waves:' + $Campaign
    if (-not $s.Data.ContainsKey($key)) {
        $s.Data[$key] = if ($Campaign -eq 'Windows11Upgrade') { @('WAVE-CONTOSO-W11-PILOT','WAVE-CONTOSO-W11-PARIS','WAVE-AUTO-W10-20261018-093000') } else { @('WAVE-CONTOSO-HJ-PILOT','WAVE-CONTOSO-HJ-LYON','WAVE-AUTO-HJ-20261018-093000') }
    }
    return @($s.Data[$key])
}

function script:Update-SemtDemoRuns {
    param([string]$Campaign)
    $s = $script:SmartM365Demo
    $statuses = switch ($s.Scenario) { 'Issues' { @('Running','Failed','Stopped','Completed') } 'Completed' { @('Completed','Completed','Completed','Completed') } default { @('Running','Completed','Completed','Stopped') } }
    $waves = @(Get-SemtDemoWaves -Campaign $Campaign)
    $rows = @(for ($i = 0; $i -lt 4; $i++) {
        [pscustomobject]@{
            WaveName = $waves[$i % $waves.Count]
            RunId = '20261018-0{0}3000-DEMO{1}' -f (9 - $i),$i
            Status = $statuses[$i]
            Cycles = 3 - ($i % 3)
            StartedUtc = '2026-10-18T0{0}:30:00Z' -f (9 - $i)
            UpdatedUtc = '2026-10-18T0{0}:45:00Z' -f (9 - $i)
            Technician = 'technician01'
        }
    })
    Set-SmartM365DemoGrid -Name RunsGrid -Rows $rows
    $active = @($rows | Where-Object { $_.Status -eq 'Running' })
    $s.Controls.ActiveRunsText.Text = if ($active.Count) { 'DEMO - {0} active Run(s): {1}' -f $active.Count,((@($active) | ForEach-Object { $_.WaveName }) -join ', ') } else { 'DEMO - No Run of this Campaign is active.' }
}

function script:Update-SemtDemoCampaign {
    $s = $script:SmartM365Demo; $c = $s.Controls
    $campaign = Get-SemtDemoCampaign
    $s.Data.Campaign = $campaign
    $isWindows11 = ($campaign -eq 'Windows11Upgrade')
    $values = @{}
    foreach ($definition in @(Get-SemtCampaignOptionDefinitions -Catalog $script:SemtDemoCatalog -Campaign $campaign)) { $values[[string]$definition.Name] = Get-SemtOptionDefault -Definition $definition -Campaign $campaign }
    $values['DryRun'] = $true
    if ($isWindows11) {
        foreach ($name in @('Windows11Upgrade.SetupSourcePath')) { if ($values.ContainsKey($name)) { $values[$name] = '\\files.contoso.example\Windows11\24H2' } }
        foreach ($name in @('Windows11Upgrade.SetupMediaId')) { if ($values.ContainsKey($name)) { $values[$name] = 'CTSO-W11-24H2-DEMO' } }
    }
    $s.Data.Editors = Add-SemtGuiOptionControls -OptionsHost $c.OptionsHost -Catalog $script:SemtDemoCatalog -Campaign $campaign -Values $values
    $c.OptionsCampaignText.Text = 'Options - ' + $script:SemtDemoCampaigns[$campaign]
    Set-SmartM365DemoCombo WaveCombo @(Get-SemtDemoWaves -Campaign $campaign | ForEach-Object { '{0}  ({1} computer(s))' -f $_,$(if ($_ -like '*PILOT*') { 4 } else { 12 }) })
    $c.WaveDeviceCountText.Text = '4'
    $c.WaveSourceText.Text = 'Manual - Contoso pilot'
    $c.WaveWrappersText.Text = 'Ready'
    $c.WaveLastRunText.Text = 'Completed (2026-10-18T08:45:00Z)'
    $c.AutomaticSourcePanel.Visibility = if ($isWindows11) { 'Visible' } else { 'Collapsed' }
    $c.AutomaticInventoryStatusText.Text = if ($isWindows11) { 'DEMO - Shared inventories - AD: Fresh (3.5 h); Intune: FreshVerifiedProvenance (0.8 h)' } else { 'DEMO - Shared inventories - AD: Fresh (3.5 h); Intune: FreshVerifiedProvenance (0.8 h); Entra: Fresh (0.8 h)' }
    $c.AutomaticWaveNameText.Text = if ($isWindows11) { 'WAVE-AUTO-W10-20261018-093000' } else { 'WAVE-AUTO-HJ-20261018-093000' }
    $c.AutomaticSummaryText.Text = "DEMO - Contoso automatic selection ($campaign)`r`nSource devices: 18`r`nEligible: 12`r`nExcluded: 6 (2 stale AD logon, 2 already done, 2 ambiguous names)`r`nSelected: CTSO-LAP-0001 to CTSO-LAP-0012`r`nNo AD, Intune, Entra, endpoint or inventory cache was queried."
    $c.SingleRunFolderText.Text = 'Demo/Runs/' + $campaign + '/_SinglePC'
    Update-SemtDemoRuns -Campaign $campaign
}

function script:Initialize-SmartM365DemoProfile {
    $s = $script:SmartM365Demo; $c = $s.Controls
    if (-not $s.Data.ContainsKey('CampaignsLoaded')) {
        $c.CampaignCombo.ItemsSource = $null; $c.CampaignCombo.Items.Clear()
        foreach ($key in $script:SemtDemoCampaigns.Keys) { $item = New-Object Windows.Controls.ComboBoxItem; $item.Content = $script:SemtDemoCampaigns[$key]; $item.Tag = $key; [void]$c.CampaignCombo.Items.Add($item) }
        $c.CampaignCombo.SelectedIndex = 0
        $s.Data.CampaignsLoaded = $true
    }
    # The shared demo host looks for the logo next to the package root; this package keeps it in Assets.
    $logo = Join-Path $script:SemtDemoPackageRoot 'Assets\WorkplaceCloudHub-lockup-WPF.png'
    if (Test-Path -LiteralPath $logo -PathType Leaf) { $c.HeaderLogoImage.Source = [Windows.Media.Imaging.BitmapFrame]::Create([uri]$logo) }
    $modes = @('Loop','Once','Loop - ignore run guard (first cycle)','Once - ignore run guard')
    Set-SmartM365DemoCombo WaveModeCombo $modes
    Set-SmartM365DemoCombo SingleModeCombo $modes 1
    Set-SmartM365DemoCombo AutomaticSourceCombo @('Both','AD','Intune')
    $c.SingleComputerText.Text = 'CTSO-LAP-0142'
    $c.NewWaveNameText.Text = 'WAVE-CONTOSO-DEMO'
    $c.NewWaveComputersText.Text = ((1..6 | ForEach-Object { 'CTSO-LAP-{0:0000}' -f $_ }) -join "`r`n")
    $c.NewWavePathText.Text = 'Demo/Waves/WAVE-CONTOSO-DEMO/Computers.txt'
    $c.AutomaticNamePrefixText.Text = 'CTSO-LAP-'
    $c.AutomaticNameContainsText.Text = ''
    $c.AutomaticLastLogonDaysText.Text = '45'
    $c.AutomaticExcludeStaleAdCheck.IsChecked = $true
    $c.AutomaticEvidencePathText.Text = 'Demo/Runs/_AutomaticWave/20261018-093000'
    Update-SemtDemoCampaign
    $c.ActivityText.Text = "[2026-10-18 09:30:00] DEMO - Fictional Contoso Waves loaded for both Campaigns.`r`n[2026-10-18 09:30:00] Options come from the shipped catalog. Launches, stops, inventories and endpoint actions are simulated."
}

function script:Connect-SmartM365DemoProfileEvents {
    $c = $script:SmartM365Demo.Controls
    $c.CampaignCombo.Add_SelectionChanged({ Update-SemtDemoCampaign; Write-SmartM365DemoActivity ('Campaign selected: ' + $script:SemtDemoCampaigns[(Get-SemtDemoCampaign)]) })
    $c.WaveCombo.Add_SelectionChanged({
        $c = $script:SmartM365Demo.Controls
        $c.WaveDeviceCountText.Text = if ([string]$c.WaveCombo.SelectedItem -like '*PILOT*') { '4' } else { '12' }
    })
}

function script:Invoke-SmartM365DemoProfileAction {
    param([string]$Name)
    $s = $script:SmartM365Demo; $c = $s.Controls
    switch -Regex ($Name) {
        '^(LaunchWaveButton|LaunchAllButton|LaunchSingleButton|OpenRunReportButton)$' {
            $paths = @(Export-SmartM365DemoProfileOutputs)
            Write-SmartM365DemoActivity ($Name + ' completed in demo memory. No launcher, PsExec, worker, scheduled task, endpoint action or reboot was started.')
            Show-SmartM365DemoFile $paths[0]
            return $true
        }
        '^(CreateWaveButton|AutomaticCreateButton)$' {
            $wave = if ($Name -eq 'CreateWaveButton') { $c.NewWaveNameText.Text } else { $c.AutomaticWaveNameText.Text }
            if ([string]::IsNullOrWhiteSpace($wave)) { $wave = 'WAVE-CONTOSO-DEMO' }
            $key = 'Waves:' + (Get-SemtDemoCampaign)
            $waves = @(Get-SemtDemoWaves -Campaign (Get-SemtDemoCampaign))
            if ($wave -notin $waves) { $s.Data[$key] = $waves + @($wave) }
            Update-SemtDemoCampaign
            $c.WaveCombo.SelectedIndex = $c.WaveCombo.Items.Count - 1
            Write-SmartM365DemoActivity ('Wave created in memory and NOT launched: ' + $wave)
            return $true
        }
        '^AutomaticPreviewButton$' { [void](Show-SmartM365DemoDetail -Title 'Automatic Wave preview' -Text $c.AutomaticSummaryText.Text); Write-SmartM365DemoActivity 'Automatic preview ready - fictional evidence only. Create is available for these filters.'; return $true }
        '^AutomaticRefreshInventoryButton$' { Write-SmartM365DemoActivity 'Shared inventory refresh simulated. No AD or Microsoft Graph query was made.'; return $true }
        '^(StopAllButton|StopSelectedRunButton)$' { Write-SmartM365DemoActivity 'Controlled stop simulated: no new computer starts; running workers finish. No real process was contacted.'; return $true }
        '^ForceStopSelectedRunButton$' { Write-SmartM365DemoActivity 'Forced local stop simulated. Remote endpoints are reported separately and must be verified before relaunch.'; return $true }
        '^(OpenWaveComputersButton|OpenNewWaveComputersButton)$' { [void](Show-SmartM365DemoDetail -Title 'Computers.txt' -Text ((1..12 | ForEach-Object { 'CTSO-LAP-{0:0000}' -f $_ }) -join [Environment]::NewLine)); return $true }
        '^OpenWaveConfigButton$' { [void](Show-SmartM365DemoDetail -Title 'Wave.local.json' -Text ('{ "SchemaVersion": 1, "Product": "SmartEndpointMigrationToolkit", "Campaign": "' + (Get-SemtDemoCampaign) + '", "Source": "Manual", "Options": { "ThrottleLimit": 5 } }')); return $true }
        '^(AutomaticOpenEvidenceButton|OpenWaveFolderButton|OpenRunFolderButton|OpenSingleRunFolderButton)$' { [void](Show-SmartM365DemoDetail -Title 'Fictional evidence' -Text $c.AutomaticSummaryText.Text); return $true }
        '^(SaveOptionsButton|ResetOptionsButton|RefreshWrappersButton)$' { if ($Name -eq 'ResetOptionsButton') { Update-SemtDemoCampaign }; Write-SmartM365DemoActivity ($Name + ' simulated. No configuration file was written.'); return $true }
        '^HeaderLogoLink$' { return $true }
    }
    return $false
}

function script:Export-SmartM365DemoProfileOutputs {
    $campaign = Get-SemtDemoCampaign
    $statuses = if ($campaign -eq 'Windows11Upgrade') { @('ALREADY_WINDOWS11','SETUP_UPGRADE_STARTED','WINDOWS11_HARDWARE_NOT_CAPABLE','DRYRUN_ADMIN_SHARE_UNREACHABLE') } else { @('INTUNE_ENROLLED','ENTRA_PENDING_RESOLVED_POST_CYCLE','SKIPPED_ALREADY_INTUNE_IN_INVENTORY','DRYRUN_ADMIN_SHARE_UNREACHABLE') }
    $rows = @(1..12 | ForEach-Object { [pscustomobject]@{ Computer = ('CTSO-LAP-{0:0000}' -f $_); Status = $statuses[($_ - 1) % 4]; NextAction = 'Review sample result'; CorrelationId = ('00000000-0000-4000-8000-{0:000000000000}' -f $_); Mode = 'DEMO' } })
    $body = '<p>Campaign: ' + [Net.WebUtility]::HtmlEncode($script:SemtDemoCampaigns[$campaign]) + ' | Wave: WAVE-CONTOSO-DEMO | Run: 20261018-093000-DEMO</p><table><tr><th>Computer</th><th>Status</th><th>Next action</th><th>Correlation</th></tr>'
    foreach ($row in $rows) { $body += '<tr><td>' + $row.Computer + '</td><td>' + $row.Status + '</td><td>' + $row.NextAction + '</td><td>' + $row.CorrelationId + '</td></tr>' }
    $body += '</table>'
    $html = Save-SmartM365DemoHtml -Name ($campaign + '-Run-Report-DEMO.html') -Title ('Smart Endpoint Migration Toolkit - ' + $script:SemtDemoCampaigns[$campaign] + ' Run report') -Body $body
    $csv = Get-SmartM365DemoOutputPath ($campaign + '-Run-Results-DEMO.csv')
    $rows | Export-Csv -LiteralPath $csv -NoTypeInformation -Encoding UTF8
    return @($html,$csv)
}

