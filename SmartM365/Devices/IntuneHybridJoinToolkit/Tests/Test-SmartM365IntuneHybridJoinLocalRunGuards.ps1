$ErrorActionPreference='Stop'
Set-StrictMode -Version Latest
$path=Join-Path (Split-Path -Parent $PSScriptRoot) 'Scripts\SmartM365-Invoke-IntuneHybridJoinRepairWithPsExec.ps1'
$tokens=$null; $errors=$null
$ast=[System.Management.Automation.Language.Parser]::ParseFile($path,[ref]$tokens,[ref]$errors)
if($errors.Count){throw $errors[0]}
foreach($name in @('New-LotRunMutexName','Acquire-LotRunMutex','Get-LotCancellationState','Wait-LotCancellationAware','Invoke-WithGlobalGateMutex','Read-GlobalLeaseData','Save-GlobalLeaseData','Acquire-GlobalWorkerLease','Release-GlobalWorkerLease','Remove-GlobalWorkerLeaseFileUnlocked')) {
    $fn=$ast.Find({param($n) $n -is [System.Management.Automation.Language.FunctionDefinitionAst] -and $n.Name -eq $name},$true)
    if(-not $fn){throw "Missing helper: $name"}
    . ([scriptblock]::Create($fn.Extent.Text))
}
function Assert-True($Condition,$Message){if(-not $Condition){throw "ASSERT FAILED: $Message"}}
$root=Join-Path ([IO.Path]::GetTempPath()) ('IHJ-guards-'+[guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $root | Out-Null
$mutex=$null
try {
    $mutexName=New-LotRunMutexName -LotPath $root
    $mutex=Acquire-LotRunMutex -MutexName $mutexName -LotPath $root
    $blocked=$false
    try{$second=Acquire-LotRunMutex -MutexName $mutexName -LotPath $root; $second.Dispose()}catch{$blocked=$true}
    Assert-True $blocked 'An existing LOT mutex blocks another launch.'
    $mutex.ReleaseMutex(); $mutex.Dispose(); $mutex=$null
    $mutex=Acquire-LotRunMutex -MutexName $mutexName -LotPath $root
    $script:CancellationSignalPath=Join-Path $root 'stop.signal'
    Assert-True (-not (Get-LotCancellationState).Requested) 'No signal permits queueing.'
    '{"Force":false,"Source":"SyntheticGUI"}' | Set-Content $script:CancellationSignalPath
    $state=Get-LotCancellationState
    Assert-True ($state.Requested -and -not $state.Force) 'First stop drains workers.'
    Assert-True (-not (Wait-LotCancellationAware -Seconds 10)) 'Requested stop interrupts a wait immediately.'
    '{"Force":true}' | Set-Content $script:CancellationSignalPath
    Assert-True ((Get-LotCancellationState).Force) 'Second stop requests forced local cancellation.'
    Remove-Item -LiteralPath $script:CancellationSignalPath
    $globalConcurrencyGatePath=Join-Path $root 'leases'
    New-Item -ItemType Directory $globalConcurrencyGatePath | Out-Null
    $script:globalConcurrencyMutex=$null
    $globalConcurrencyMutexName=$mutexName+'-gate'
    $GlobalConcurrencyLimit=1; $GlobalConcurrencyLeaseTimeoutMinutes=30
    $launcherInstanceId='synthetic'; $JobPollSeconds=0
    function Remove-StaleGlobalWorkerLeases { param($GatePath,$LeaseTimeoutMinutes) }
    $first=Acquire-GlobalWorkerLease -Computer 'DEVICE-EXAMPLE' -CycleNumber 1
    Assert-True (Test-Path -LiteralPath $first) 'First worker owns a persisted lease.'
    # At capacity, inject an operator stop on the retry instead of waiting or launching a worker.
    function Start-Sleep { param($Seconds) '{"Force":false}' | Set-Content $script:CancellationSignalPath }
    $second=Acquire-GlobalWorkerLease -Computer 'DEVICE-SECOND' -CycleNumber 1
    Assert-True ([string]::IsNullOrEmpty($second) -and @(Get-ChildItem $globalConcurrencyGatePath -Filter '*.json').Count -eq 1) 'Capacity is not exceeded and stop cancels a queued lease.'
    Release-GlobalWorkerLease -LeasePath $first
    Assert-True (-not (Test-Path $first)) 'Completed worker releases its lease.'
    Write-Output 'PASS: local LOT mutex, controlled/forced stop signals, lease capacity and release. No real worker or endpoint used.'
}
finally {
    if($mutex){$mutex.ReleaseMutex();$mutex.Dispose()}
    $resolved=[IO.Path]::GetFullPath($root)
    if($resolved.StartsWith([IO.Path]::GetFullPath([IO.Path]::GetTempPath())) -and (Split-Path $resolved -Leaf) -like 'IHJ-guards-*'){Remove-Item -LiteralPath $resolved -Recurse -Force}
}

