$ErrorActionPreference = 'Stop'

function Assert-True {
    param(
        [Parameter(Mandatory = $true)][bool]$Condition,
        [Parameter(Mandatory = $true)][string]$Message
    )

    if (-not $Condition) {
        throw "ASSERTION FAILED: $Message"
    }
}

$toolkitRoot = Split-Path -Parent $PSScriptRoot
$repairScriptPath = Join-Path $toolkitRoot 'Scripts\SmartM365-Invoke-IntuneHybridJoinRepair.ps1'
if (-not (Test-Path -LiteralPath $repairScriptPath -PathType Leaf)) {
    throw "Repair script not found: $repairScriptPath"
}

$tokens = $null
$parseErrors = $null
$ast = [System.Management.Automation.Language.Parser]::ParseFile(
    $repairScriptPath,
    [ref]$tokens,
    [ref]$parseErrors
)
if ($parseErrors.Count -gt 0) {
    throw "Repair script parsing failed: $($parseErrors[0].Message)"
}

$classificationFunction = @($ast.FindAll({
    param($node)
    $node -is [System.Management.Automation.Language.FunctionDefinitionAst] -and
        $node.Name -eq 'Get-MdmEnrollmentClassification'
}, $true))
Assert-True -Condition ($classificationFunction.Count -eq 1) -Message 'The MDM classification helper must exist exactly once.'
. ([scriptblock]::Create($classificationFunction[0].Extent.Text))

$bridgeOnly = Get-MdmEnrollmentClassification `
    -ProviderID 'WMI_Bridge_SCCM_Server' `
    -DiscoveryServiceFullURL '' `
    -OmadmAccountPresent $false `
    -EnterpriseMgmtTaskPresent $false
Assert-True -Condition $bridgeOnly.IsManagementBridge -Message 'WMI_Bridge_SCCM_Server must be classified as a management bridge.'
Assert-True -Condition (-not $bridgeOnly.IsMdmEnrollment) -Message 'A bridge-only registration must not be treated as an MDM enrollment.'
Assert-True -Condition (-not $bridgeOnly.IsNonIntuneMdmEnrollment) -Message 'A bridge-only registration must not block Intune auto-enrollment.'

$bridgeWithOmaDmArtifacts = Get-MdmEnrollmentClassification `
    -ProviderID 'WMI_Bridge_SCCM_Server' `
    -DiscoveryServiceFullURL '' `
    -OmadmAccountPresent $true `
    -EnterpriseMgmtTaskPresent $true
Assert-True -Condition $bridgeWithOmaDmArtifacts.IsManagementBridge -Message 'The protected bridge identity must remain recognizable when artifacts exist.'
Assert-True -Condition $bridgeWithOmaDmArtifacts.HasStrongOmaDmEvidence -Message 'Bridge diagnostics must report any accompanying strong OMA-DM evidence.'
Assert-True -Condition (-not $bridgeWithOmaDmArtifacts.IsNonIntuneMdmEnrollment) -Message 'The protected bridge identity must never enter the removable non-Intune MDM set.'

$externalMarkerOnly = Get-MdmEnrollmentClassification `
    -ProviderID 'ThirdPartyMdm' `
    -DiscoveryServiceFullURL '' `
    -OmadmAccountPresent $false `
    -EnterpriseMgmtTaskPresent $false
Assert-True -Condition (-not $externalMarkerOnly.IsMdmEnrollment) -Message 'An external provider name without OMA-DM evidence must remain an unconfirmed marker.'

$externalWithOmadm = Get-MdmEnrollmentClassification `
    -ProviderID 'ThirdPartyMdm' `
    -DiscoveryServiceFullURL '' `
    -OmadmAccountPresent $true `
    -EnterpriseMgmtTaskPresent $false
Assert-True -Condition $externalWithOmadm.IsNonIntuneMdmEnrollment -Message 'An external provider with an OMADM account must be treated as a confirmed non-Intune MDM.'

$externalWithDiscovery = Get-MdmEnrollmentClassification `
    -ProviderID '' `
    -DiscoveryServiceFullURL 'https://mdm.example.test/enrollment' `
    -OmadmAccountPresent $false `
    -EnterpriseMgmtTaskPresent $false
Assert-True -Condition $externalWithDiscovery.IsNonIntuneMdmEnrollment -Message 'An external discovery URL must confirm a non-Intune MDM enrollment.'

$intune = Get-MdmEnrollmentClassification `
    -ProviderID 'MS DM Server' `
    -DiscoveryServiceFullURL 'https://enrollment.manage.microsoft.com/enrollmentserver/discovery.svc' `
    -OmadmAccountPresent $true `
    -EnterpriseMgmtTaskPresent $true
Assert-True -Condition $intune.IsIntuneEnrollment -Message 'MS DM Server must remain the confirmed Intune provider.'
Assert-True -Condition (-not $intune.IsNonIntuneMdmEnrollment) -Message 'Intune must never be classified as a competing MDM.'

$internal = Get-MdmEnrollmentClassification `
    -ProviderID 'Cloud Authority' `
    -DiscoveryServiceFullURL '' `
    -OmadmAccountPresent $true `
    -EnterpriseMgmtTaskPresent $true
Assert-True -Condition (-not $internal.IsMdmEnrollment) -Message 'Windows internal authority registrations must remain excluded.'

$repairScriptText = Get-Content -LiteralPath $repairScriptPath -Raw
foreach ($requiredText in @(
    '$ScriptVersion = "2.10.38"',
    'ManagementBridgeDetected',
    'ManagementBridgeEnrollmentIds',
    'ManagementBridgeProviderIds',
    'ManagementBridgeDetails'
)) {
    Assert-True -Condition $repairScriptText.Contains($requiredText) -Message "Repair output is missing '$requiredText'."
}

Write-Output 'PASS: Intune Hybrid Join MDM classification tests completed.'

