try {
    Set-ItemProperty -Path "HKLM:\SYSTEM\CurrentControlSet\Services\tzautoupdate" -Name "Start" -Value 3 -ErrorAction Stop
    Write-Output "Status=Completed Service=tzautoupdate Start=3"
