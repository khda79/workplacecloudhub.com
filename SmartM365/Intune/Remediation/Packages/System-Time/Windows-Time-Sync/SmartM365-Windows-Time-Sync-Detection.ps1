#Requires -Version 5.1
# Description: Checks clock offset against the current Windows time source and requests resynchronization.
<#
.SYNOPSIS
    Checks clock offset against the current Windows time source and requests resynchronization.
.DESCRIPTION
    Standalone Intune detection, SYSTEM, 64-bit Windows PowerShell.
    Detection: 0 healthy/not applicable/deferred, 1 actionable finding, 2 technical error.
    Remediation: 0 completed/requested/deferred, 1 unresolved or technical failure.
    Keeps the existing peer list, domain hierarchy and service startup policy; never sets the clock directly.
.VERSION
    1.0.0
#>
[CmdletBinding()]
param([ValidateRange(1,3600)][int]$MaxOffsetSeconds = 120)

$Scenario = 'Windows-Time-Sync'
$Remediate = $false

$ErrorActionPreference = 'Stop'
function Write-Result {
    param([string]$Status, [string]$Reason, [string]$Detail = '')
    $line = ('{0} Status={1} Reason={2} {3}' -f $Scenario, $Status, $Reason, $Detail).Trim()
    if ($line.Length -gt 2000) { $line = $line.Substring(0, 2000) }
    if ($Remediate) {
        $logRoot = Join-Path $env:ProgramData ('SmartM365\IntuneRemediation\Logs\' + $Scenario)
        [IO.Directory]::CreateDirectory($logRoot) | Out-Null
        Add-Content -LiteralPath (Join-Path $logRoot ($Scenario + '.log')) -Encoding UTF8 -Value ((Get-Date -Format 'yyyy-MM-dd HH:mm:ss') + ' ' + $line)
    }
    Write-Output $line
}


function Get-TimeOffset {
    $sourceLines = & w32tm.exe /query /source 2>&1
    if ($LASTEXITCODE -ne 0) { return $null }
    $source = ($sourceLines -join '').Trim()
    if ($source -notmatch '^[a-zA-Z0-9_.:\-]+$') { return $null }
    $samples = & w32tm.exe /stripchart "/computer:$source" /dataonly /samples:3 /period:1 2>&1
    if ($LASTEXITCODE -ne 0) { return $null }
    $offsets = @(foreach ($line in $samples) {
        if ([string]$line -match '([+-]\d+[.,]\d+)s\s*$') {
            [math]::Abs([double]::Parse($matches[1].Replace(',','.'), [Globalization.CultureInfo]::InvariantCulture))
        }
    })
    if ($offsets.Count -lt 3) { return $null }
    return [double](($offsets | Measure-Object -Maximum).Maximum)
}

try {

    $service = Get-Service -Name W32Time -ErrorAction Stop
    $configuration = Get-CimInstance -ClassName Win32_Service -Filter "Name='W32Time'" -ErrorAction Stop
    if ($configuration.StartMode -eq 'Disabled') { Write-Result -Status Deferred -Reason TimeServiceDisabledByConfiguration; exit 0 }
    if ($service.Status -eq 'Running') {
        $offset = Get-TimeOffset
        if ($null -eq $offset) { Write-Result -Status Deferred -Reason TimeSourceUnreachableOrUnmeasurable; exit 0 }
        if ($offset -le $MaxOffsetSeconds) { Write-Result -Status Healthy -Reason OffsetWithinThreshold; exit 0 }
    }
    if (-not $Remediate) { Write-Result -Status RemediationRequired -Reason TimeServiceStoppedOrClockDrift; exit 1 }
    if ($service.Status -ne 'Running') { Start-Service -Name W32Time -ErrorAction Stop }
    & w32tm.exe /resync /rediscover 2>&1 | Out-Null
    if ($LASTEXITCODE -ne 0) { Write-Result -Status Unresolved -Reason ResynchronizationRejected; exit 1 }
    $offset = Get-TimeOffset
    if ($null -eq $offset) { Write-Result -Status Unresolved -Reason OffsetVerificationUnavailable; exit 1 }
    if ($offset -gt $MaxOffsetSeconds) { Write-Result -Status Unresolved -Reason ClockDriftPersists; exit 1 }
    Write-Result -Status Completed -Reason OffsetVerified; exit 0

}
catch {
    # Do not expose user identities, certificate subjects, job names or native output.
    Write-Result -Status Error -Reason OperationFailed -Detail ('ErrorType=' + $_.Exception.GetType().Name)
    if ($Remediate) { exit 1 } else { exit 2 }
}

