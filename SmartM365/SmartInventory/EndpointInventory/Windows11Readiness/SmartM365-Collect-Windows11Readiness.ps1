<#
.SYNOPSIS
Collect one Windows device's Microsoft hardware readiness result. Version 1.0.0.
.DESCRIPTION
Windows PowerShell 5.1. Pass the Base64-encoded bytes of the unmodified Microsoft HardwareReadiness.ps1.
Returns one object; optionally exports it as a CSV. Missing detail is UNDETERMINED.
.PARAMETER ReadinessScriptBase64
Base64-encoded bytes of a trusted, locally reviewed Microsoft HardwareReadiness.ps1.
.PARAMETER OutputPath
Optional path for a single-device CSV. Parent directory must exist.
.EXAMPLE
$text = [Convert]::ToBase64String([IO.File]::ReadAllBytes((Resolve-Path .\HardwareReadiness.ps1)))
.\SmartM365-Collect-Windows11Readiness.ps1 -ReadinessScriptBase64 $text -OutputPath .\device.csv
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory=$true)][string]$ReadinessScriptBase64,
    [string]$OutputPath
)
Set-StrictMode -Version 2
$ErrorActionPreference = 'Stop'
function Get-Check([string]$Log,[string]$Name) {
    $pattern = '(?s)(?:^|;\s*)' + [regex]::Escape($Name) + ':\s*(.*?)(?:\.\s*(PASS|FAIL|UNDETERMINED)\s*;)'
    $m = [regex]::Match($Log, $pattern, [Text.RegularExpressions.RegexOptions]::IgnoreCase)
    if (-not $m.Success) { return @{Value=''; Check='UNDETERMINED'} }
    $v=$m.Groups[1].Value.Trim()
    if ($v -match '^[^=]+=(.*)$') { $v=$Matches[1].Trim() }
    if ($Name -in @('Storage','Memory')) { $v=$v -replace 'GB$','' }
    return @{Value=$v; Check=$m.Groups[2].Value.ToUpperInvariant()}
}
$pc = Get-CimInstance Win32_ComputerSystem -ErrorAction Stop
$os = Get-CimInstance Win32_OperatingSystem -ErrorAction Stop
$cpu = @(Get-CimInstance Win32_Processor -ErrorAction Stop | Select-Object -First 1)
# Run in a child Windows PowerShell instance: the official script uses Get-WmiObject.
$temp = Join-Path ([IO.Path]::GetTempPath()) ('readiness-' + [guid]::NewGuid().ToString('N') + '.ps1')
try {
    [IO.File]::WriteAllBytes($temp,[Convert]::FromBase64String($ReadinessScriptBase64))
    $raw = @(& "$env:SystemRoot\System32\WindowsPowerShell\v1.0\powershell.exe" -NoProfile -NonInteractive -File $temp 2>&1)
    if ($LASTEXITCODE -ne 0) { throw "Microsoft readiness process exited with code $LASTEXITCODE." }
    $json = ($raw | ForEach-Object { [string]$_ }) -join "`n"
    try { $result = $json | ConvertFrom-Json -ErrorAction Stop } catch { throw 'Microsoft readiness script did not produce valid JSON.' }
    if ($null -eq $result -or $null -eq $result.PSObject.Properties['returnCode'] -or $null -eq $result.PSObject.Properties['logging'] -or $null -eq $result.PSObject.Properties['returnReason']) { throw 'Microsoft readiness JSON is missing required fields.' }
    $codes = @{ '0'='CAPABLE'; '1'='NOT CAPABLE'; '-1'='UNDETERMINED'; '-2'='FAILED TO RUN' }
    $code = [string]$result.returnCode
    if (-not $codes.ContainsKey($code)) { throw "Unexpected Microsoft returnCode: $code" }
    $checks=@{}
    foreach ($key in @('Storage','Memory','TPM','Processor','SecureBoot')) { $checks[$key]=Get-Check ([string]$result.logging) $key }
    $row = [pscustomobject][ordered]@{
        'pc.Date'=[DateTime]::UtcNow.ToString('yyyy-MM-dd HH:mm:ssZ')
        'pc.name'=[string]$env:COMPUTERNAME
        'ComputerDomain'=[string]$pc.Domain
        'pc.Manufacturer'=[string]$pc.Manufacturer
        'pc.Model'=[string]$pc.Model
        'pc.WinVersion'=[string]$os.Version
        'pc.WINEDT'=[string]$os.Caption
        'pc.Storage'=$checks.Storage.Value; 'pc.Storage_Check'=$checks.Storage.Check
        'pc.Memory'=$checks.Memory.Value; 'pc.Memory_Check'=$checks.Memory.Check
        'pc.TPM'=$checks.TPM.Value; 'pc.TPM_Check'=$checks.TPM.Check
        'pc.Processor'=if ($cpu.Count -gt 0) { [string]$cpu[0].Caption } else { '' }
        'pc.Processor_Check'=$checks.Processor.Check
        'pc.SecureBoot'=$checks.SecureBoot.Value; 'pc.SecureBoot_Check'=$checks.SecureBoot.Check
        'pc.CPU'=''; 'pc.CPU_Check'=''
        'pc.GLOBALResult'=$codes[$code]
        'MicrosoftReturnCode'=[int]$code
        'MicrosoftReason'=[string]$result.returnReason
        'MicrosoftLogging'=[string]$result.logging
    }
    if ($OutputPath) { $row | Export-Csv -LiteralPath $OutputPath -NoTypeInformation -Encoding UTF8 -ErrorAction Stop }
    $row
} finally { if (Test-Path -LiteralPath $temp) { Remove-Item -LiteralPath $temp -Force -ErrorAction SilentlyContinue } }

