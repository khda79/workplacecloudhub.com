<#
.SYNOPSIS
Verifies that five-week detail retention preserves older application trend summaries.
#>
[CmdletBinding()]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$repoRoot = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot '../../../../../../')).Path
$inventoryScript = Join-Path $PSScriptRoot '../SmartM365-Intune-DiscoveredApps-Inventory.ps1'
$evidenceScript = Join-Path $repoRoot 'SmartWorkplaceIntelligence/scripts/New-ApplicationInventoryEvidence.ps1'
Import-Module (Join-Path $repoRoot 'SmartM365/Modules/SmartM365.Core/SmartM365.Core.psd1') -Force

$tokens = $null
$errors = $null
$ast = [Management.Automation.Language.Parser]::ParseFile((Resolve-Path -LiteralPath $inventoryScript), [ref]$tokens, [ref]$errors)
if ($errors.Count) { throw ($errors | Out-String) }
$functionAst = $ast.Find({ param($node) $node -is [Management.Automation.Language.FunctionDefinitionAst] -and $node.Name -eq 'Save-DiscoveredAppsHistoricalSummaries' }, $true)
if (-not $functionAst) { throw 'Summary retention function is missing.' }
. ([scriptblock]::Create($functionAst.Extent.Text))
function WriteLog { param([string]$Message, [string]$Level) }
$global:EnableSharePointUpload = $false

$testRoot = Join-Path ([IO.Path]::GetTempPath()) ('SmartM365-DiscoveredApps-Retention-' + [guid]::NewGuid().ToString('N'))
$dataRoot = Join-Path $testRoot 'DATA'
$appsRoot = Join-Path $dataRoot 'DATA-ALL/Intune/Applications/DiscoveredApps'
$weeklyRoot = Join-Path $appsRoot 'WeeklyHistory'
$summaryRoot = Join-Path $appsRoot 'SummaryHistory'
$latestRoot = Join-Path $dataRoot 'DATA-LAST'
$sample = [pscustomobject]@{
    TenantKey = 'test'; AppId = 'app-1'; AppName = 'Example app'; AppVersion = '1.0'
    AppPublisher = 'Example publisher'; Platform = 'windows'; DeviceCount = 1
    CollectionScope = 'AllPlatforms'; RelationCollectionScope = 'All'
}

try {
    New-Item -ItemType Directory -Path $weeklyRoot, $latestRoot -Force | Out-Null
    foreach ($weekNumber in 1..7) {
        $week = '2020-W{0:00}' -f $weekNumber
        $folder = Join-Path $weeklyRoot $week
        New-Item -ItemType Directory -Path $folder -Force | Out-Null
        $path = Join-Path $folder 'Intune_DiscoveredApps_Summary.csv'
        $sample | Export-Csv -LiteralPath $path -NoTypeInformation -Encoding utf8NoBOM
        [IO.File]::SetLastWriteTimeUtc($path, [datetime]::SpecifyKind(([datetime]'2020-01-01').AddDays(7 * $weekNumber), [DateTimeKind]::Utc))
    }
    $sample | Export-Csv -LiteralPath (Join-Path $latestRoot 'Intune_DiscoveredApps_Summary.csv') -NoTypeInformation -Encoding utf8NoBOM
    [pscustomobject]@{ TenantKey = 'test'; AppId = 'app-1'; DeviceId = 'device-1' } |
        Export-Csv -LiteralPath (Join-Path $latestRoot 'Intune_DiscoveredApps_AppDeviceRelations.csv') -NoTypeInformation -Encoding utf8NoBOM

    Save-DiscoveredAppsHistoricalSummaries -WeeklyHistoryRoot $weeklyRoot -SummaryHistoryRoot $summaryRoot -RetentionWeeks 5
    $archived = @(Get-ChildItem -LiteralPath $summaryRoot -Directory | Sort-Object Name)
    if (($archived.Name -join ',') -ne '2020-W01,2020-W02,2020-W03') { throw "Unexpected archived weeks: $($archived.Name -join ',')" }
    foreach ($week in $archived.Name) { Remove-Item -LiteralPath (Join-Path $weeklyRoot $week) -Recurse -Force }

    $trendPath = Join-Path $testRoot 'ApplicationTrendEvidence.csv'
    & $evidenceScript -DataRoot $dataRoot -InventoryOutputPath (Join-Path $testRoot 'ApplicationInventoryEvidence.csv') -TrendOutputPath $trendPath
    $trend = @(Import-Csv -LiteralPath $trendPath)
    if ($trend.Count -ne 7) { throw "Expected seven trend weeks; got $($trend.Count)." }
    if ((@($trend.'Snapshot Week' | Sort-Object -Unique).Count) -ne 7) { throw 'Trend contains duplicate or missing weeks.' }

    Add-Content -LiteralPath (Join-Path $summaryRoot '2020-W01/Intune_DiscoveredApps_Summary.csv') -Value 'tampered'
    $rejected = $false
    try { & $evidenceScript -DataRoot $dataRoot -InventoryOutputPath (Join-Path $testRoot 'ApplicationInventoryEvidence.csv') -TrendOutputPath $trendPath } catch { $rejected = $_.Exception.Message -like '*provenance verification*' }
    if (-not $rejected) { throw 'Tampered archived summary was not rejected.' }
    'Discovered Apps retention fixture passed: seven trend weeks retained; tampering rejected.'
}
finally {
    $fullRoot = [IO.Path]::GetFullPath($testRoot)
    $fullTemp = [IO.Path]::GetFullPath([IO.Path]::GetTempPath()).TrimEnd('\') + '\'
    if ($fullRoot.StartsWith($fullTemp, [StringComparison]::OrdinalIgnoreCase) -and (Test-Path -LiteralPath $fullRoot)) {
        Remove-Item -LiteralPath $fullRoot -Recurse -Force
    }
}

