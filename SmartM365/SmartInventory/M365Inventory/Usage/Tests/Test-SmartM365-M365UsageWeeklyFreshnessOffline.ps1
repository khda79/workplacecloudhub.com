<#
.SYNOPSIS
    Offline checks for delayed Microsoft 365 weekly report dates.
.DESCRIPTION
    Runs the collector's actual history decision on synthetic CSVs. No Graph,
    tenant collection, or publication is performed.
.VERSION
1.0
#>

[CmdletBinding()]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$collector = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot '..\SmartM365-M365UserActivity-Inventory.ps1')).Path
$tokens = $null
$parseErrors = $null
$ast = [System.Management.Automation.Language.Parser]::ParseFile($collector,[ref]$tokens,[ref]$parseErrors)
if ($parseErrors.Count -gt 0) { throw ($parseErrors | Out-String) }
$definition = @($ast.FindAll({
    param($node)
    $node -is [System.Management.Automation.Language.FunctionDefinitionAst] -and $node.Name -eq 'Test-M365UsageWeeklySnapshotDate'
},$true))
if ($definition.Count -ne 1) { throw 'Expected one weekly report date decision function.' }
Invoke-Expression $definition[0].Extent.Text

$script:warnings = [System.Collections.Generic.List[string]]::new()
function WriteLog { param([string]$Message,[string]$Level) if ($Level -eq 'WARNING') { $script:warnings.Add($Message) | Out-Null } }
function Assert-Case { param([bool]$Condition,[string]$Message) if (-not $Condition) { throw $Message } }
function Assert-Rejected { param([scriptblock]$Action,[string]$Pattern,[string]$Message)
    $caught = $false
    try { & $Action | Out-Null } catch { $caught = $_.Exception.Message -match $Pattern }
    Assert-Case $caught $Message
}

$tempRoot = Join-Path ([IO.Path]::GetTempPath()) ('SmartM365-UsageFreshness-' + [guid]::NewGuid().ToString('N'))
$fileName = 'M365_Teams_UserActivity.csv'
$weekDate = [datetime]'2026-10-12'
try {
    New-Item -ItemType Directory -Path $tempRoot -Force | Out-Null
    Assert-Case (Test-M365UsageWeeklySnapshotDate -RefreshDate ([datetime]'2026-10-04') -HistoryRootPath $tempRoot -FileName $fileName -WeekDate $weekDate) 'First history week was rejected.'

    $week41 = Join-Path $tempRoot '2026-W41'
    New-Item -ItemType Directory -Path $week41 -Force | Out-Null
    'ReportRefreshDate,Value','2026-10-04,one' | Set-Content -LiteralPath (Join-Path $week41 $fileName) -Encoding UTF8
    Assert-Case (Test-M365UsageWeeklySnapshotDate -RefreshDate ([datetime]'2026-10-05') -HistoryRootPath $tempRoot -FileName $fileName -WeekDate $weekDate) 'A newer report date was rejected.'
    Assert-Case (-not (Test-M365UsageWeeklySnapshotDate -RefreshDate ([datetime]'2026-10-04') -HistoryRootPath $tempRoot -FileName $fileName -WeekDate $weekDate)) 'A cross-week repeat was added to history.'
    Assert-Case ($script:warnings.Count -eq 1 -and $script:warnings[0] -match 'duplicate WeeklyHistory snapshot will be skipped') 'Repeated date was not reported as a warning.'
    Assert-Rejected { Test-M365UsageWeeklySnapshotDate -RefreshDate ([datetime]'2026-10-03') -HistoryRootPath $tempRoot -FileName $fileName -WeekDate $weekDate } 'older than weekly history' 'An older report date was published.'

    $week40 = Join-Path $tempRoot '2026-W40'
    New-Item -ItemType Directory -Path $week40 -Force | Out-Null
    'ReportRefreshDate,Value','2026-10-05,older-week-newer-date' | Set-Content -LiteralPath (Join-Path $week40 $fileName) -Encoding UTF8
    Assert-Rejected { Test-M365UsageWeeklySnapshotDate -RefreshDate ([datetime]'2026-10-04') -HistoryRootPath $tempRoot -FileName $fileName -WeekDate $weekDate } 'older than weekly history' 'An equal date in one week hid a later date in another.'
    'ReportRefreshDate,Value','2026-09-28,older-week' | Set-Content -LiteralPath (Join-Path $week40 $fileName) -Encoding UTF8

    $week42 = Join-Path $tempRoot '2026-W42'
    New-Item -ItemType Directory -Path $week42 -Force | Out-Null
    'ReportRefreshDate,Value','2026-10-09,two' | Set-Content -LiteralPath (Join-Path $week42 $fileName) -Encoding UTF8
    Assert-Case (Test-M365UsageWeeklySnapshotDate -RefreshDate ([datetime]'2026-10-09') -HistoryRootPath $tempRoot -FileName $fileName -WeekDate $weekDate) 'Same-week retry was rejected.'
    Assert-Rejected { Test-M365UsageWeeklySnapshotDate -RefreshDate ([datetime]'2026-10-08') -HistoryRootPath $tempRoot -FileName $fileName -WeekDate $weekDate } 'older than weekly history' 'Current-week regression was published.'

    'ReportRefreshDate,Value','bad-date,two' | Set-Content -LiteralPath (Join-Path $week42 $fileName) -Encoding UTF8
    Assert-Rejected { Test-M365UsageWeeklySnapshotDate -RefreshDate ([datetime]'2026-10-10') -HistoryRootPath $tempRoot -FileName $fileName -WeekDate $weekDate } 'invalid Report Refresh Date' 'Malformed history was silently accepted.'
    'PASS: cross-week repeats warn and skip history; newer and same-week dates publish; regressions and malformed history fail.'
}
finally {
    $resolved = [IO.Path]::GetFullPath($tempRoot)
    $base = [IO.Path]::GetFullPath([IO.Path]::GetTempPath()).TrimEnd('\') + '\'
    if ($resolved.StartsWith($base,[StringComparison]::OrdinalIgnoreCase) -and (Split-Path $resolved -Leaf) -like 'SmartM365-UsageFreshness-*') {
        Remove-Item -LiteralPath $resolved -Recurse -Force -ErrorAction SilentlyContinue
    }
}

