#requires -Version 7.0
[CmdletBinding()]
param()
$ErrorActionPreference = 'Stop'
$inventory = (Resolve-Path (Join-Path $PSScriptRoot '../SmartM365-Licences-Inventory.ps1')).Path
$root = (Resolve-Path (Join-Path $PSScriptRoot '../../../..')).Path
$modulePath = Join-Path $root 'Modules/SmartM365.Core/SmartM365.Core.psd1'
$tokens = $null; $errors = $null
$ast = [Management.Automation.Language.Parser]::ParseFile($inventory, [ref]$tokens, [ref]$errors)
if ($errors.Count) { throw ($errors | Out-String) }
$source = $ast.Extent.Text
$loadPosition = $source.IndexOf("'SmartM365-InventoryLifecycle.ps1'")
$startPosition = $source.IndexOf('Start-SmartM365InventoryRun -ScriptPath $PSCommandPath -RequireReturn')
$policyPosition = $source.IndexOf('Initialize-SmartM365CollectorUploadContext')
if ($loadPosition -lt 0 -or $startPosition -le $loadPosition -or $policyPosition -le $startPosition) { throw 'The collector does not load and start its lifecycle before its upload policy.' }
$outer = @($ast.EndBlock.Statements | Where-Object { $_ -is [Management.Automation.Language.TryStatementAst] -and $_.Finally -and $_.Finally.Extent.Text.Contains('Complete-SmartM365InventoryRun') })
if ($outer.Count -ne 1) { throw 'Expected one outer lifecycle guard.' }
$inner = @($outer[0].Body.Statements | Where-Object { $_ -is [Management.Automation.Language.TryStatementAst] -and $_.Body.Extent.Text.Contains('Initialize-SmartM365CollectorUploadContext') })
if ($inner.Count -ne 1) { throw 'Expected one collector initialization block.' }
$prefix = @($inner[0].Body.Statements | Select-Object -First 3)
if ($prefix.Count -ne 3 -or $prefix[2].Extent.Text -notmatch 'Initialize-SmartM365CollectorUploadContext') { throw 'Initialization sequence changed.' }
. (Join-Path (Split-Path $modulePath -Parent) 'SmartM365-InventoryLifecycle.ps1')
$testRoot = Join-Path ([IO.Path]::GetTempPath()) 'SmartM365-Offline-LicenseLifecycle'
$OutputPath = Join-Path $testRoot 'DATA-ALL'
$global:LogPath = Join-Path $testRoot 'LOG-ALL'
$global:EnableSharePointUpload = $false
$global:SmartM365GlobalConfig = @{}
$ScriptLocalConfig = @{}
function InitializeScriptEnvironment { param($OutputPath, $LogFileName) return $OutputPath }
function Get-ScriptLocalConfigValue { param($Config, $Name, $DefaultValue) return (Join-Path $testRoot 'DATA-LAST') }
$smartM365RunGuard = Start-SmartM365InventoryRun -ScriptPath $inventory -RequireReturn
try {
    foreach ($statement in $prefix) { Invoke-Expression $statement.Extent.Text }
    if (-not $global:SmartM365CollectorUploadPolicies -or $global:EnableSharePointUpload) { throw 'Upload policy was not initialized safely.' }
    $smartM365RunGuard.ReachedTerminal = $true
    $smartM365RunGuard.ReturnedNormally = $true
} finally {
    Complete-SmartM365InventoryRun -State $smartM365RunGuard
}
if ($global:SmartM365InventoryRun) { throw 'Lifecycle state was not released.' }
'PASS: real license initialization accepts the lifecycle and restores state without network or publication.'

