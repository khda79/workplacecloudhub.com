[CmdletBinding()]
param([string]$Tenant='test',[string]$PricingSourceCsvPath,[switch]$ValidateOnly,[switch]$SelfTest,[switch]$EnableConfiguredExternalActions,[string]$OutputPath,[string]$LatestCsvFolderPath)
Set-StrictMode -Version Latest
$ErrorActionPreference='Stop';$ScriptVersion='1.0.0';$script:Runtime=$null;$script:CompletionStatus='Success';$script:CompletionError=$null

function ConvertTo-LicensePriceRows{
    param([object[]]$InputRows,[string]$RunId,[string]$CollectedAtUtc)
    $seen=@{};$rows=[System.Collections.Generic.List[object]]::new()
    foreach($row in $InputRows){
        $sku=[string](Get-SmartM365EvidenceProperty $row @('SkuPartNumber'));$currency=[string](Get-SmartM365EvidenceProperty $row @('Currency'));$priceText=[string](Get-SmartM365EvidenceProperty $row @('UnitPriceMonthly'))
        if([string]::IsNullOrWhiteSpace($sku)-or $currency-notmatch'^[A-Z]{3}$'){throw "Invalid SKU or ISO currency in license pricing source: '$sku' / '$currency'."}
        $price=0.0;if(-not[double]::TryParse($priceText,[System.Globalization.NumberStyles]::Number,[System.Globalization.CultureInfo]::InvariantCulture,[ref]$price)-or $price-lt 0){throw "Invalid UnitPriceMonthly for SKU '$sku'. Use an invariant non-negative number."}
        $from=[string](Get-SmartM365EvidenceProperty $row @('EffectiveFrom'));$to=[string](Get-SmartM365EvidenceProperty $row @('EffectiveTo'));$key="$sku|$currency|$from|$to";if($seen.ContainsKey($key)){throw "Duplicate license price period: $key"};$seen[$key]=$true
        if($from-and $to-and [datetime]$from-gt[datetime]$to){throw "EffectiveFrom is after EffectiveTo for SKU '$sku'."}
        $rows.Add([pscustomobject][ordered]@{RunId=$RunId;CollectedAtUtc=$CollectedAtUtc;CollectionStatus='GovernedInput';IsPartialInventory=$false;SourceScriptVersion=$ScriptVersion;SkuPartNumber=$sku;Currency=$currency;UnitPriceMonthly=$price;BillingCadence=[string](Get-SmartM365EvidenceProperty $row @('BillingCadence') 'Monthly');EffectiveFrom=$from;EffectiveTo=$to;PriceSource=[string](Get-SmartM365EvidenceProperty $row @('PriceSource'));PricingBasis=[string](Get-SmartM365EvidenceProperty $row @('PricingBasis'));ContractReference=[string](Get-SmartM365EvidenceProperty $row @('ContractReference'));IsEstimated=[string](Get-SmartM365EvidenceProperty $row @('IsEstimated') 'False')})
    }
    return @($rows)
}
if($SelfTest){Import-Module (Join-Path $PSScriptRoot '..\..\Common\SmartM365.EvidenceCollector.Common.psm1') -Force;$sample=[pscustomobject]@{SkuPartNumber='SPE_E5';Currency='EUR';UnitPriceMonthly='42.50';EffectiveFrom='2026-01-01';EffectiveTo='2026-12-31';PriceSource='Contract'};$test=ConvertTo-LicensePriceRows @($sample) r n;if($test.Count-ne 1-or $test[0].UnitPriceMonthly-ne 42.5){throw 'License pricing self-test failed.'};'PASS: License pricing offline contract';return}
try{
    $tenantContextPath=Join-Path (Split-Path (Split-Path (Split-Path $PSScriptRoot -Parent) -Parent) -Parent) 'Config\SmartM365-TenantContext.ps1';. $tenantContextPath
    $effectiveConfig=Initialize-SmartM365TenantContext -Tenant $Tenant -StartPath $PSScriptRoot
    Import-Module (Join-Path $PSScriptRoot '..\..\Common\SmartM365.EvidenceCollector.Common.psm1') -Force
    $script:Runtime=Initialize-SmartM365EvidenceRuntime -ScriptPath $PSCommandPath -EffectiveConfig $effectiveConfig -DefaultOutputRelativePath 'M365\Licensing\Pricing' -OutputPath $OutputPath -LatestCsvFolderPath $LatestCsvFolderPath -ValidateOnly:$ValidateOnly -EnableConfiguredExternalActions:$EnableConfiguredExternalActions
    if([string]::IsNullOrWhiteSpace($PricingSourceCsvPath)){$PricingSourceCsvPath=[string](Get-SmartM365EvidenceProperty $script:Runtime.Config @('PricingSourceCsvPath'))}
    if([string]::IsNullOrWhiteSpace($PricingSourceCsvPath)-or -not(Test-Path -LiteralPath $PricingSourceCsvPath -PathType Leaf)){throw 'PricingSourceCsvPath must reference an existing private CSV.'}
    $rows=ConvertTo-LicensePriceRows @(Import-Csv -LiteralPath $PricingSourceCsvPath) $script:Runtime.RunId $script:Runtime.CollectedAtUtc
    if($rows.Count-eq 0){throw 'The license pricing source contains no rows.'}
    if($ValidateOnly){Write-SmartM365EvidenceLog -Message ("License pricing source valid; {0} governed row(s). No CSV published." -f $rows.Count) -Level SUCCESS;return}
    Export-SmartM365EvidenceDataset $script:Runtime 'M365_License_Prices' $rows @('RunId','CollectedAtUtc','CollectionStatus','IsPartialInventory','SourceScriptVersion','SkuPartNumber','Currency','UnitPriceMonthly','BillingCadence','EffectiveFrom','EffectiveTo','PriceSource','PricingBasis','ContractReference','IsEstimated')|Out-Null
}catch{$script:CompletionStatus='Failed';$script:CompletionError=$_;throw}finally{if($script:Runtime){Complete-SmartM365EvidenceRuntime -Status $script:CompletionStatus -ErrorRecord $script:CompletionError -FailureStage 'LicensePricingInventory'}}

