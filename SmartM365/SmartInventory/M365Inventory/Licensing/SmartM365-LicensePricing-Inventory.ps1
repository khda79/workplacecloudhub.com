<#
.SYNOPSIS
Validates and normalizes a private, governed Microsoft 365 license-pricing CSV.
.VERSION
1.0.0
.REQUIREMENTS
No Microsoft Graph permission. PricingSourceCsvPath must reference a private CSV.
