Set-StrictMode -Version Latest
$ErrorActionPreference='Stop';$ScriptVersion='1.0.6';$script:Runtime=$null;$script:CompletionStatus='Success';$script:CompletionError=$null

function ConvertTo-ConditionalAccessRows{
    param([object[]]$Policies,[string]$RunId,[string]$CollectedAtUtc)
    $policyRows=[System.Collections.Generic.List[object]]::new();$targetRows=[System.Collections.Generic.List[object]]::new()
    foreach($policy in $Policies){
        $conditions=Get-SmartM365EvidenceProperty $policy @('conditions') $null;$users=Get-SmartM365EvidenceProperty $conditions @('users') $null;$apps=Get-SmartM365EvidenceProperty $conditions @('applications') $null
        $policyId=[string](Get-SmartM365EvidenceProperty $policy @('id'))
        $policyRows.Add([pscustomobject][ordered]@{RunId=$RunId;CollectedAtUtc=$CollectedAtUtc;CollectionStatus='Observed';IsPartialInventory=$false;SourceScriptVersion=$ScriptVersion;PolicyId=$policyId;DisplayName=[string](Get-SmartM365EvidenceProperty $policy @('displayName'));State=[string](Get-SmartM365EvidenceProperty $policy @('state'));CreatedDateTime=[string](Get-SmartM365EvidenceProperty $policy @('createdDateTime'));ModifiedDateTime=[string](Get-SmartM365EvidenceProperty $policy @('modifiedDateTime'));IncludedUsers=ConvertTo-SmartM365EvidenceText (Get-SmartM365EvidenceProperty $users @('includeUsers') @());ExcludedUsers=ConvertTo-SmartM365EvidenceText (Get-SmartM365EvidenceProperty $users @('excludeUsers') @());IncludedGroups=ConvertTo-SmartM365EvidenceText (Get-SmartM365EvidenceProperty $users @('includeGroups') @());ExcludedGroups=ConvertTo-SmartM365EvidenceText (Get-SmartM365EvidenceProperty $users @('excludeGroups') @());IncludedApplications=ConvertTo-SmartM365EvidenceText (Get-SmartM365EvidenceProperty $apps @('includeApplications') @());ExcludedApplications=ConvertTo-SmartM365EvidenceText (Get-SmartM365EvidenceProperty $apps @('excludeApplications') @());ConditionsJson=ConvertTo-SmartM365EvidenceJson $conditions;GrantControlsJson=ConvertTo-SmartM365EvidenceJson (Get-SmartM365EvidenceProperty $policy @('grantControls') $null);SessionControlsJson=ConvertTo-SmartM365EvidenceJson (Get-SmartM365EvidenceProperty $policy @('sessionControls') $null)})
        foreach($dimension in @(@('IncludeUser',$users,'includeUsers'),@('ExcludeUser',$users,'excludeUsers'),@('IncludeGroup',$users,'includeGroups'),@('ExcludeGroup',$users,'excludeGroups'),@('IncludeApplication',$apps,'includeApplications'),@('ExcludeApplication',$apps,'excludeApplications'))){foreach($target in @(Get-SmartM365EvidenceProperty $dimension[1] @($dimension[2]) @())){$targetRows.Add([pscustomobject][ordered]@{RunId=$RunId;CollectedAtUtc=$CollectedAtUtc;CollectionStatus='Observed';IsPartialInventory=$false;SourceScriptVersion=$ScriptVersion;PolicyId=$policyId;PolicyDisplayName=[string](Get-SmartM365EvidenceProperty $policy @('displayName'));PolicyState=[string](Get-SmartM365EvidenceProperty $policy @('state'));TargetType=$dimension[0];TargetId=[string]$target})}}
    }
    return [pscustomobject]@{Policies=@($policyRows);Targets=@($targetRows)}
}
if($SelfTest){Import-Module (Join-Path $PSScriptRoot '..\..\..\Common\SmartM365.EvidenceCollector.Common.psd1') -MinimumVersion '1.0.22' -Force;$sample=[pscustomobject]@{id='p';displayName='Require MFA';state='enabled';conditions=[pscustomobject]@{users=[pscustomobject]@{includeUsers=@('All');excludeUsers=@();includeGroups=@();excludeGroups=@()};applications=[pscustomobject]@{includeApplications=@('All');excludeApplications=@()}}};$test=ConvertTo-ConditionalAccessRows @($sample) r n;if($test.Policies.Count-ne 1 -or $test.Targets.Count-ne 2){throw 'Conditional Access self-test failed.'};'PASS: Conditional Access offline contract';$smartM365RunGuard.ReachedTerminal=$true; $smartM365RunGuard.ExplicitExit=$true; return}
try{
    $tenantContextPath=Join-Path (Split-Path (Split-Path (Split-Path (Split-Path $PSScriptRoot -Parent) -Parent) -Parent) -Parent) 'Config\SmartM365-TenantContext.ps1';. $tenantContextPath
    $effectiveConfig=Initialize-SmartM365TenantContext -Tenant $Tenant -StartPath $PSScriptRoot
    Import-Module (Join-Path $PSScriptRoot '..\..\..\Common\SmartM365.EvidenceCollector.Common.psd1') -MinimumVersion '1.0.22' -Force
    $script:Runtime=Initialize-SmartM365EvidenceRuntime -ScriptPath $PSCommandPath -EffectiveConfig $effectiveConfig -DefaultOutputRelativePath 'M365\Security\ConditionalAccess' -OutputPath $OutputPath -LatestCsvFolderPath $LatestCsvFolderPath -ValidateOnly:$ValidateOnly -EnableConfiguredExternalActions:$EnableConfiguredExternalActions
    Start-SmartM365SourceReceipt -ScriptPath $PSCommandPath -SourceRootPath $script:Runtime.LatestCsvFolderPath -ReadOnly:($ValidateOnly -or $SelfTest)
    Connect-SmartM365EvidenceGraph $script:Runtime @('Policy.Read.All') -InteractiveAuth:$InteractiveAuth
    $raw=@(Get-SmartM365EvidenceGraphCollection -Uri 'https://graph.microsoft.com/v1.0/identity/conditionalAccess/policies' -MaxItems $MaxItems)
    if($ValidateOnly){Write-SmartM365EvidenceLog -Message ("Conditional Access endpoint available; {0} policy record(s). No CSV published." -f $raw.Count) -Level SUCCESS;$smartM365RunGuard.ReachedTerminal=$true; $smartM365RunGuard.ExplicitExit=$true; return}
    $rows=ConvertTo-ConditionalAccessRows $raw $script:Runtime.RunId $script:Runtime.CollectedAtUtc
    Export-SmartM365EvidenceDataset $script:Runtime 'M365_Entra_ConditionalAccessPolicies' $rows.Policies @('RunId','CollectedAtUtc','CollectionStatus','IsPartialInventory','SourceScriptVersion','PolicyId','DisplayName','State','CreatedDateTime','ModifiedDateTime','IncludedUsers','ExcludedUsers','IncludedGroups','ExcludedGroups','IncludedApplications','ExcludedApplications','ConditionsJson','GrantControlsJson','SessionControlsJson')|Out-Null
    Export-SmartM365EvidenceDataset $script:Runtime 'M365_Entra_ConditionalAccessPolicyTargets' $rows.Targets @('RunId','CollectedAtUtc','CollectionStatus','IsPartialInventory','SourceScriptVersion','PolicyId','PolicyDisplayName','PolicyState','TargetType','TargetId')|Out-Null

    $smartM365RunGuard.ReachedTerminal=$true
}catch{
    if ($_.Exception -is [Management.Automation.PipelineStoppedException] -or $_.Exception -is [OperationCanceledException]) { throw }
    $smartM365RunGuard.ErrorRecord=$_
$script:CompletionStatus='Failed';$script:CompletionError=$_;throw}finally{
    $smartM365RunGuard.InCleanup=$true
try{Disconnect-MgGraph -ErrorAction SilentlyContinue|Out-Null; Set-SmartM365InventoryConnectionOwnership -Connection Graph -Owned $false}catch{};if($script:Runtime){Complete-SmartM365EvidenceRuntime -Status $script:CompletionStatus -ErrorRecord $script:CompletionError -FailureStage 'ConditionalAccessInventory'}}
    $smartM365RunGuard.ReachedTerminal=$true
    $smartM365RunGuard.ReturnedNormally=$true
} catch {
    if ($_.Exception -isnot [Management.Automation.PipelineStoppedException] -and $_.Exception -isnot [OperationCanceledException]) { $smartM365RunGuard.ErrorRecord=$_ }
    throw
} finally {
    Complete-SmartM365InventoryRun -State $smartM365RunGuard
    if($smartM365RunGuard.ExitCode -eq 130){exit 130}
}
