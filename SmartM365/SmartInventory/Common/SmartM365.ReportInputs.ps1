# Persist only the structured inputs that cannot be recovered from a published CSV.
# The collector never stores an outgoing message or workbook in this manifest.
function Save-SmartM365ReportInputs {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][string]$Producer,
        [Parameter(Mandatory)][string]$LatestFolder,
        [Parameter(Mandatory)][string]$TenantKey,
        [string[]]$Files = @(),
        [hashtable]$InputData,
        [string]$BatchId = '',
        [string]$BatchManifestHash = ''
    )
    try {
        if ($Producer -notmatch '^SmartM365-[a-zA-Z0-9_-]+$' -or -not $TenantKey) { throw 'Missing collected report identity.' }
        $publicationCommand = Get-Command Get-CoreSmartM365CurrentSourcePublication,Get-SmartM365CurrentSourcePublication -ErrorAction SilentlyContinue | Select-Object -First 1
        $publication = if ($publicationCommand) { & $publicationCommand }
        $hashes = @{}
        foreach ($file in $Files) {
            if ([IO.Path]::GetFileName($file) -cne $file) { throw "Invalid current export name: $file" }
            $path = [IO.Path]::GetFullPath((Join-Path $LatestFolder $file))
            $hashes[$file] = if ($publication -and $publication.Hashes.ContainsKey($path)) { $publication.Hashes[$path] }
                else { (Get-FileHash -LiteralPath $path -Algorithm SHA256 -ErrorAction Stop).Hash }
        }
        $manifest = @{SchemaVersion=1; Producer=$Producer; TenantKey=$TenantKey; Files=$hashes; BatchId=$BatchId; BatchManifestHash=$BatchManifestHash; Inputs=$InputData}
        $directory = Join-Path $LatestFolder '.report-input'
        $null = [IO.Directory]::CreateDirectory($directory)
        if ((Get-Item -LiteralPath $directory -Force).Attributes -band [IO.FileAttributes]::ReparsePoint) { throw 'Linked report input directory is not accepted.' }
        $destination = Join-Path $directory ($Producer + '.clixml.txt')
        $writer = Get-Command Write-CoreSmartM365TextAtomically,Write-SmartM365TextAtomically -ErrorAction SilentlyContinue | Select-Object -First 1
        if (-not $writer) { throw 'Atomic text writer is unavailable.' }
        & $writer -Path $destination -Content ([System.Management.Automation.PSSerializer]::Serialize($manifest, 20)) -ErrorAction Stop
    } catch {
        Write-Warning ("Could not save {0} report inputs for mail-only: {1}" -f $Producer,$_.Exception.Message)
    }
}

function Get-SmartM365ReportFileReference {
    param([string]$Path)
    $item = Get-Item -LiteralPath $Path -ErrorAction Stop
    $uploaded = Get-Variable SmartM365SharePointUploadedFiles -Scope Global -ValueOnly -ErrorAction SilentlyContinue
    $upload = $uploaded | Where-Object LocalFilePath -EQ $item.FullName | Select-Object -Last 1
    [pscustomobject]@{
        Name=$item.Name; Path=$item.FullName; SizeKB=[math]::Round(($item.Length / 1KB),1)
        WebUrl=$(if ($upload) { $upload.WebUrl }); SharePointPath=$(if ($upload) { $upload.SharePointPath })
    }
}

function Get-SmartM365ReportUploadReference {
    param([string[]]$Paths)
    $uploaded = Get-Variable SmartM365SharePointUploadedFiles -Scope Global -ValueOnly -ErrorAction SilentlyContinue
    foreach ($record in @($uploaded)) {
        if ($record -and $record.LocalFilePath -in $Paths) {
            [pscustomobject]@{LocalFilePath=$record.LocalFilePath; WebUrl=$record.WebUrl; SharePointPath=$record.SharePointPath}
        }
    }
}

