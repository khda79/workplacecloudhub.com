<#
.SYNOPSIS
Generates the SmartInventory\LaunchersByOrchestrator and SmartInventory\Launchers\Jobs launchers
from the jobs manifest template.

.DESCRIPTION
Each LaunchersByOrchestrator launcher submits one job through SmartM365-Inventory-Pipeline.ps1
-Job ... -Collect: the resident orchestrators run it on its elected server with their shared
claims, locks and dependency rules, and the launcher waits for the result. A generic launcher
accepts one or more job names.

Each Launchers\Jobs\Start-<JobName>.cmd runs the job immediately on the current server, outside
the orchestrator, with the command the orchestrator builds: the template Arguments, the engine
of PowerShellEdition, -Tenant (prod unless SMARTM365_ORCHESTRATOR_TENANT is set) and -Connect
when the script declares it. A job with a LauncherPath calls that launcher with the Arguments,
as the orchestrator does. Extra options given to a launcher are appended.

Launchers are generated for every non-manual job of the template; a job that is disabled in the
shared manifest is refused at submission time.

With -Check the script only compares the expected launchers with both folders and exits 1 when
they differ (used by the offline tests).

.PARAMETER Check
Compares without writing.

.VERSION
1.1.0
#>
#requires -Version 7.2
[CmdletBinding()]
param([switch]$Check)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$tenantContextPath = Join-Path -Path $PSScriptRoot -ChildPath '..\..\Config\SmartM365-TenantContext.ps1'
if (-not (Test-Path -LiteralPath $tenantContextPath -PathType Leaf)) { throw "SmartM365 tenant context not found: $tenantContextPath" }
. $tenantContextPath
Write-SmartM365StartupBanner

$templatePath = Join-Path -Path $PSScriptRoot -ChildPath 'Orchestrator-Jobs.json.template'
$smartInventoryRoot = Split-Path -Path $PSScriptRoot -Parent
$launcherRoot = Join-Path -Path $smartInventoryRoot -ChildPath 'LaunchersByOrchestrator'
$jobLauncherRoot = Join-Path -Path $smartInventoryRoot -ChildPath 'Launchers\Jobs'
$template = Get-Content -LiteralPath $templatePath -Raw | ConvertFrom-Json -Depth 100

$pwshBlock = @'
set "PWSH="
set "PWSH_X64=%ProgramFiles%\PowerShell\7\pwsh.exe"
set "PWSH_X86="
if not "%ProgramFiles(x86)%"=="" set "PWSH_X86=%ProgramFiles(x86)%\PowerShell\7\pwsh.exe"
if exist "%PWSH_X64%" set "PWSH=%PWSH_X64%"
if not defined PWSH if defined PWSH_X86 if exist "%PWSH_X86%" set "PWSH=%PWSH_X86%"
if not defined PWSH for /f "delims=" %%I in ('where pwsh.exe 2^>nul') do if not defined PWSH set "PWSH=%%I"
if not defined PWSH (
    echo PowerShell 7 ^(pwsh.exe^) was not found.
    echo Install PowerShell 7 or add pwsh.exe to PATH.
    pause
    exit /b 1
)
'@

$expected = [ordered]@{}
foreach ($job in @($template.Jobs | Sort-Object Name)) {
    $mode = if ($job.PSObject.Properties['AssignmentMode'] -and $job.AssignmentMode) { [string]$job.AssignmentMode } else { 'Legacy' }
    if ($mode -eq 'Manual') { continue }
    $name = [string]$job.Name
    # Legacy preparation remains disabled for rollback until cutover acceptance.
    if ($name -eq 'CmdbEvidence-Prepare') { continue }
    if ($name -notmatch '^[A-Za-z0-9._-]+$') { throw "Job name not usable in a launcher: $name" }
    $expected["Request-$name.cmd"] = @"
@echo off
setlocal EnableExtensions EnableDelayedExpansion
rem Generated by Orchestrator\New-SmartM365-OrchestratorJobLaunchers.ps1. Do not edit.
rem Requests job $name through the resident orchestrators (elected server, shared locks and
rem dependency rules) and waits for its result. Optional: -IncludeDependencies, -NoWait.

set "SCRIPT_DIR=%~dp0..\Orchestrator\"
$pwshBlock

"%PWSH%" -NoProfile -ExecutionPolicy Bypass -File "%SCRIPT_DIR%SmartM365-Inventory-Pipeline.ps1" -Tenant prod -Job "$name" -Collect %*
set "EXIT_CODE=%ERRORLEVEL%"
exit /b %EXIT_CODE%
"@
}
$expected['Request-SmartM365-OrchestratorJob.cmd'] = @"
@echo off
setlocal EnableExtensions EnableDelayedExpansion
rem Generated by Orchestrator\New-SmartM365-OrchestratorJobLaunchers.ps1. Do not edit.
rem Usage: Request-SmartM365-OrchestratorJob.cmd JobName[,JobName...] [-IncludeDependencies] [-NoWait]
rem Requests the named jobs through the resident orchestrators and waits for their result.

if "%~1"=="" (
    echo Usage: %~nx0 JobName[,JobName...] [-IncludeDependencies] [-NoWait]
    exit /b 1
)
set "SCRIPT_DIR=%~dp0..\Orchestrator\"
$pwshBlock

"%PWSH%" -NoProfile -ExecutionPolicy Bypass -File "%SCRIPT_DIR%SmartM365-Inventory-Pipeline.ps1" -Tenant prod -Collect -Job %*
set "EXIT_CODE=%ERRORLEVEL%"
exit /b %EXIT_CODE%
"@

$powerShell5Block = @'
set "POWERSHELL5=%SystemRoot%\System32\WindowsPowerShell\v1.0\powershell.exe"
if exist "%SystemRoot%\Sysnative\WindowsPowerShell\v1.0\powershell.exe" set "POWERSHELL5=%SystemRoot%\Sysnative\WindowsPowerShell\v1.0\powershell.exe"
if not exist "%POWERSHELL5%" (
    echo Windows PowerShell 5.1 ^(powershell.exe^) was not found.
    pause
    exit /b 1
)
'@

# Direct launchers reproduce the orchestrator command (Start-OrchestratorJob): ScriptPath and
# LauncherPath are relative to SmartInventory, Arguments come first, then -Tenant and -Connect.
$jobExpected = [ordered]@{}
foreach ($job in @($template.Jobs | Sort-Object Name)) {
    $mode = if ($job.PSObject.Properties['AssignmentMode'] -and $job.AssignmentMode) { [string]$job.AssignmentMode } else { 'Legacy' }
    if ($mode -eq 'Manual') { continue }
    $name = [string]$job.Name
    if ($name -eq 'CmdbEvidence-Prepare') { continue }
    if ($name -notmatch '^[A-Za-z0-9._-]+$') { throw "Job name not usable in a launcher: $name" }
    $arguments = ([string]$job.Arguments).Trim()
    if ($arguments -match '[%!^&|<>]') { throw "Job '$name': Arguments contain a character that a CMD launcher would alter: $arguments" }
    $argumentPart = if ($arguments) { ' ' + $arguments } else { '' }
    $launcherPath = if ($job.PSObject.Properties['LauncherPath'] -and $job.LauncherPath) { [string]$job.LauncherPath } else { '' }
    $header = @"
@echo off
setlocal EnableExtensions
rem Generated by Orchestrator\New-SmartM365-OrchestratorJobLaunchers.ps1. Do not edit.
rem Runs job $name now on this server, outside the orchestrator, with the orchestrator command
rem and the template Arguments. Extra options are appended. Use LaunchersByOrchestrator for a
rem production run through the elected server.

set "SMARTINVENTORY_ROOT=%~dp0..\..\"
"@
    if ($launcherPath) {
        if (-not (Test-Path -LiteralPath (Join-Path -Path $smartInventoryRoot -ChildPath $launcherPath) -PathType Leaf)) { throw "Job '$name': LauncherPath not found: $launcherPath" }
        # The job launcher resolves the tenant from SMARTM365_ORCHESTRATOR_TENANT itself.
        $jobExpected["Start-$name.cmd"] = @"
$header
call "%SMARTINVENTORY_ROOT%$launcherPath"$argumentPart %*
exit /b %ERRORLEVEL%
"@
        continue
    }
    $scriptPath = [string]$job.ScriptPath
    $scriptFullPath = Join-Path -Path $smartInventoryRoot -ChildPath $scriptPath
    if (-not (Test-Path -LiteralPath $scriptFullPath -PathType Leaf)) { throw "Job '$name': ScriptPath not found: $scriptPath" }
    $parseErrors = $null
    $scriptAst = [Management.Automation.Language.Parser]::ParseFile($scriptFullPath, [ref]$null, [ref]$parseErrors)
    if ($parseErrors) { throw "Job '$name': unable to inspect the parameters of $scriptPath" }
    $connectPart = ''
    if ($scriptAst.ParamBlock -and @($scriptAst.ParamBlock.Parameters | Where-Object { $_.Name.VariablePath.UserPath -eq 'Connect' }).Count -gt 0) { $connectPart = ' -Connect' }
    $edition = if ($job.PSObject.Properties['PowerShellEdition'] -and $job.PowerShellEdition) { [string]$job.PowerShellEdition } else { 'PowerShell7' }
    $engineBlock = if ($edition -eq 'WindowsPowerShell') { $powerShell5Block } else { $pwshBlock }
    $engine = if ($edition -eq 'WindowsPowerShell') { '%POWERSHELL5%' } else { '%PWSH%' }
    $jobExpected["Start-$name.cmd"] = @"
$header
set "SMARTM365_LAUNCHER_TENANT=prod"
if defined SMARTM365_ORCHESTRATOR_TENANT set "SMARTM365_LAUNCHER_TENANT=%SMARTM365_ORCHESTRATOR_TENANT%"
$engineBlock

"$engine" -NoProfile -ExecutionPolicy Bypass -File "%SMARTINVENTORY_ROOT%$scriptPath"$argumentPart -Tenant "%SMARTM365_LAUNCHER_TENANT%"$connectPart %*
set "EXIT_CODE=%ERRORLEVEL%"
exit /b %EXIT_CODE%
"@
}

$differences = [Collections.Generic.List[string]]::new()
foreach ($target in @(
        [pscustomobject]@{ Root = $launcherRoot; Label = 'LaunchersByOrchestrator'; Expected = $expected },
        [pscustomobject]@{ Root = $jobLauncherRoot; Label = 'Launchers\Jobs'; Expected = $jobExpected })) {
    $existing = if (Test-Path -LiteralPath $target.Root -PathType Container) { @(Get-ChildItem -LiteralPath $target.Root -File -Filter '*.cmd' | ForEach-Object Name) } else { @() }
    foreach ($fileName in $target.Expected.Keys) {
        $path = Join-Path -Path $target.Root -ChildPath $fileName
        $content = ($target.Expected[$fileName] -replace "`r?`n", "`r`n").TrimEnd() + "`r`n"
        if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { $differences.Add("missing: $($target.Label)\$fileName") }
        elseif ([IO.File]::ReadAllText($path) -cne $content) { $differences.Add("outdated: $($target.Label)\$fileName") }
        if (-not $Check) {
            if (-not (Test-Path -LiteralPath $target.Root)) { New-Item -ItemType Directory -Path $target.Root -Force | Out-Null }
            [IO.File]::WriteAllText($path, $content, [Text.Encoding]::ASCII)
        }
    }
    foreach ($fileName in @($existing | Where-Object { -not $target.Expected.Contains($_) })) {
        $differences.Add("obsolete: $($target.Label)\$fileName")
        if (-not $Check) { Remove-Item -LiteralPath (Join-Path -Path $target.Root -ChildPath $fileName) -Force }
    }
}
$launcherCount = $expected.Count + $jobExpected.Count

if ($Check) {
    if ($differences.Count -gt 0) {
        $differences | ForEach-Object { Write-Output $_ }
        Write-Output ("LaunchersByOrchestrator or Launchers\Jobs is out of date ({0} difference(s)). Run New-SmartM365-OrchestratorJobLaunchers.ps1." -f $differences.Count)
        exit 1
    }
    Write-Output ("LaunchersByOrchestrator and Launchers\Jobs are up to date: {0} launcher(s)." -f $launcherCount)
    exit 0
}
Write-Output ("LaunchersByOrchestrator and Launchers\Jobs generated: {0} launcher(s); {1} change(s)." -f $launcherCount, $differences.Count)

