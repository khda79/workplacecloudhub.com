#Requires -Version 7.0
<#
.SYNOPSIS
Interactive EXO read-only worker. Line-delimited commands keep the GUI responsive.
.VERSION
1.0.0
#>
[CmdletBinding()]
param([string]$TenantId, [switch]$ValidateOnly)
$ErrorActionPreference='Stop'
Import-Module (Join-Path $PSScriptRoot 'SmartM365.ExchangeMigrationSelection.psm1') -Force
if ($ValidateOnly) { return }
function Write-SelectionResponse {
    param([string]$Kind, $Data)
    [Console]::Out.WriteLine('EXOBATCH:' + (@{Kind=$Kind;Data=$Data} | ConvertTo-Json -Depth 14 -Compress))
    [Console]::Out.Flush()
}
$connected=$false
try {
    $tenantGuid=[guid]::Empty
    if (-not [guid]::TryParse($TenantId,[ref]$tenantGuid) -or $tenantGuid -eq [guid]::Empty) { throw 'Select a tenant profile with a valid TenantId GUID' }
    Import-Module ExchangeOnlineManagement -MinimumVersion 3.7.2 -ErrorAction Stop
    # This worker owns its process/session. It never uses the operator's GUI session.
    Disconnect-ExchangeOnline -Confirm:$false -ErrorAction SilentlyContinue
    Connect-ExchangeOnline -ShowBanner:$false -ErrorAction Stop | Out-Null
    $connected=$true
    $connections=@(Get-ConnectionInformation -ErrorAction Stop | Where-Object State -EQ 'Connected')
    if ($connections.Count -ne 1 -or [string]$connections[0].TenantID -ine $TenantId -or
        [string]::IsNullOrWhiteSpace([string]$connections[0].UserPrincipalName) -or
        [bool](Get-ExoSelectionValue $connections[0] 'AppCertificateAuthentication' $false)) { throw 'EXO interactive tenant/account could not be verified' }
    foreach ($command in @('Get-MigrationBatch','Get-MigrationUser','Get-MigrationUserStatistics')) {
        if (-not (Get-Command $command -ErrorAction SilentlyContinue)) { throw "EXO read permission is missing: $command" }
    }
    Write-SelectionResponse 'Connected' @{TenantId=$TenantId;Account=[string]$connections[0].UserPrincipalName}
    while ($null -ne ($line=[Console]::In.ReadLine())) {
        try {
            $request=$line | ConvertFrom-Json -ErrorAction Stop
            if ($request.Operation -eq 'Close') { break }
            $batches=@(Get-MigrationBatch -ResultSize Unlimited -ErrorAction Stop)
            if ($request.Operation -eq 'Batches') {
                $normalized=@(foreach($batch in $batches){[pscustomobject]@{
                    Selected=$false;Identity=[string]$batch.Identity;Status=[string]$batch.Status
                    MigrationType=[string](Get-ExoSelectionValue $batch 'MigrationType');TotalCount=(Get-ExoSelectionValue $batch 'TotalCount' '')
                    Direction=[string](Get-ExoSelectionValue $batch 'Direction')
                    CompleteAfter=[string](Get-ExoSelectionValue $batch 'CompleteAfter');CompleteAfterUTC=[string](Get-ExoSelectionValue $batch 'CompleteAfterUTC')
                    StartAfter=[string](Get-ExoSelectionValue $batch 'StartAfter');TimeZone=[string](Get-ExoSelectionValue $batch 'TimeZone')
                }})
                Write-SelectionResponse 'Batches' @{Rows=$normalized;ReadAtUtc=[datetime]::UtcNow.ToString('o')}
            }
            elseif ($request.Operation -eq 'Recipients') {
                $ids=@($request.BatchIds | Where-Object {-not [string]::IsNullOrWhiteSpace([string]$_)} | Sort-Object -Unique)
                if (-not $ids.Count) { throw 'No batch was selected' }
                $records=[Collections.Generic.List[object]]::new()
                foreach ($id in $ids) {
                    $matches=@($batches | Where-Object {[string]$_.Identity -ceq [string]$id})
                    if ($matches.Count -ne 1) { throw "Batch no longer available: $id" }
                    $batch=$matches[0]
                    if ([string]$batch.Status -match '^Completed|^Removed|^Removing') { throw "Batch is no longer active: $id" }
                    if ([string](Get-ExoSelectionValue $batch 'Direction') -eq 'Offboarding') { throw "Batch migrates away from EXO: $id" }
                    if ([string](Get-ExoSelectionValue $batch 'MigrationType') -match 'PublicFolder|Group|Teams|SharePoint|Drive') { throw "Batch is not a mailbox migration: $id" }
                    $users=@(Get-MigrationUser -BatchId $id -ResultSize Unlimited -ErrorAction Stop)
                    if (-not $users.Count) { throw "Selected batch returned no recipients: $id" }
                    $expectedCount=0
                    if ([int]::TryParse([string](Get-ExoSelectionValue $batch 'TotalCount'),[ref]$expectedCount) -and $expectedCount -ne $users.Count) { throw "Batch membership changed or is incomplete: $id. Refresh before selecting recipients." }
                    foreach ($user in $users) {
                        if (-not [string]$user.Identity) { throw 'Migration user identity is missing' }
                        $stats=$null
                        try { $stats=Get-MigrationUserStatistics -Identity $user.Identity -ErrorAction Stop }
                        catch { $stats=[pscustomobject]@{ScheduleReadError=$_.Exception.Message} }
                        $records.Add([pscustomobject]@{Batch=$batch;User=$user;Statistics=$stats})
                    }
                }
                $rows=@(ConvertTo-ExoSelectionRecipient -Records $records.ToArray() -DisplayTimeZoneId $request.TimeZoneId)
                Write-SelectionResponse 'Recipients' @{Rows=$rows;ReadAtUtc=[datetime]::UtcNow.ToString('o')}
            }
            else { throw 'Unsupported read-only worker operation' }
        }
        catch { Write-SelectionResponse 'Error' @{Message=$_.Exception.Message} }
    }
}
catch { Write-SelectionResponse 'Error' @{Message=$_.Exception.Message}; exit 1 }
finally { if($connected){Disconnect-ExchangeOnline -Confirm:$false -ErrorAction SilentlyContinue | Out-Null} }

