# Explicit single-recipient mail test adapter, version 0.4.0.
function New-SiMailTestPlan {
    param([Parameter(Mandatory)][string]$Root,[Parameter(Mandatory)][string]$Tenant,[Parameter(Mandatory)][string]$From,[Parameter(Mandatory)][string]$To,[Parameter(Mandatory)][ValidateSet('Graph','SMTP')][string]$Transport,[string]$Worker=(Join-Path $PSScriptRoot 'SmartM365-MailTestWorker.ps1'))
    if ($Tenant -notmatch '^[a-zA-Z0-9][a-zA-Z0-9_-]{0,63}$') { throw 'Invalid profile key.' }
    foreach ($address in @($From,$To)) {
        if ($address -match '[^\x21-\x7e]' -or $address -match '[\r\n;,]' -or $address -ne $address.Trim()) { throw 'Enter one sender and one recipient as bare ASCII email addresses.' }
        try { $parsed=[Net.Mail.MailAddress]::new($address); if ($parsed.Address -ine $address) { throw 'Not a bare address.' } }
        catch { throw 'Enter one sender and one recipient as bare ASCII email addresses.' }
    }
    $sources=@($Worker)
    $sources+=@('Config/SmartM365-TenantContext.ps1','Modules/SmartM365.Core/SmartM365.Core.psd1','Modules/SmartM365.Core/SmartM365.Core.psm1','Modules/SmartM365.Core/SmartM365-MailMaintenance.ps1','Modules/SmartM365.Core/SmartM365-DeferredMail.ps1','Modules/SmartM365.Core/SmartM365-MailAdminRouting.ps1','Modules/SmartM365.Core/SmartM365.JsonTransport.psd1','Modules/SmartM365.Core/SmartM365.JsonTransport.psm1') | ForEach-Object { Join-Path $Root $_ }
    $receipts=@(foreach ($path in $sources) { if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { throw 'A required mail runtime file is missing.' }; [pscustomobject]@{Path=$path;Hash=(Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash} })
    $profile=Read-SiPrivateJson (Join-Path $Root ("Config/Tenants/$Tenant.local"))
    if ($profile.State -ne 'Present' -or [string]$profile.Value.ProfileKey -ine $Tenant) { throw 'Tenant profile missing, invalid or conflicting.' }
    $base=Join-Path $Root ("Config/Tenants/$Tenant.local.json")
    $profilePath=if (Test-Path -LiteralPath ($base+'.txt') -PathType Leaf) { $base+'.txt' } else { $base }
    $hash=(Get-FileHash -LiteralPath $profilePath -Algorithm SHA256).Hash
    $profile=Read-SiPrivateJson (Join-Path $Root ("Config/Tenants/$Tenant.local"))
    if ($profile.State -ne 'Present' -or [string]$profile.Value.ProfileKey -ine $Tenant -or (Get-FileHash -LiteralPath $profilePath -Algorithm SHA256).Hash -ne $hash) { throw 'Tenant profile changed during planning.' }
    [pscustomobject]@{Root=$Root;Tenant=$Tenant;From=$From;To=$To;Transport=$Transport;Worker=$Worker;Sources=$receipts;ProfilePath=$profilePath;ProfileHash=$hash}
}
function Start-SiMailTest {
    param([Parameter(Mandatory)]$Plan,[string]$Executable=(Join-Path $PSHOME 'pwsh.exe'))
    $fresh=New-SiMailTestPlan -Root $Plan.Root -Tenant $Plan.Tenant -From $Plan.From -To $Plan.To -Transport $Plan.Transport -Worker $Plan.Worker
    foreach ($name in @('Worker','ProfilePath','ProfileHash')) { if ($fresh.$name -cne $Plan.$name) { throw 'Mail test inputs changed; prepare the test again.' } }
    if ($fresh.Sources.Count -ne $Plan.Sources.Count) { throw 'Mail runtime changed; prepare the test again.' }
    for ($i=0;$i -lt $fresh.Sources.Count;$i++) { if ($fresh.Sources[$i].Path -cne $Plan.Sources[$i].Path -or $fresh.Sources[$i].Hash -cne $Plan.Sources[$i].Hash) { throw 'Mail runtime changed; prepare the test again.' } }
    if (-not (Test-Path -LiteralPath $Executable -PathType Leaf)) { throw 'PowerShell is missing.' }
    $locks=[Collections.Generic.List[object]]::new(); $process=$null; $started=$false
    try {
        foreach ($source in $fresh.Sources) {
            $locks.Add([IO.File]::Open($source.Path,[IO.FileMode]::Open,[IO.FileAccess]::Read,[IO.FileShare]::Read))
            if ((Get-FileHash -LiteralPath $source.Path -Algorithm SHA256).Hash -ne $source.Hash) { throw 'Mail runtime changed; prepare the test again.' }
        }
        $info=[Diagnostics.ProcessStartInfo]::new(); $info.FileName=$Executable; $info.UseShellExecute=$false; $info.CreateNoWindow=$true
        $info.RedirectStandardInput=$true; $info.RedirectStandardOutput=$true; $info.RedirectStandardError=$true
        foreach ($arg in @('-NoProfile','-NonInteractive','-ExecutionPolicy','Bypass','-File',$fresh.Worker,'-Root',$fresh.Root,'-Tenant',$fresh.Tenant)) { $info.ArgumentList.Add($arg) }
        $process=[Diagnostics.Process]::new(); $process.StartInfo=$info
        if (-not $process.Start()) { throw 'Mail test process could not start.' }; $started=$true
        $stdout=$process.StandardOutput.ReadToEndAsync(); $stderr=$process.StandardError.ReadToEndAsync()
        $json=@{From=$fresh.From;To=$fresh.To;Transport=$fresh.Transport} | ConvertTo-Json -Compress
        $process.StandardInput.Write($json); $process.StandardInput.Close(); $json=$null
        [pscustomobject]@{Process=$process;Stdout=$stdout;Stderr=$stderr;Locks=$locks}
    } catch {
        if ($started) { try { if (-not $process.HasExited) { $process.Kill($true); $null=$process.WaitForExit(3000) } } catch {} }
        if ($process) { $process.Dispose() }; foreach ($lock in $locks) { $lock.Dispose() }
        throw 'Mail test could not be started or its result is uncertain. Check the recipient and delivery before retrying.'
    }
}
function Complete-SiMailTest {
    param([Parameter(Mandatory)]$Run)
    if (-not $Run.Process.HasExited) { throw 'Mail test is still running.' }
    try {
        $exitCode=$Run.Process.ExitCode
        # Output may contain addresses and is intentionally not returned or persisted here.
        $null=Read-SiBoundedProcessStreams -Stdout $Run.Stdout -Stderr $Run.Stderr
        if ($exitCode -eq 0) { return [pscustomobject]@{State='Completed';Detail='Test completed: the transport may have accepted the message. Verify delivery; this does not prove receipt.'} }
        return [pscustomobject]@{State='Uncertain';Detail='Failure or interruption: a message may have been sent. Check recipient and delivery before retrying.'}
    } finally { $Run.Process.Dispose(); foreach ($lock in $Run.Locks) { $lock.Dispose() } }
}
function Stop-SiMailTest {
    param([Parameter(Mandatory)]$Run)
    if (-not $Run.Process.HasExited) { $Run.Process.Kill($true) }
}
