function Get-SiGraphSetupReadiness {
    param([Parameter(Mandatory)][scriptblock]$GraphGet)
    $checks=[ordered]@{AppRegistration='Unknown';AdminConsent='Unknown';TeamsCreation='Unknown'}
    $messages=[Collections.Generic.List[string]]::new()
    try {
        $members=[Collections.Generic.List[object]]::new();$url='https://graph.microsoft.com/v1.0/me/transitiveMemberOf';$pages=0
        do {
            if (++$pages -gt 100) {throw 'Membership page limit exceeded.'}
            $uri=[uri]$url;if ($uri.Scheme -ne 'https' -or $uri.Host -ine 'graph.microsoft.com' -or -not $uri.IsDefaultPort) {throw 'Unexpected Graph page.'}
            $page=& $GraphGet $url
            if ($null -eq $page -or $null -eq $page.value) {throw 'Incomplete membership result.'}
            foreach ($item in $page.value) {$members.Add($item)}
            $url=[string]$page.'@odata.nextLink'
        } while ($url)
        $roles=@($members | Where-Object {$_.'@odata.type' -eq '#microsoft.graph.directoryRole'} | ForEach-Object {[string]$_.roleTemplateId})
        $groups=@($members | Where-Object {$_.'@odata.type' -eq '#microsoft.graph.group'} | ForEach-Object {[string]$_.id})
        $global='62e90394-69f5-4237-9190-012177145e10';$privileged='e8611ab8-c189-46e8-94e1-60213ab1f814';$cloudApp='158c047a-c907-4556-b7ef-446551a6b5f7';$appAdmin='cf1c38e5-3621-4004-a7cb-879624dced7c'
        if ($global -in $roles -or $privileged -in $roles) {$checks.AdminConsent='Confirmed'} else {$messages.Add('An active Global Administrator or Privileged Role Administrator role was not confirmed. Custom roles require separate review.')}
        if (@($global,$cloudApp,$appAdmin | Where-Object {$_ -in $roles}).Count) {$checks.AppRegistration='Confirmed'}
        else {
            try {$policy=& $GraphGet 'https://graph.microsoft.com/v1.0/policies/authorizationPolicy';if ($policy.defaultUserRolePermissions.allowedToCreateApps -is [bool] -and $policy.defaultUserRolePermissions.allowedToCreateApps) {$checks.AppRegistration='Confirmed'} else {$messages.Add('Application registration permission could not be confirmed.')}} catch {$messages.Add('Application registration policy could not be read.')}
        }
        try {
            $settings=[Collections.Generic.List[object]]::new();$url='https://graph.microsoft.com/v1.0/groupSettings';$pages=0
            do {if (++$pages -gt 100) {throw 'Settings page limit exceeded.'};$uri=[uri]$url;if ($uri.Scheme -ne 'https' -or $uri.Host -ine 'graph.microsoft.com' -or -not $uri.IsDefaultPort) {throw 'Unexpected Graph page.'};$page=& $GraphGet $url;if ($null -eq $page -or $null -eq $page.value) {throw 'Incomplete group settings.'};foreach($item in $page.value){$settings.Add($item)};$url=[string]$page.'@odata.nextLink'} while ($url)
            $unified=@($settings | Where-Object {$_.displayName -eq 'Group.Unified'})
            if ($unified.Count -gt 1) {throw 'Conflicting group settings.'}
            if ($unified.Count -eq 0) {$checks.TeamsCreation='Confirmed'} else {
                $flag=@($unified[0].values | Where-Object name -eq 'EnableGroupCreation');$allowed=@($unified[0].values | Where-Object name -eq 'GroupCreationAllowedGroupId')
                if ($flag.Count -ne 1) {throw 'Group creation policy unavailable.'}
                if ([string]$flag[0].value -ieq 'true') {$checks.TeamsCreation='Confirmed'}
                elseif ([string]$flag[0].value -ieq 'false' -and $allowed.Count -eq 1 -and [string]$allowed[0].value -and [string]$allowed[0].value -in $groups) {$checks.TeamsCreation='Confirmed'}
                else {$messages.Add('Microsoft 365 group creation is restricted or the allowed group membership was not confirmed.')}
            }
        } catch {$messages.Add('Microsoft 365 group creation policy could not be read.')}
    } catch {$messages.Add('Active directory roles and group memberships could not be read.')}
    [pscustomobject]@{Ready=(@($checks.Values | Where-Object {$_ -ne 'Confirmed'}).Count -eq 0);Checks=[pscustomobject]$checks;Messages=$messages.ToArray()}
}

