# SmartInventory local service account operation, version 0.2.0.
function New-SiLocalServiceAccount {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][string]$Name,
        [Parameter(Mandatory)][System.Security.SecureString]$Password,
        [scriptblock]$ListAccounts,
        [scriptblock]$CreateAccount
    )
    if ($Name -cnotmatch '^[A-Za-z0-9][A-Za-z0-9_.-]{0,19}$' -or $Name.EndsWith('.')) { throw 'Invalid local account name.' }
    if ($Password.Length -eq 0) { throw 'A nonempty password is required.' }
    if ($null -eq $ListAccounts) { $ListAccounts={ Get-LocalUser -ErrorAction Stop } }
    if ($null -eq $CreateAccount) { $CreateAccount={ param($n,$p) New-LocalUser -Name $n -Password $p -Description 'SmartInventory service account' -ErrorAction Stop } }
    $existing=@(& $ListAccounts | Where-Object { $_.Name -ieq $Name })
    if ($existing.Count -gt 0) { throw 'The account already exists; it was not changed.' }
    $null=& $CreateAccount $Name $Password
    $matches=@(& $ListAccounts | Where-Object { $_.Name -ieq $Name })
    if ($matches.Count -ne 1 -or $null -eq $matches[0].SID) { throw 'Creation was requested but the resulting account could not be verified; review the machine before retrying.' }
    [pscustomobject]@{Name=$matches[0].Name; SID=[string]$matches[0].SID; State='Created locally; task logon and access rights not verified'}
}

function Resolve-SiServiceAccount {
    param([Parameter(Mandatory)][string]$Account,[switch]$Managed,[scriptblock]$Resolver)
    $Account=$Account.Trim()
    if ($Account -notmatch '^(?:[A-Za-z0-9._-]+\\[A-Za-z0-9._$+-]+|[A-Za-z0-9._+-]+@[A-Za-z0-9.-]+)$') { throw 'Enter DOMAIN\account or an account UPN.' }
    if ($null -eq $Resolver) { $Resolver={ param($name) ([Security.Principal.NTAccount]::new($name)).Translate([Security.Principal.SecurityIdentifier]).Value } }
    $sid=[string](& $Resolver $Account)
    if ($sid -notmatch '^S-1-(?:\d+-)+\d+$') { throw 'Account SID could not be resolved.' }
    if ($sid -eq 'S-1-5-18') { throw 'LocalSystem is not accepted as the service account.' }
    if ($Managed -or $Account.EndsWith('$')) { throw 'Only standard service accounts are supported.' }
    [pscustomobject]@{Account=$Account;Sid=$sid;Managed=[bool]$Managed;State='Resolved';Detail='Identity resolved; task logon, share access and private-key access are not verified.'}
}

