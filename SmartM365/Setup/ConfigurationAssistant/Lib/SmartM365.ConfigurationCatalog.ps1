# SmartInventory catalog inspection, version 0.2.0.
function Get-SiCatalogObservation {
    param([Parameter(Mandatory)][string]$CatalogPath,[Parameter(Mandatory)][string]$InventoryRoot,[scriptblock]$PathGuard)
    if (-not [IO.Path]::IsPathFullyQualified($CatalogPath) -or -not [IO.Path]::IsPathFullyQualified($InventoryRoot)) { throw 'Absolute paths are required.' }
    $doc=Get-Content -LiteralPath $CatalogPath -Raw -ErrorAction Stop | ConvertFrom-Json -ErrorAction Stop
    if ($doc -isnot [pscustomobject] -or $doc.Jobs -isnot [array]) { throw 'Catalog must contain a Jobs array.' }
    $names=@{}; $issues=[Collections.Generic.List[string]]::new(); $enabled=[Collections.Generic.List[object]]::new()
    foreach ($job in $doc.Jobs) {
        $name=[string]$job.Name
        if ([string]::IsNullOrWhiteSpace($name)) { $issues.Add('Job without a name.'); continue }
        if ($names.ContainsKey($name)) { $issues.Add(('Duplicate job: {0}' -f $name)); continue }
        $names[$name]=$job
        if ($job.Enabled -isnot [bool]) { $issues.Add(('{0}: Enabled is missing or not a Boolean' -f $name)); continue }
        if ($job.Enabled -eq $true) { $enabled.Add($job) }
    }
    $unchecked=0; $ignored=0
    $root=[IO.Path]::GetFullPath($InventoryRoot).TrimEnd([IO.Path]::DirectorySeparatorChar) + [IO.Path]::DirectorySeparatorChar
    foreach ($job in $enabled) {
        foreach ($dependency in @($job.DependsOn)) {
            if ([string]::IsNullOrWhiteSpace([string]$dependency)) { continue }
            if (-not $names.ContainsKey([string]$dependency)) { $issues.Add(('{0}: unknown dependency {1}' -f $job.Name,$dependency)); continue }
            $dep=$names[[string]$dependency]
            if ($dep.Enabled -ne $true -or [string]$dep.AssignmentMode -eq 'Manual') { $ignored++ }
        }
        $scriptPath=[string]$job.ScriptPath
        if ([string]::IsNullOrWhiteSpace($scriptPath) -or [IO.Path]::IsPathRooted($scriptPath)) { $unchecked++; continue }
        try { $full=[IO.Path]::GetFullPath((Join-Path $root $scriptPath)) } catch { $unchecked++; continue }
        if (-not $full.StartsWith($root,[StringComparison]::OrdinalIgnoreCase)) { $unchecked++; continue }
        if ($null -ne $PathGuard) {
            try { $null=& $PathGuard $full } catch { $unchecked++; continue }
        }
        if (-not (Test-Path -LiteralPath $full -PathType Leaf)) { $issues.Add(('{0}: script missing from selected local tree' -f $job.Name)) }
    }
    $remaining=@{}
    foreach ($job in $enabled) { if ([string]$job.AssignmentMode -ne 'Manual') { $remaining[[string]$job.Name]=$job } }
    do {
        $ready=[Collections.Generic.List[string]]::new()
        foreach ($name in @($remaining.Keys)) {
            $blocked=$false
            foreach ($dependency in @($remaining[$name].DependsOn)) { if ($remaining.ContainsKey([string]$dependency)) { $blocked=$true; break } }
            if (-not $blocked) { $ready.Add($name) }
        }
        foreach ($name in $ready) { $remaining.Remove($name) }
    } while ($ready.Count -gt 0 -and $remaining.Count -gt 0)
    if ($remaining.Count -gt 0) { $issues.Add(('Cyclic or cycle-dependent scheduled jobs: {0}' -f ((@($remaining.Keys) | Sort-Object) -join ', '))) }
    [pscustomobject]@{EnabledCount=$enabled.Count; Issues=$issues.ToArray(); UncheckedScripts=$unchecked; IgnoredDependencies=$ignored}
}

