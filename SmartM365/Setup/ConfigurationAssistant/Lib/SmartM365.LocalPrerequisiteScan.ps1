# Read-only module-directory observations, version 0.2.0; no installation or imports.
function Get-SiDeclaredPrerequisiteModules {
    param([Parameter(Mandatory)][string]$ScriptPath)
    $safe=Assert-SiLocalAssessmentPath $ScriptPath -AllowRepository
    if (-not (Test-Path -LiteralPath $safe -PathType Leaf)) { throw 'Prerequisite source is unavailable.' }
    $hash=(Get-FileHash -LiteralPath $safe -Algorithm SHA256).Hash
    $tokens=$null; $errors=$null
    $ast=[Management.Automation.Language.Parser]::ParseFile($safe,[ref]$tokens,[ref]$errors)
    if ($errors.Count) { throw 'Prerequisite source could not be parsed.' }
    $allAssignments=@($ast.FindAll({param($n) $n -is [Management.Automation.Language.AssignmentStatementAst] -and $n.Left -is [Management.Automation.Language.VariableExpressionAst] -and $n.Left.VariablePath.UserPath -eq 'requiredModules'},$true))
    foreach ($assignment in $allAssignments) {
        if ($assignment.Operator -eq [Management.Automation.Language.TokenKind]::Equals) {
            $expression=$assignment.Right.Extent.Text -replace '\s',''
            if ($expression -ine '@()' -and $expression -ine '@($requiredModules|Select-Object-Unique)') { throw 'Prerequisite module declarations changed; use the dedicated audit.' }
        } elseif ($assignment.Operator -ne [Management.Automation.Language.TokenKind]::PlusEquals) { throw 'Prerequisite module declarations changed; use the dedicated audit.' }
    }
    $assignments=@($allAssignments | Where-Object Operator -eq ([Management.Automation.Language.TokenKind]::PlusEquals))
    foreach ($assignment in $assignments) {
        $dynamic=@($assignment.Right.FindAll({param($n) $n -is [Management.Automation.Language.VariableExpressionAst] -or $n -is [Management.Automation.Language.CommandAst] -or $n -is [Management.Automation.Language.ExpandableStringExpressionAst] -or $n -is [Management.Automation.Language.MemberExpressionAst]},$true))
        $literals=@($assignment.Right.FindAll({param($n) $n -is [Management.Automation.Language.StringConstantExpressionAst]},$true))
        if ($dynamic.Count -or -not $literals.Count) { throw 'Prerequisite module declarations are not static; use the dedicated audit.' }
    }
    $names=@($(foreach ($assignment in $assignments) { foreach ($literal in $assignment.Right.FindAll({param($n) $n -is [Management.Automation.Language.StringConstantExpressionAst]},$true)) { [string]$literal.Value } }) | Select-Object -Unique)
    if ($names.Count -eq 0 -or @($names | Where-Object { $_ -notmatch '^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$' }).Count) { throw 'Prerequisite module declarations are invalid.' }
    if ((Get-FileHash -LiteralPath $safe -Algorithm SHA256).Hash -cne $hash) { throw 'Prerequisite source changed during inspection.' }
    [pscustomobject]@{Names=$names;SourceHash=$hash}
}
function Get-SiLocalPrerequisiteObservation {
    param([Parameter(Mandatory)][string]$Root,[string[]]$ModuleRoots=@($env:PSModulePath -split [IO.Path]::PathSeparator))
    $manifest=Get-SiDeclaredPrerequisiteModules -ScriptPath (Join-Path $Root 'Setup/Install-SmartM365-SmartInventoryPrerequisites.ps1')
    $safeRoots=[Collections.Generic.List[string]]::new(); $unscanned=0
    foreach ($path in $ModuleRoots) {
        if ([string]::IsNullOrWhiteSpace($path)) { continue }
        try { $local=Assert-SiLocalAssessmentPath $path; if (Test-Path -LiteralPath $local -PathType Container) { $safeRoots.Add($local) } else { $unscanned++ } }
        catch { $unscanned++ }
    }
    $found=[Collections.Generic.List[string]]::new(); $missing=[Collections.Generic.List[string]]::new()
    foreach ($name in $manifest.Names) {
        $seen=$false
        foreach ($base in $safeRoots) {
            foreach ($leaf in @($name,($name+'.psd1'),($name+'.psm1'))) {
                try { $candidate=Assert-SiLocalAssessmentPath (Join-Path $base $leaf); if (Test-Path -LiteralPath $candidate) { $seen=$true; break } }
                catch { $unscanned++ }
            }
            if ($seen) { break }
        }
        if ($seen) { $found.Add($name) } else { $missing.Add($name) }
    }
    if ((Get-FileHash -LiteralPath (Join-Path $Root 'Setup/Install-SmartM365-SmartInventoryPrerequisites.ps1') -Algorithm SHA256).Hash -cne $manifest.SourceHash) { throw 'Prerequisite source changed during inspection.' }
    [pscustomobject]@{Observed=$found.ToArray();NotObserved=$missing.ToArray();UnscannedLocations=$unscanned;SourceHash=$manifest.SourceHash;Detail='Module names were checked only as local filesystem entries. Versions, imports, remote locations, other PowerShell editions and service-account access are not verified. Microsoft.Graph rollup may be omitted when the individual submodules are managed separately.'}
}

