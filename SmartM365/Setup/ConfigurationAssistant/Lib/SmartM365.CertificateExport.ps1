# Export the application's private certificate as an encrypted PFX, without overwriting files.
function Export-SiApplicationCertificate {
    param([Parameter(Mandatory)][string]$Root,[Parameter(Mandatory)][string]$Thumbprint,[Parameter(Mandatory)][Security.SecureString]$Password,[scriptblock]$FindCertificate,[scriptblock]$WriteProtectedFile)
    $thumb=$Thumbprint.Replace(' ','').ToUpperInvariant()
    if ($thumb -notmatch '^[0-9A-F]{40}$' -or $thumb -match '^0+$') {throw 'A valid application certificate thumbprint is required.'}
    if ($Password.Length -lt 12) {throw 'The export password must contain at least 12 characters.'}
    if ($null -eq $FindCertificate) {$FindCertificate={param($t) Get-Item -LiteralPath ('Cert:\CurrentUser\My\'+$t) -ErrorAction Stop}}
    $certificate=& $FindCertificate $thumb
    if ($null -eq $certificate -or [string]$certificate.Thumbprint -ine $thumb -or -not $certificate.HasPrivateKey) {throw 'The application certificate with its private key was not found in the current user store.'}
    $config=Join-Path $Root 'Config';$folder=Join-Path $config 'Certificats'
    foreach ($path in @($Root,$config)) {$item=Get-Item -LiteralPath $path -Force -ErrorAction Stop;if (-not $item.PSIsContainer -or ($item.Attributes -band [IO.FileAttributes]::ReparsePoint)) {throw 'The certificate export path is not a normal directory.'}}
    if (-not (Test-Path -LiteralPath $folder)) {New-Item -ItemType Directory -Path $folder -ErrorAction Stop | Out-Null}
    $item=Get-Item -LiteralPath $folder -Force -ErrorAction Stop
    if (-not $item.PSIsContainer -or ($item.Attributes -band [IO.FileAttributes]::ReparsePoint)) {throw 'The certificate export folder is not a normal directory.'}
    $target=Join-Path $folder ('SmartM365-App-'+$thumb+'-'+[guid]::NewGuid().ToString('N')+'.pfx')
    if ($null -eq $WriteProtectedFile) {
        $WriteProtectedFile={param($path,$bytes)
            $sid=[Security.Principal.WindowsIdentity]::GetCurrent().User
            $system=[Security.Principal.SecurityIdentifier]::new('S-1-5-18');$admins=[Security.Principal.SecurityIdentifier]::new('S-1-5-32-544')
            $acl=[Security.AccessControl.FileSecurity]::new();$acl.SetAccessRuleProtection($true,$false);$acl.SetOwner($sid)
            foreach ($identity in @($sid,$system,$admins)) {$acl.AddAccessRule([Security.AccessControl.FileSystemAccessRule]::new($identity,[Security.AccessControl.FileSystemRights]::FullControl,[Security.AccessControl.AccessControlType]::Allow))}
            $file=[IO.FileInfo]::new($path);$rights=[Security.AccessControl.FileSystemRights]::FullControl
            $stream=$null;$created=$false
            try {
                $stream=[IO.FileSystemAclExtensions]::Create($file,[IO.FileMode]::CreateNew,$rights,[IO.FileShare]::None,4096,[IO.FileOptions]::WriteThrough,$acl);$created=$true
                $actual=[IO.FileSystemAclExtensions]::GetAccessControl($stream)
                if (-not $actual.AreAccessRulesProtected) {throw 'File ACL inheritance could not be disabled.'}
                $allowed=@($sid.Value,$system.Value,$admins.Value)
                foreach ($rule in $actual.GetAccessRules($true,$true,[Security.Principal.SecurityIdentifier])) {if ($rule.IsInherited -or ($rule.AccessControlType -eq 'Allow' -and $rule.IdentityReference.Value -notin $allowed)) {throw 'The export file permissions are not sufficiently restricted.'}}
                $stream.Write($bytes,0,$bytes.Length);$stream.Flush($true)
            } catch {if ($stream) {$stream.Dispose();$stream=$null};if ($created) {Remove-Item -LiteralPath $path -Force -ErrorAction SilentlyContinue};throw} finally {if ($stream) {$stream.Dispose()}}
        }
    }
    $bytes=$null
    try {
        $bytes=$certificate.Export([Security.Cryptography.X509Certificates.X509ContentType]::Pfx,$Password)
        if ($null -eq $bytes -or $bytes.Length -eq 0) {throw 'The certificate could not be exported.'}
        & $WriteProtectedFile $target $bytes
    } finally {if ($null -ne $bytes) {[Array]::Clear($bytes,0,$bytes.Length)}}
    return $target
}
function Test-SiSecurePasswordEqual {
    param([Security.SecureString]$First,[Security.SecureString]$Second)
    if ($null -eq $First -or $null -eq $Second -or $First.Length -ne $Second.Length) {return $false}
    $a=[IntPtr]::Zero;$b=[IntPtr]::Zero
    try {$a=[Runtime.InteropServices.Marshal]::SecureStringToBSTR($First);$b=[Runtime.InteropServices.Marshal]::SecureStringToBSTR($Second);$difference=0;for ($i=0;$i -lt $First.Length;$i++) {$difference=$difference -bor ([Runtime.InteropServices.Marshal]::ReadInt16($a,$i*2) -bxor [Runtime.InteropServices.Marshal]::ReadInt16($b,$i*2))};return $difference -eq 0} finally {if ($a -ne [IntPtr]::Zero) {[Runtime.InteropServices.Marshal]::ZeroFreeBSTR($a)};if ($b -ne [IntPtr]::Zero) {[Runtime.InteropServices.Marshal]::ZeroFreeBSTR($b)}}
}

