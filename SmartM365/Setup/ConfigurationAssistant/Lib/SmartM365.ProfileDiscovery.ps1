function ConvertTo-SiWorkspaceSharePath {
    param([AllowEmptyString()][string]$Path)
    $value=([string]$Path).Trim()
    if ($value.Length -gt 32760 -or -not $value.StartsWith('\\') -or $value -match '[/\x00-\x1f\x7f:*?<>|"\u200e\u200f\u202a-\u202e\u2066-\u2069]') {throw 'Enter a valid UNC share path, for example \\server\share.'}
    $components=@($value.Substring(2).TrimEnd('\').Split('\'))
    if ($components.Count -lt 2 -or @($components | Where-Object {$_ -in @('','.','..') -or $_.EndsWith(' ') -or $_.EndsWith('.')}).Count) {throw 'Enter a valid UNC share path, for example \\server\share.'}
    return $value.TrimEnd('\')
}
function Get-SiSuggestedProfileIdentity {
    param([AllowEmptyString()][string]$ProfileName,[AllowEmptyString()][string]$EnvironmentName)
    $profile=([string]$ProfileName).Trim().ToLowerInvariant()
    if ($profile -cnotmatch '^[a-z0-9][a-z0-9_-]{0,63}$') {throw 'Use 1-64 letters, digits, hyphens or underscores, starting with a letter or digit.'}
    $environment=([string]$EnvironmentName).Trim().ToLowerInvariant()
    if ($environment -cnotmatch '^[a-z0-9][a-z0-9-]{0,63}$') {throw 'Enter an environment using 1-64 letters, digits or hyphens, starting with a letter or digit.'}
    $organization=$profile.Replace('_','-')
    $suffix='-'+$environment
    if ($organization.EndsWith($suffix,[StringComparison]::Ordinal) -and $organization.Length -gt $suffix.Length) {$organization=$organization.Substring(0,$organization.Length-$suffix.Length)}
    if ($organization -cnotmatch '^[a-z0-9][a-z0-9-]{0,63}$') {throw 'A valid organization key could not be proposed.'}
    [pscustomobject]@{ProfileKey=$profile;OrganizationKey=$organization;EnvironmentKey=$environment;TenantKey=($organization+'-'+$environment)}
}
function Get-SiProfileDiscovery {
    param([Parameter(Mandatory)][string]$Root)
    $config=Join-Path $Root 'Config';$tenants=Join-Path $config 'Tenants'
    try {
        $configFiles=@(Get-ChildItem -LiteralPath $config -File -Force -ErrorAction Stop)
        $tenantFiles=@(Get-ChildItem -LiteralPath $tenants -File -Force -ErrorAction Stop)
    } catch {return [pscustomobject]@{State='Unavailable';GlobalState='Unavailable';Profiles=@();Selected='';Message='Configuration folders cannot be read. Check access before continuing.'}}
    $globalFiles=@($configFiles | Where-Object {$_.Name -in @('SmartM365.global.local.json','SmartM365.global.local.json.txt')})
    $globalState='Missing';$default=''
    if ($globalFiles.Count -gt 1) {$globalState='Conflict'}
    elseif ($globalFiles.Count -eq 1) {
        try {
            $doc=Get-Content -LiteralPath $globalFiles[0].FullName -Raw -ErrorAction Stop | ConvertFrom-Json -ErrorAction Stop
            if ($doc -isnot [pscustomobject]) {throw 'Expected JSON object.'}
            $globalState='Present'
            if ($null -ne $doc.PSObject.Properties['DefaultTenant']) {$default=[string]$doc.DefaultTenant}
        } catch {$globalState='Unreadable'}
    }
    $groups=@{};$badName=$false
    foreach ($file in $tenantFiles) {
        if ($file.Name -match '(?i)\.mail\.local\.json(?:\.txt)?$') {continue}
        if ($file.Name -match '^(.*)\.local\.json(?:\.txt)?$') {
            $key=$Matches[1]
            if ($key -notmatch '^[a-zA-Z0-9][a-zA-Z0-9_-]{0,63}$') {$badName=$true;continue}
            if (-not $groups.ContainsKey($key)) {$groups[$key]=[Collections.Generic.List[object]]::new()}
            $groups[$key].Add($file)
        }
    }
    $profiles=@(foreach ($key in @($groups.Keys | Sort-Object)) {
        $items=$groups[$key];$state='Present'
        if ($items.Count -gt 1) {$state='Conflict'} else {
            try {$doc=Get-Content -LiteralPath $items[0].FullName -Raw -ErrorAction Stop | ConvertFrom-Json -ErrorAction Stop;if ($doc -isnot [pscustomobject]) {throw 'Expected JSON object.'}} catch {$state='Unreadable'}
        }
        [pscustomobject]@{Name=$key;State=$state}
    })
    $issues=@($profiles | Where-Object State -ne 'Present')
    if ($globalState -in @('Conflict','Unreadable') -or $badName -or $issues.Count) {
        $message='Configuration files are unreadable or conflicting. Correct them before continuing.'
        if ($globalState -in @('Conflict','Unreadable')) {$message+=' Global configuration: '+$globalState+'.'}
        if ($badName) {$message+=' A profile filename is invalid.'}
        if ($issues.Count) {$message+=' Profiles requiring correction: '+(($issues | ForEach-Object {$_.Name+' ('+$_.State+')'}) -join ', ')+'.'}
        return [pscustomobject]@{State='CorrectionRequired';GlobalState=$globalState;Profiles=$profiles;Selected='';Message=$message}
    }
    $chosen=''
    if ($profiles.Count -eq 1) {$chosen=$profiles[0].Name}
    elseif ($profiles.Count -gt 1 -and $default) {$match=@($profiles | Where-Object {$_.Name -ieq $default});if ($match.Count -eq 1) {$chosen=$match[0].Name}}
    $state=if ($profiles.Count -eq 0) {'New'} elseif ($chosen) {'Selected'} else {'Choose'}
    $globalMessage=if ($globalState -eq 'Missing') {'Global configuration is missing; it can be created during setup.'} else {'Global configuration found.'}
    $message=switch ($state) {'New' {'No profile found. Create a new profile. '+$globalMessage} 'Choose' {'Select an existing profile or create a new one. '+$globalMessage} default {'Existing profile selected: '+$chosen+'. '+$globalMessage}}
    [pscustomobject]@{State=$state;GlobalState=$globalState;Profiles=$profiles;Selected=$chosen;Message=$message}
}

