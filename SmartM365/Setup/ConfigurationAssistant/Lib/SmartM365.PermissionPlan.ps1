# Read-only permission check plan, version 0.1.0. Does not connect or send mail.
function New-SiPermissionCheckPlan {
    param([Parameter(Mandatory)][string]$Root,[Parameter(Mandatory)][string]$Tenant,[Parameter(Mandatory)][string]$CatalogPath,[Parameter(Mandatory)][string]$Outside,[Parameter(Mandatory)][string]$ExpectedScope,[string]$Worker=(Join-Path $PSScriptRoot 'SmartM365-PermissionWorker.ps1'))
    if ($Tenant -notmatch '^[a-zA-Z0-9][a-zA-Z0-9_-]{0,63}$' -or -not [IO.Path]::IsPathFullyQualified($Root) -or -not [IO.Path]::IsPathFullyQualified($CatalogPath)) {throw 'A valid profile and absolute paths are required.'}
    $base=Join-Path $Root ("Config/Tenants/$Tenant.local")
    $profile=Read-SiPrivateJson $base
    if ($profile.State -ne 'Present' -or [string]$profile.Value.ProfileKey -ine $Tenant) {throw 'Profile is missing, invalid, conflicting or mismatched.'}
    $path=$base+'.json'; if (Test-Path -LiteralPath ($path+'.txt') -PathType Leaf) {$path+='.txt'}
    $profileHash=(Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash
    $tenantId=[guid]::Empty;$appId=[guid]::Empty
    if (-not [guid]::TryParse([string]$profile.Value.TenantId,[ref]$tenantId) -or $tenantId -eq [guid]::Empty -or -not [guid]::TryParse([string]$profile.Value.AppId,[ref]$appId) -or $appId -eq [guid]::Empty) {throw 'The profile requires nonzero tenant and application GUIDs.'}
    $sender=[string]$profile.Value.From
    foreach ($address in @($sender,$Outside)) {try {if ($address.Length -gt 320 -or $address -match '[\x00-\x1f\x7f\u200e\u200f\u202a-\u202e\u2066-\u2069]') {throw 'invalid'};$m=[Net.Mail.MailAddress]::new($address);if ($m.Address -ine $address) {throw 'invalid'}} catch {throw 'Use valid bare sender and outside mailbox addresses.'}}
    if ($sender -ieq $Outside -or [string]::IsNullOrWhiteSpace($ExpectedScope) -or $ExpectedScope.Length -gt 256 -or $ExpectedScope -match '[\x00-\x1f\u200e\u200f\u202a-\u202e\u2066-\u2069]') {throw 'Distinct mailboxes and a valid expected scope are required.'}
    $catalogInfo=Get-Item -LiteralPath $CatalogPath -Force -ErrorAction Stop
    if ($catalogInfo.PSIsContainer -or $catalogInfo.Length -gt 20MB) {throw 'Catalog is not a supported JSON file.'}
    $bytes=[IO.File]::ReadAllBytes($CatalogPath);$sha=[Security.Cryptography.SHA256]::Create()
    try {$catalogHash=([BitConverter]::ToString($sha.ComputeHash($bytes))).Replace('-','')} finally {$sha.Dispose()}
    $catalog=[Text.UTF8Encoding]::new($false,$true).GetString($bytes).TrimStart([char]0xfeff) | ConvertFrom-Json -ErrorAction Stop
    if ($catalog -isnot [pscustomobject] -or $catalog.Jobs -isnot [array]) {throw 'Catalog must contain a Jobs array.'}
    if ($catalog.Jobs.Count -gt 10000) {throw 'Catalog contains too many jobs.'}
    $roles=[Collections.Generic.List[string]]::new();$undeclared=0
    foreach ($job in $catalog.Jobs) {
        if ($job.Enabled -isnot [bool]) {throw 'Every catalog job must have a Boolean Enabled field.'}
        if (-not $job.Enabled) {continue}
        if ($null -eq $job.PSObject.Properties['RequiredGraphAppRoles']) {$undeclared++;continue}
        if ($job.RequiredGraphAppRoles -isnot [array]) {throw 'RequiredGraphAppRoles must be an array.'}
        foreach ($role in $job.RequiredGraphAppRoles) {if ($role -isnot [string] -or $role -notmatch '^[A-Za-z0-9._-]{1,128}$') {throw 'A Graph role declaration is invalid.'};$roles.Add($role)}
    }
    $unique=@($roles | Select-Object -Unique)
    if ($unique.Count -gt 500) {throw 'Too many Graph role declarations.'}
    $again=Read-SiPrivateJson $base
    if ($again.State -ne 'Present' -or (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash -cne $profileHash -or (Get-FileHash -LiteralPath $CatalogPath -Algorithm SHA256).Hash -cne $catalogHash) {throw 'Profile or catalog changed; review again.'}
    $sources=@($Worker)+@('SmartM365.GraphPermissionCheck.ps1','SmartM365.ExchangePermissionCheck.ps1' | ForEach-Object {Join-Path $PSScriptRoot $_})
    $receipts=@(foreach ($source in $sources) {if (-not (Test-Path -LiteralPath $source -PathType Leaf)) {throw 'A permission-check component is missing.'};[pscustomobject]@{Path=$source;Hash=(Get-FileHash -LiteralPath $source -Algorithm SHA256).Hash}})
    [pscustomobject]@{Root=$Root;Tenant=$Tenant;TenantId=$tenantId.ToString();AppId=$appId.ToString();Sender=$sender;Outside=$Outside;ExpectedScope=$ExpectedScope;CatalogPath=[IO.Path]::GetFullPath($CatalogPath);CatalogHash=$catalogHash;ProfilePath=$path;ProfileHash=$profileHash;RequiredRoles=$unique;UndeclaredJobs=$undeclared;Worker=$Worker;Sources=$receipts}
}

