param([Parameter(Mandatory)][string]$StatePath,[Parameter(Mandatory)][int]$ParentId,[Parameter(Mandatory)][long]$ParentStartTicks)
$ErrorActionPreference='Stop'
Add-Type -AssemblyName PresentationFramework
[xml]$xaml=Get-Content -LiteralPath (Join-Path (Split-Path -Parent $PSScriptRoot) 'Views/SmartM365-ApplyProgress.xaml') -Raw
$dialog=[Windows.Markup.XamlReader]::Load([System.Xml.XmlNodeReader]::new($xaml))
$state=@{Close=$false}
$dialog.Add_Closing({param($sender,$eventArgs) if (-not $state.Close) {$eventArgs.Cancel=$true}}.GetNewClosure())
$timer=[Windows.Threading.DispatcherTimer]::new();$timer.Interval=[TimeSpan]::FromMilliseconds(250)
$timer.Add_Tick({
    try {
        $parent=Get-Process -Id $ParentId -ErrorAction Stop
        if ($parent.StartTime.ToUniversalTime().Ticks -ne $ParentStartTicks) {throw 'Parent changed.'}
        try {$message=Get-Content -LiteralPath $StatePath -Raw -ErrorAction Stop} catch {return}
        if ($message -eq '__CLOSE__') {$state.Close=$true;$timer.Stop();$dialog.Close();return}
        if ($message) {$dialog.FindName('Message').Text=$message}
    } catch {$state.Close=$true;$timer.Stop();$dialog.Close()}
}.GetNewClosure())
$dialog.Add_ContentRendered({[IO.File]::WriteAllText($StatePath+'.ready','ready')}.GetNewClosure())
$timer.Start();[void]$dialog.ShowDialog()

