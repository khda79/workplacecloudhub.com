# Guarded grouped tenant identity editing, version 0.1.0.
function Get-SiTenantIdentitySnapshot {
    param([Parameter(Mandatory)][string]$Root,[Parameter(Mandatory)][string]$Tenant)
    $legacy=Get-SiEditLocation -Root $Root -Tenant $Tenant -Step 'tenant'
    if ((Read-SiPrivateJson ($legacy.Substring(0,$legacy.Length-5))).State -ne 'Present') {throw 'Configuration missing, invalid or conflicting.'}
    $read=Read-SmartM365JsonDocument -Path $legacy
    if ($read.Coexistence -ne 'Single') {throw 'Coexisting configuration files require review.'}
    $current=[ordered]@{}
    foreach ($key in @('ProfileKey','OrganizationKey','EnvironmentKey','TenantKey')) {
        $property=$read.Document.PSObject.Properties[$key]
        if ($null -ne $property -and $null -ne $property.Value -and $property.Value -isnot [string]) {throw 'An identity field has an unexpected type.'}
        $current[$key]=if ($null -eq $property) {''} else {[string]$property.Value}
        if ($current[$key] -match '[\x00-\x1f\x7f\u200e\u200f\u202a-\u202e\u2066-\u2069]') {throw 'An identity field contains unsupported control characters.'}
    }
    [pscustomobject]@{Root=$Root;Tenant=$Tenant;Path=$read.Path;Hash=$read.SHA256;Current=[pscustomobject]$current}
}
function New-SiTenantIdentityEditPlan {
    param([Parameter(Mandatory)]$Snapshot,[Parameter(Mandatory)][string]$OrganizationKey,[Parameter(Mandatory)][string]$EnvironmentKey)
    foreach ($key in @($OrganizationKey,$EnvironmentKey)) {if ($key -cnotmatch '^[a-z0-9][a-z0-9-]{0,63}$') {throw 'Organization and environment keys require lowercase letters, digits or hyphens.'}}
    $fresh=Get-SiTenantIdentitySnapshot -Root $Snapshot.Root -Tenant $Snapshot.Tenant
    if ($fresh.Path -cne $Snapshot.Path -or $fresh.Hash -cne $Snapshot.Hash) {throw 'Configuration changed; review it again.'}
    $templatePath=Join-Path $Snapshot.Root 'Config/Tenants/tenant.local.json.template'
    $bytes=[IO.File]::ReadAllBytes($templatePath)
    $sha=[Security.Cryptography.SHA256]::Create();try {$templateHash=([BitConverter]::ToString($sha.ComputeHash($bytes))).Replace('-','')} finally {$sha.Dispose()}
    $model=[Text.UTF8Encoding]::new($false,$true).GetString($bytes).TrimStart([char]0xfeff) | ConvertFrom-Json -ErrorAction Stop
    if ($model -isnot [pscustomobject]) {throw 'Invalid tenant template.'}
    $read=Read-SmartM365JsonDocument -Path (Get-SiEditLocation -Root $Snapshot.Root -Tenant $Snapshot.Tenant -Step tenant)
    if ($read.SHA256 -cne $Snapshot.Hash -or $read.Path -cne $Snapshot.Path -or $read.Coexistence -ne 'Single') {throw 'Configuration changed; review it again.'}
    $keys=@(Add-SmartM365MissingJsonTemplateProperties -Target $read.Document -Template $model)
    $additions=@(foreach ($key in $keys) {
        $node=$read.Document
        foreach ($part in ($key -split '\.')) {$property=$node.PSObject.Properties[$part];if ($null -eq $property) {throw 'Template addition cannot be displayed.'};$node=$property.Value}
        $json=ConvertTo-Json -InputObject $node -Depth 100 -Compress
        if ($json -match '[\u200e\u200f\u202a-\u202e\u2066-\u2069]') {throw 'Template addition contains unsupported direction controls.'}
        [pscustomobject]@{Field=$key;ValueJson=$json}
    })
    foreach ($key in @('ProfileKey','OrganizationKey','EnvironmentKey','TenantKey')) {if ($null -eq $read.Document.PSObject.Properties[$key]) {throw 'Tenant template is missing an identity field.'}}
    [pscustomobject]@{Snapshot=$Snapshot;OrganizationKey=$OrganizationKey;EnvironmentKey=$EnvironmentKey;TenantKey=($OrganizationKey+'-'+$EnvironmentKey);TemplateHash=$templateHash;AddedKeys=$keys;Additions=$additions}
}
function Set-SiTenantIdentityEditPlan {
    param([Parameter(Mandatory)]$Plan)
    $fresh=New-SiTenantIdentityEditPlan -Snapshot $Plan.Snapshot -OrganizationKey $Plan.OrganizationKey -EnvironmentKey $Plan.EnvironmentKey
    if ($fresh.TenantKey -cne $Plan.TenantKey -or $fresh.TemplateHash -cne $Plan.TemplateHash -or (($fresh.Additions | ConvertTo-Json -Depth 100 -Compress) -cne ($Plan.Additions | ConvertTo-Json -Depth 100 -Compress))) {throw 'The reviewed identity plan changed.'}
    $legacy=Get-SiEditLocation -Root $Plan.Snapshot.Root -Tenant $Plan.Snapshot.Tenant -Step tenant
    $read=Read-SmartM365JsonDocument -Path $legacy
    if ($read.Coexistence -ne 'Single' -or $read.Path -cne $Plan.Snapshot.Path -or $read.SHA256 -cne $Plan.Snapshot.Hash) {throw 'Configuration changed; review it again.'}
    $templatePath=Join-Path $Plan.Snapshot.Root 'Config/Tenants/tenant.local.json.template'
    $bytes=[IO.File]::ReadAllBytes($templatePath);$sha=[Security.Cryptography.SHA256]::Create();try {$hash=([BitConverter]::ToString($sha.ComputeHash($bytes))).Replace('-','')} finally {$sha.Dispose()}
    if ($hash -cne $Plan.TemplateHash) {throw 'Template changed; review it again.'}
    $template=[Text.UTF8Encoding]::new($false,$true).GetString($bytes).TrimStart([char]0xfeff) | ConvertFrom-Json -ErrorAction Stop
    $added=@(Add-SmartM365MissingJsonTemplateProperties -Target $read.Document -Template $template)
    if (($added -join "`n") -cne ($Plan.AddedKeys -join "`n")) {throw 'Template additions changed; review them again.'}
    $read.Document.ProfileKey=$Plan.Snapshot.Tenant;$read.Document.OrganizationKey=$Plan.OrganizationKey;$read.Document.EnvironmentKey=$Plan.EnvironmentKey;$read.Document.TenantKey=$Plan.TenantKey
    $output=[Text.UTF8Encoding]::new($false).GetBytes(($read.Document | ConvertTo-Json -Depth 100)+[Environment]::NewLine)
    $written=Write-SmartM365JsonBytesAtomically -Path $read.Path -Bytes $output -ExpectedSHA256 $Plan.Snapshot.Hash -Validate {param($d) if ($d -isnot [pscustomobject]) {throw 'Expected JSON object.'}}
    $confirmed=$false
    try {
        $after=Get-SiTenantIdentitySnapshot -Root $Plan.Snapshot.Root -Tenant $Plan.Snapshot.Tenant
        $confirmed=($after.Path -ceq $read.Path -and $after.Hash -ceq $written.SHA256 -and $after.Current.ProfileKey -ceq $Plan.Snapshot.Tenant -and $after.Current.OrganizationKey -ceq $Plan.OrganizationKey -and $after.Current.EnvironmentKey -ceq $Plan.EnvironmentKey -and $after.Current.TenantKey -ceq $Plan.TenantKey)
    } catch { $confirmed=$false }
    [pscustomobject]@{State=if ($confirmed) {'Saved'} else {'SavedReview'};ProfileKey=$Plan.Snapshot.Tenant;TenantKey=$Plan.TenantKey;AddedKeys=$added}
}

