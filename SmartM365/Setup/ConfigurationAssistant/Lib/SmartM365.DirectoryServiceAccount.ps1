# Create-only AD service accounts, version 0.1.0. No directory is contacted during planning.
function New-SiDirectoryServiceAccount {
    param(
        [Parameter(Mandatory)][ValidateSet('DomainUser')][string]$Kind,
        [Parameter(Mandatory)][string]$Name,
        [Parameter(Mandatory)][string]$DomainController,
        [Parameter(Mandatory)][string]$OrganizationalUnit,
        [Security.SecureString]$Password,
        [string[]]$ComputerNames=@(),
        [scriptblock]$Inspect,[scriptblock]$Create,[scriptblock]$ReadBack
    )
    $Name=$Name.Trim(); $DomainController=$DomainController.Trim(); $OrganizationalUnit=$OrganizationalUnit.Trim()
    if ($Name -cnotmatch '^[A-Za-z0-9][A-Za-z0-9_-]{0,14}$') { throw 'Account name must contain 1 to 15 letters, digits, hyphens or underscores.' }
    if ([Uri]::CheckHostName($DomainController) -ne [UriHostNameType]::Dns -or -not $DomainController.Contains('.')) { throw 'Enter an explicit domain controller DNS name.' }
    if ($OrganizationalUnit.Length -lt 4 -or $OrganizationalUnit.Length -gt 1024 -or $OrganizationalUnit -match '[\x00-\x1f]') { throw 'Enter the distinguished name of an organizational unit.' }
    if ($Kind -eq 'DomainUser' -and ($null -eq $Password -or $Password.Length -eq 0)) { throw 'A password is required for a domain user.' }
    if (@($ComputerNames).Count -gt 0) { throw 'Computer principals are not supported.' }
    $computers=@()
    $sam=$Name
    if ($null -eq $Inspect) {
        $Inspect={param($dc,$ouName,$samName,$hosts)
            Import-Module ActiveDirectory -ErrorAction Stop
            $domain=Get-ADDomain -Server $dc -ErrorAction Stop
            $ou=Get-ADObject -Identity $ouName -Server $dc -Properties objectClass -ErrorAction Stop
            if ($ou.ObjectClass -notin @('organizationalUnit','container')) {throw 'Select an organizational unit or directory container.'}
            if (-not ([string]$ou.DistinguishedName).EndsWith(','+[string]$domain.DistinguishedName,[StringComparison]::OrdinalIgnoreCase)) { throw 'The organizational unit does not belong to the selected domain.' }
            $existing=@(Get-ADObject -LDAPFilter ("(sAMAccountName={0})" -f $samName) -Server $dc -ErrorAction Stop)
            $principals=@(foreach ($hostName in $hosts) { (Get-ADComputer -Identity $hostName -Server $dc -ErrorAction Stop).DistinguishedName })
            [pscustomobject]@{DomainDns=[string]$domain.DNSRoot;OU=[string]$ou.DistinguishedName;Existing=$existing.Count;Principals=$principals}
        }
    }
    $inspection=& $Inspect $DomainController $OrganizationalUnit $sam $computers
    if ($null -eq $inspection -or $inspection.Existing -ne 0 -or [string]::IsNullOrWhiteSpace($inspection.OU) -or [Uri]::CheckHostName([string]$inspection.DomainDns) -ne [UriHostNameType]::Dns -or @($inspection.Principals).Count -ne $computers.Count) { throw 'Directory inspection failed or the account already exists; no account was changed.' }
    if ($null -eq $Create) {
        $Create={param($type,$account,$dc,$info,$secret)
            New-ADUser -Name $account -SamAccountName $account -UserPrincipalName ($account+'@'+$info.DomainDns) -Path $info.OU -Server $dc -AccountPassword $secret -Enabled $true -PassThru -ErrorAction Stop
        }
    }
    if ($null -eq $ReadBack) {
        $ReadBack={param($type,$account,$dc) Get-ADUser -Identity $account -Server $dc -ErrorAction Stop }
    }
    try { $created=& $Create $Kind $Name $DomainController $inspection $Password; $observed=& $ReadBack $Kind $Name $DomainController }
    catch { throw 'Creation or verification was not confirmed. Inspect the selected directory before retrying; the account may exist.' }
    if ($null -eq $created -or $null -eq $observed -or [string]::IsNullOrWhiteSpace([string]$created.SID) -or [string]$created.SID -cne [string]$observed.SID -or [string]$observed.SamAccountName -ine $sam -or $observed.Enabled -ne $true) { throw 'Creation may have succeeded, but identity or enabled-state verification failed. Inspect the selected directory before retrying.' }
    [pscustomobject]@{Name=$sam;Sid=[string]$observed.SID;Domain=[string]$inspection.DomainDns;Kind=$Kind;State='CreatedReviewRequired';Detail='Account created. Task logon, host installation, access and certificate rights require separate verification.'}
}

