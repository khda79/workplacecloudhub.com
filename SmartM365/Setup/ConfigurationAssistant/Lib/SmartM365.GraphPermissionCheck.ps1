# Read-only Graph app-role comparison, version 0.1.0.
function Get-SiGraphPermissionAssessment {
    param([Parameter(Mandatory)][string]$TenantId,[Parameter(Mandatory)][string]$AppId,[Parameter(Mandatory)][AllowEmptyCollection()][string[]]$RequiredRoles,[scriptblock]$Reader)
    $tenant=[guid]::Empty; $app=[guid]::Empty
    if (-not [guid]::TryParse($TenantId,[ref]$tenant) -or $tenant -eq [guid]::Empty -or -not [guid]::TryParse($AppId,[ref]$app) -or $app -eq [guid]::Empty) { throw 'Valid tenant and application GUIDs are required.' }
    $requested=@($RequiredRoles | Select-Object -Unique)
    if ($requested.Count -gt 500 -or @($requested | Where-Object {$_ -notmatch '^[A-Za-z0-9._-]{1,128}$'}).Count) { throw 'Invalid expected Graph role list.' }
    if ($null -eq $Reader) {
        $Reader={param($tenantId,$applicationId)
            $context=Get-MgContext -ErrorAction Stop
            if ($null -eq $context -or $context.AuthType -ne 'Delegated' -or [string]$context.TenantId -ine $tenantId -or 'Application.Read.All' -notin @($context.Scopes)) { throw 'A delegated read-only Graph session in the expected tenant is required.' }
            $principal=@(Get-MgServicePrincipal -Filter ("appId eq '{0}'" -f $applicationId) -Property 'id,appId' -All -ErrorAction Stop)
            $graph=@(Get-MgServicePrincipal -Filter "appId eq '00000003-0000-0000-c000-000000000000'" -Property 'id,appId,appRoles' -All -ErrorAction Stop)
            if ($principal.Count -ne 1 -or $graph.Count -ne 1) { throw 'The target or Microsoft Graph service principal is ambiguous.' }
            $assignments=@(Get-MgServicePrincipalAppRoleAssignment -ServicePrincipalId $principal[0].Id -All -ErrorAction Stop)
            [pscustomobject]@{TenantId=[string]$context.TenantId;AppId=[string]$principal[0].AppId;PrincipalId=[string]$principal[0].Id;GraphResourceId=[string]$graph[0].Id;Roles=@($graph[0].AppRoles);Assignments=$assignments}
        }
    }
    $data=& $Reader $tenant.ToString() $app.ToString()
    if ($null -eq $data -or [string]$data.TenantId -ine $tenant.ToString() -or [string]$data.AppId -ine $app.ToString()) { throw 'Graph result does not match the selected tenant and application.' }
    $principal=[guid]::Empty; $resource=[guid]::Empty
    if (-not [guid]::TryParse([string]$data.PrincipalId,[ref]$principal) -or $principal -eq [guid]::Empty -or -not [guid]::TryParse([string]$data.GraphResourceId,[ref]$resource) -or $resource -eq [guid]::Empty) { throw 'Graph service principal identities are invalid.' }
    if ($null -eq $data.PSObject.Properties['Roles'] -or $null -eq $data.PSObject.Properties['Assignments']) { throw 'Graph returned incomplete role information.' }
    $roleMap=@{}
    foreach ($role in @($data.Roles)) {
        $roleId=[guid]::Empty
        if (-not [guid]::TryParse([string]$role.Id,[ref]$roleId) -or $roleId -eq [guid]::Empty -or [string]::IsNullOrWhiteSpace([string]$role.Value)) { continue }
        if (@($role.AllowedMemberTypes) -notcontains 'Application') { continue }
        $key=$roleId.ToString(); if ($roleMap.ContainsKey($key)) { throw 'Graph returned duplicate app role identifiers.' }
        $roleMap[$key]=[pscustomobject]@{Value=[string]$role.Value;Enabled=($role.IsEnabled -eq $true)}
    }
    if ($roleMap.Count -eq 0) { throw 'Graph application role definitions are unavailable.' }
    $granted=[Collections.Generic.List[string]]::new(); $unmapped=0; $broadMail=$false
    foreach ($assignment in @($data.Assignments)) {
        $assignmentPrincipal=[guid]::Empty; $assignmentResource=[guid]::Empty
        if (-not [guid]::TryParse([string]$assignment.PrincipalId,[ref]$assignmentPrincipal) -or $assignmentPrincipal -ne $principal -or -not [guid]::TryParse([string]$assignment.ResourceId,[ref]$assignmentResource) -or $assignmentResource -eq [guid]::Empty) { $unmapped++; continue }
        if ($assignmentResource -ne $resource) { continue }
        $roleId=[guid]::Empty
        if (-not [guid]::TryParse([string]$assignment.AppRoleId,[ref]$roleId) -or -not $roleMap.ContainsKey($roleId.ToString())) { $unmapped++; continue }
        $definition=$roleMap[$roleId.ToString()]
        if ($definition.Value -eq 'Mail.Send') { $broadMail=$true }
        if (-not $definition.Enabled) { $unmapped++; continue }
        $granted.Add($definition.Value)
    }
    $missing=@($requested | Where-Object { $_ -notin $granted })
    $state=if ($broadMail -or $missing.Count -gt 0) { 'ReviewRequired' } elseif ($unmapped -gt 0) { 'Uncertain' } else { 'ObservedReviewRequired' }
    [pscustomobject]@{State=$state;PrincipalId=$principal.ToString();Missing=$missing;BroadGraphMailSend=$broadMail;UnmappedAssignments=$unmapped;OperationallyQualified=$false;Detail='Only listed Graph application roles were compared. Role replication, Exchange App RBAC, site-specific grants, effective token access and actual workload execution remain unverified.'}
}

