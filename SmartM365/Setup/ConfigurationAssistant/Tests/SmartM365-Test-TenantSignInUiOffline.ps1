param([switch]$SelfTestChild)
$ErrorActionPreference='Stop'
if ([Threading.Thread]::CurrentThread.ApartmentState -ne 'STA') {
    & (Join-Path $PSHOME 'pwsh.exe') -NoProfile -STA -File $PSCommandPath -SelfTestChild
    exit $LASTEXITCODE
}
Add-Type -AssemblyName PresentationFramework,PresentationCore,WindowsBase
$root=Split-Path -Parent $PSScriptRoot
. (Join-Path $root 'Lib/SmartM365.TenantSignInUi.InitialDomain.ps1')
$unstoppable=[pscustomobject]@{HasExited=$false;KillCount=0;WaitCount=0}
$unstoppable | Add-Member ScriptMethod Kill {$this.KillCount++}
$unstoppable | Add-Member ScriptMethod WaitForExit {param($milliseconds) $this.WaitCount++;return $false}
$uncertain=$false;try {Stop-SiTenantSignInProcess -Process $unstoppable} catch {$uncertain=$_.Exception.Message -match 'termination is uncertain'}
if (-not $uncertain -or $unstoppable.KillCount -ne 1 -or $unstoppable.WaitCount -ne 1) {throw 'An unconfirmed sign-in process stop was accepted.'}
$stuckDialog=[Windows.Window]::new();[Windows.NameScope]::SetNameScope($stuckDialog,[Windows.NameScope]::new());$stuckPanel=[Windows.Controls.StackPanel]::new();$stuckDialog.Content=$stuckPanel
foreach ($name in @('TenantStatus','DetectTenant','Cancel')) {$control=if($name -eq 'TenantStatus'){[Windows.Controls.TextBlock]::new()}else{[Windows.Controls.Button]::new()};$control.Name=$name;$stuckDialog.RegisterName($name,$control);[void]$stuckPanel.Children.Add($control)}
$unstoppable | Add-Member ScriptMethod Dispose {}
$stuckState=@{Process=$unstoppable;Timer=$null;Path='';ProgressPath=''}
Initialize-SiTenantSignInDialog -Dialog $stuckDialog -State $stuckState -LibraryRoot (Join-Path $root 'Lib') -Changed {} -InstallPrerequisites {} -OfflineFixture $true
$check=[Windows.Threading.DispatcherTimer]::new();$check.Interval=[TimeSpan]::FromMilliseconds(100);$checkState=@{Blocked=$false}
$check.Add_Tick({$check.Stop();$stuckDialog.Close();$checkState.Blocked=$stuckDialog.IsVisible -and $stuckDialog.FindName('TenantStatus').Text -eq 'Sign-in could not be stopped yet.';$unstoppable.HasExited=$true;$stuckDialog.Close()}.GetNewClosure())
$stuckDialog.Add_ContentRendered({$check.Start()}.GetNewClosure());[void]$stuckDialog.ShowDialog()
if (-not $checkState.Blocked) {throw 'The sign-in dialog closed without confirming process termination.'}
foreach ($scenario in @('Success','Rejected','Failure','Cancelled')) {
    $dialog=[Windows.Window]::new();$dialog.Title='Synthetic Microsoft sign-in';$dialog.Width=400;$dialog.Height=250
    [Windows.NameScope]::SetNameScope($dialog,[Windows.NameScope]::new())
    $panel=[Windows.Controls.StackPanel]::new();$dialog.Content=$panel
    foreach ($name in @('TenantStatus','DetectTenant','Cancel')) {
        $control=if ($name -eq 'TenantStatus') {[Windows.Controls.TextBlock]::new()} else {[Windows.Controls.Button]::new()}
        $control.Name=$name;$dialog.RegisterName($name,$control);[void]$panel.Children.Add($control)
    }
    $state=@{Tenant='';Account='';Path='';ProgressPath='';Process=$null;Timer=$null}
    $test=@{Confirmed=0;Changed=0;Error='';Tick=0;ProgressSeen=$false}
    $changed={$test.Changed++}.GetNewClosure()
    $confirm={param($tenant,$account) $test.Confirmed++;if ($tenant -ne '11111111-2222-3333-4444-555555555555' -or $account -ne 'user@synthetic.invalid') {throw 'Incorrect detected identity.'};return ($scenario -eq 'Success')}.GetNewClosure()
    $start={param($worker,$result,$progress)
        $q={param($v) "'"+$v.Replace("'","''")+"'"}
        $delay=if ($scenario -eq 'Cancelled') {15000} else {800}
        $body="[IO.File]::WriteAllText("+(& $q $progress)+",'Synthetic sign-in in progress'); Start-Sleep -Milliseconds "+$delay+'; '
        if ($scenario -eq 'Failure') {$body+='exit 1'} else {$body+="[IO.File]::WriteAllText("+(& $q $result)+",'{`"TenantId`":`"11111111-2222-3333-4444-555555555555`",`"Account`":`"user@synthetic.invalid`"}'); exit 0"}
        $encoded=[Convert]::ToBase64String([Text.Encoding]::Unicode.GetBytes($body))
        Start-Process -FilePath (Join-Path $PSHOME 'pwsh.exe') -ArgumentList @('-NoProfile','-EncodedCommand',$encoded) -WindowStyle Hidden -PassThru
    }.GetNewClosure()
    Initialize-SiTenantSignInDialog -Dialog $dialog -State $state -LibraryRoot (Join-Path $root 'Lib') -Changed $changed -InstallPrerequisites {} -StartWorker $start -ConfirmTenant $confirm -ModuleAvailable {$true}
    $driver=[Windows.Threading.DispatcherTimer]::new();$driver.Interval=[TimeSpan]::FromMilliseconds(100)
    $driver.Add_Tick({
        try {
            $test.Tick++
            if ($test.Tick -eq 1) {$dialog.FindName('DetectTenant').RaiseEvent([Windows.RoutedEventArgs]::new([Windows.Controls.Primitives.ButtonBase]::ClickEvent))}
            if ($dialog.FindName('TenantStatus').Text -eq 'Synthetic sign-in in progress') {$test.ProgressSeen=$true}
            if ($scenario -eq 'Cancelled' -and $test.ProgressSeen) {$driver.Stop();$dialog.Close()}
            elseif ($test.Tick -gt 1 -and $null -eq $state.Process) {$driver.Stop();$dialog.Close()}
            elseif ($test.Tick -gt 150) {$test.Error='Timed out waiting for simulated sign-in.';$driver.Stop();$dialog.Close()}
        } catch {$test.Error=$_.Exception.Message;$driver.Stop();$dialog.Close()}
    }.GetNewClosure())
    $dialog.Add_ContentRendered({$driver.Start()}.GetNewClosure())
    [void]$dialog.ShowDialog()
    if ($test.Error) {throw $test.Error}
    if (-not $test.ProgressSeen) {throw 'Sign-in progress was not shown.'}
    if ($state.Process -or $state.Timer -or (Test-Path -LiteralPath $state.Path) -or (Test-Path -LiteralPath $state.ProgressPath)) {throw 'Sign-in resources were not cleaned up.'}
    if ($scenario -eq 'Success' -and ($test.Confirmed -ne 1 -or $state.Tenant -ne '11111111-2222-3333-4444-555555555555' -or $state.Account -ne 'user@synthetic.invalid')) {throw 'Successful sign-in did not update the dialog.'}
    if ($scenario -eq 'Rejected' -and ($test.Confirmed -ne 1 -or $state.Tenant -or $state.Account)) {throw 'Rejected tenant was accepted.'}
    if ($scenario -eq 'Failure' -and ($test.Confirmed -ne 0 -or $state.Tenant -or $dialog.FindName('TenantStatus').Text -notlike 'Tenant detection failed*')) {throw 'Failed sign-in was not handled.'}
    if ($scenario -eq 'Cancelled' -and ($test.Confirmed -ne 0 -or $state.Tenant)) {throw 'Cancelled sign-in was accepted.'}
}
