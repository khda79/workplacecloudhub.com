    $steps = @(Get-SiStepAudit -SmartM365Root $fixture -Tenant 'test')
    if (($steps | Where-Object Id -eq 'tenant').State -ne 'Local consistency checked') { throw 'Valid local profile was not recognized.' }
    if (($steps | Where-Object Id -eq 'permissions').State -ne 'Not checked') { throw 'Local values cannot prove remote permissions.' }
    if ((Get-FileHash $tenantFile).Hash -ne $hash) { throw 'Step audit modified the profile.' }
    [IO.File]::WriteAllText($tenantFile + '.txt', '{}')
