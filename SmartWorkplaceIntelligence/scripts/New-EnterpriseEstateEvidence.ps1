[CmdletBinding()]
param([Parameter(Mandatory)][string]$DataRoot,[Parameter(Mandatory)][string]$OutputRoot,[string]$AdCountryRulesPath)
# Local preparation only: no collection, network calls, batch activation or Power BI refresh.
Set-StrictMode -Version Latest
$ErrorActionPreference='Stop'
if($PSVersionTable.PSVersion.Major -lt 7){throw 'PowerShell 7 is required.'}
Import-Module (Join-Path $PSScriptRoot 'EnterpriseEstateEvidence.psm1') -Force
Import-Module (Join-Path $PSScriptRoot 'AdCountryEvidence.psm1') -Force
$data=(Resolve-Path -LiteralPath $DataRoot).ProviderPath
$last=Join-Path $data 'DATA-LAST';$output=[IO.Path]::GetFullPath($OutputRoot).TrimEnd('\','/')
if($output -eq $data.TrimEnd('\','/') -or $output.StartsWith($data.TrimEnd('\','/')+'\',[StringComparison]::OrdinalIgnoreCase)){throw 'Outputs must not overwrite raw sources or active prepared data.'}
if($output -match '[\\/]pbip(?:[\\/]|$)'){throw 'Outputs must not be placed in a PBIP.'}
$cursor=$output
while($cursor){if(Test-Path -LiteralPath (Join-Path $cursor '.git')){throw 'Client evidence must not be written into a Git checkout.'};$parent=Split-Path $cursor -Parent;if($parent -eq $cursor){break};$cursor=$parent}
foreach($name in @('AllAccountsEvidence.csv','AllDevicesEvidence.csv','EnterpriseEstateAudit.json.txt')){if(Test-Path -LiteralPath (Join-Path $output $name)){throw 'Estate staging outputs already exist; choose an unused directory.'}}
$sources=[Collections.Generic.List[object]]::new()
$identity=@('TenantKey','OrganizationKey','EnvironmentKey','TenantId')
function Read-EstateCsv([string]$Name,[string[]]$Columns,[string[]]$Optional=@()){
    $path=Join-Path $last $Name;$file=Get-Item -LiteralPath $path;$hash=(Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash
    $parser=[Microsoft.VisualBasic.FileIO.TextFieldParser]::new($path)
    try{
        $parser.SetDelimiters(',');$parser.HasFieldsEnclosedInQuotes=$true;$parser.TrimWhiteSpace=$false
        $head=$parser.ReadFields();if(-not $head -or @($head|Sort-Object -Unique).Count -ne $head.Length){throw 'Missing or duplicate CSV headers.'}
        $keep=@($identity+$Columns|Select-Object -Unique)
        foreach($col in $keep){if($col -cnotin $head){throw "Required CSV column missing in ${Name}: $col"}}
        $keep+=@($Optional|Where-Object {$_ -cin $head -and $_ -cnotin $keep})
        $positions=@{};foreach($col in $keep){$positions[$col]=[array]::IndexOf($head,$col)}
        $rows=[Collections.Generic.List[object]]::new()
        while(-not $parser.EndOfData){$fields=$parser.ReadFields();if($fields.Length -ne $head.Length){throw "Malformed CSV record: $Name"};$row=[ordered]@{};foreach($col in $keep){$row[$col]=$fields[$positions[$col]]};$rows.Add([pscustomobject]$row)}
    }finally{$parser.Dispose()}
    $sources.Add([pscustomobject]@{File=$Name;Path=$file.FullName;SHA256=$hash;Rows=$rows.Count;Bytes=$file.Length;PublicationUtc=$file.LastWriteTimeUtc.ToString('O')})
    Write-Host "Read $Name ($($rows.Count) records)."
    return ,$rows.ToArray()
}
$ad=Read-EstateCsv 'AD_Users_AllDomains.csv' @('ObjectGUID','ObjectSID','ImmutableId_AD','UserPrincipalName','Enabled') @('Country','CountryName')
$cloud=Read-EstateCsv 'M365_Users_Active.csv' @('Object Id','OnPremisesSecurityIdentifier','OnPremisesImmutableId','User principal name','AccountEnabled','UserType','CollectedAtUtc') @('CountryOrRegion')
$directory=Read-EstateCsv 'AD_DirectoryObjects_AllDomains.csv' @('ObjectClass','ObjectGUID','ObjectSID','DomainName') @('Name','SamAccountName')
$managed=Read-EstateCsv 'Intune_ManagedDevices_All.csv' @('ManagedDeviceId','AzureADDeviceId','OperatingSystem','UserId','CollectedAtUtc')
$computers=Read-EstateCsv 'AD_Computers_AllDomains.csv' @('ObjectGUID') @('Name','SamAccountName','DomainName')
$countryRules=Read-AdCountryRules -Path $AdCountryRulesPath -ExpectedTenantKey $cloud[0].TenantKey
$result=New-EnterpriseEstateProjection -ADUsers $ad -EntraUsers $cloud -DirectoryObjects $directory -ManagedDevices $managed -ADComputers $computers -ADObservationUtc $sources[2].PublicationUtc -ADUserObservationUtc $sources[0].PublicationUtc -EntraObservationUtc $cloud[0].CollectedAtUtc -IntuneObservationUtc $managed[0].CollectedAtUtc -AdCountryRules $countryRules
foreach($source in $sources){if((Get-FileHash -LiteralPath $source.Path -Algorithm SHA256).Hash -ne $source.SHA256){throw 'Source changed during estate preparation. No outputs written.'}}
if($AdCountryRulesPath -and (Get-FileHash -LiteralPath $AdCountryRulesPath).Hash -cne $countryRules.SourceSHA256){throw 'AD country rules changed during estate preparation. No outputs written.'}
New-Item -ItemType Directory -Path $output -Force|Out-Null
# The publication pipeline adds TenantKey exactly once, after staging validation.
$accountColumns=@($result.Accounts[0].PSObject.Properties.Name|Where-Object {$_ -ne 'TenantKey'})
$deviceColumns=@($result.Devices[0].PSObject.Properties.Name|Where-Object {$_ -ne 'TenantKey'})
$result.Accounts|Select-Object $accountColumns|Export-Csv -LiteralPath (Join-Path $output 'AllAccountsEvidence.csv') -NoTypeInformation -Encoding utf8
$result.Devices|Select-Object $deviceColumns|Export-Csv -LiteralPath (Join-Path $output 'AllDevicesEvidence.csv') -NoTypeInformation -Encoding utf8
$audit=[ordered]@{SchemaVersion=1;CreatedUtc=[datetime]::UtcNow.ToString('O');Projection=$result.Audit;Sources=$sources.ToArray();Published=$false;Refreshed=$false;CountryNormalization='Entra CountryOrRegion only for linked accounts and managed-device primary users, no UsageLocation fallback; explicit tenant domain then configured name prefix for AD-only; conflicts yield Unknown, not verified physical location.';AdCountryRulesSHA256=$(if($AdCountryRulesPath){(Get-FileHash -LiteralPath $AdCountryRulesPath).Hash}else{''})}
[IO.File]::WriteAllText((Join-Path $output 'EnterpriseEstateAudit.json.txt'),($audit|ConvertTo-Json -Depth 8),[Text.UTF8Encoding]::new($false))
$result.Audit|ConvertTo-Json -Depth 5

