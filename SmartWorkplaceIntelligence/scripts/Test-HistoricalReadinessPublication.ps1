<# Synthetic end-to-end publication regression for historical readiness. #>
[CmdletBinding()]
param([string]$TestRoot = (Join-Path ([IO.Path]::GetTempPath()) 'SmartM365-OfflineTests'))
$ErrorActionPreference='Stop'
$root=Join-Path ([IO.Path]::GetFullPath($TestRoot)) ([guid]::NewGuid().ToString('N'))
$staging=Join-Path $root 'staging';$output=Join-Path $root 'DATA-POWERBI'
New-Item -ItemType Directory -Force -Path $staging | Out-Null
Import-Module (Join-Path $PSScriptRoot 'PreparedEvidencePipeline.psm1') -Force
$contractSource=Get-Content -Raw -LiteralPath (Join-Path $PSScriptRoot '../config/prepared-evidence-contract.json.txt') | ConvertFrom-Json
$table=@($contractSource.tables | Where-Object file -eq 'HistoricalWindowsReadiness.csv')
if ($table.Count -ne 1 -or $table[0].stagingIncludesTenantKey -ne $true) {throw 'Historical table must explicitly declare tenant-aware staging.'}
$contractPath=Join-Path $root 'contract.json'
@{tables=@($table[0])} | ConvertTo-Json -Depth 20 | Set-Content -LiteralPath $contractPath
$staged=Join-Path $staging 'HistoricalWindowsReadiness.csv'
$row=[ordered]@{}
foreach($column in $table[0].columns){$row[$column.name]=''}
$row.TenantKey='synthetic-test';$row.ObservationKey='sample-key';$row.'Device Name'='PC1';$row.'Historical Result'='NOT CAPABLE'
[pscustomobject]$row | Export-Csv -LiteralPath $staged -NoTypeInformation -Encoding utf8
$argsForPublish=@{StagingRoot=$staging;OutputRoot=$output;TenantKey='synthetic-test';Provenance=@{Mode='SyntheticTest'};ContractPath=$contractPath}
$first=Publish-PreparedEvidenceBatch @argsForPublish
$result=@(Import-Csv -LiteralPath (Join-Path $first.BatchPath 'HistoricalWindowsReadiness.csv'))
if($result.Count -ne 1 -or $result[0].TenantKey -ne 'synthetic-test' -or $result[0].'Historical Result' -ne 'NOT CAPABLE'){throw 'Tenant-aware row publication mismatch.'}
$pointer=Join-Path $output 'current.json.txt';$before=(Get-FileHash -LiteralPath $pointer).Hash
$row.TenantKey='foreign-test';[pscustomobject]$row | Export-Csv -LiteralPath $staged -NoTypeInformation -Encoding utf8
$rejected=$false
try {Publish-PreparedEvidenceBatch @argsForPublish | Out-Null} catch {$rejected=$_.Exception.Message -like 'Batch validation failed*'}
if(-not $rejected -or (Get-FileHash -LiteralPath $pointer).Hash -ne $before){throw 'Foreign tenant was not safely rejected.'}
$header=($table[0].columns.name | ForEach-Object {'"'+$_+'"'}) -join ','
[IO.File]::WriteAllText($staged,$header+[Environment]::NewLine,[Text.UTF8Encoding]::new($false))
$empty=Publish-PreparedEvidenceBatch @argsForPublish
if(@(Import-Csv -LiteralPath (Join-Path $empty.BatchPath 'HistoricalWindowsReadiness.csv')).Count -ne 0){throw 'Expected empty output.'}
$publishedHeader=Get-Content -LiteralPath (Join-Path $empty.BatchPath 'HistoricalWindowsReadiness.csv') -TotalCount 1
if($publishedHeader -ne $header){throw 'Empty output header changed or duplicated.'}
Write-Host 'PASS: historical tenant-aware publication, foreign tenant rejection, and header-only empty output.'

