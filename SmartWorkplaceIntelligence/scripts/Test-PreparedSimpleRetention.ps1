$ErrorActionPreference='Stop'
Import-Module (Join-Path $PSScriptRoot 'PreparedSimpleRetention.psm1') -Force
$testRoot=Join-Path ([IO.Path]::GetTempPath()) ('prepared-retention-test-'+[guid]::NewGuid().ToString('N'))
$root=Join-Path $testRoot 'DATA-POWERBI'
$batchRoot=Join-Path $root 'batches'
$ids=@('20261028T120000000Z-11111111','20261029T120000000Z-22222222','20261030T120000000Z-33333333','20261031T120000000Z-44444444')
try {
    foreach($id in $ids){New-Item -ItemType Directory -Path (Join-Path $batchRoot $id) -Force | Out-Null; Set-Content -LiteralPath (Join-Path $batchRoot "$id/data.csv") -Value 'sample'}
    $pointer=Join-Path $root 'current.json.txt'
    [IO.File]::WriteAllText($pointer,(@{SchemaVersion=1;TenantKey='test';BatchId=$ids[3];PreviousBatchId=$ids[2]} | ConvertTo-Json),[Text.UTF8Encoding]::new($false))
    $hash=(Get-FileHash $pointer).Hash
    $script:recycled=[Collections.Generic.List[string]]::new()
    $script:reject=$false
    $script:changed=$false
    $script:changeAfterRecycle=$false
    $remote=@($ids | ForEach-Object {[pscustomobject]@{Name=$_;Id=$_;Kind='Folder';Linked=$false;ETag='tag'}})
    $transport=@{
        DescribeSimple={ [pscustomobject]@{RootId='root';BatchesId='batches'} }
        List={ param($id) if($id -eq 'root'){@([pscustomobject]@{Name='current.json.txt';Id='pointer';Kind='File';Linked=$false},[pscustomobject]@{Name='batches';Id='batches';Kind='Folder';Linked=$false})}else{$remote} }
        Download={param($id,$destination) Copy-Item -LiteralPath $pointer -Destination $destination; if($script:changed){Add-Content $destination 'changed'}; $true}
        PrepareRecycle={param($id,$etag) [pscustomobject]@{Id=$id;ETag=$etag} }
        Recycle={param($request) if($script:reject){[pscustomobject]@{Outcome='PreconditionFailed'}}else{$script:recycled.Add($request.Id);if($script:changeAfterRecycle){$script:changed=$true};[pscustomobject]@{Outcome='Recycled'}} }
    }
    $args=@{OutputRoot=$root;TenantKey='test';Transport=$transport;ExpectedPublishedBatchId=$ids[3];ExpectedPointerSHA256=$hash}
    $preview=Invoke-PreparedSimpleRetention @args -Preview
    if($preview.Status -ne 'Preview' -or $script:recycled.Count -ne 0 -or @(Get-ChildItem $batchRoot -Directory).Count -ne 4){throw 'Preview mutated data.'}
    $held=[IO.File]::Open((Join-Path $root '.publication.lock'),'OpenOrCreate','ReadWrite','None')
    try {try {Invoke-PreparedSimpleRetention @args;throw 'Concurrent publication lock ignored.'} catch {if($_.Exception.Message -eq 'Concurrent publication lock ignored.'){throw}}} finally {$held.Dispose()}
    $script:changed=$true
    try {Invoke-PreparedSimpleRetention @args;throw 'Changed pointer accepted.'} catch {if($_.Exception.Message -eq 'Changed pointer accepted.'){throw}}
    $script:changed=$false;$script:reject=$true
    try {Invoke-PreparedSimpleRetention @args;throw 'Rejected recycle accepted.'} catch {if($_.Exception.Message -eq 'Rejected recycle accepted.'){throw}}
    if(@(Get-ChildItem $batchRoot -Directory).Count -ne 4){throw 'Local batches removed after failed remote recycle.'}
    $script:reject=$false
    $script:changeAfterRecycle=$true
    try {Invoke-PreparedSimpleRetention @args;throw 'Changed pointer during cleanup accepted.'} catch {if($_.Exception.Message -eq 'Changed pointer during cleanup accepted.'){throw}}
    if($script:recycled.Count -ne 1 -or @(Get-ChildItem $batchRoot -Directory).Count -ne 4){throw 'Cleanup did not stop when pointer changed.'}
    $script:changed=$false;$script:changeAfterRecycle=$false;$script:recycled.Clear()
    $result=Invoke-PreparedSimpleRetention @args
    if($result.Status -ne 'Completed' -or $script:recycled.Count -ne 2 -or @(Get-ChildItem $batchRoot -Directory).Count -ne 2){throw 'Expected two retained batches on each store.'}
    if(@($script:recycled | Where-Object {$_ -in $ids[2],$ids[3]}).Count){throw 'Protected batch recycled.'}
    'PASS: preview, pointer mismatch, recycle failure and two-batch cleanup.'
} finally {if(Test-Path -LiteralPath $testRoot){Remove-Item -LiteralPath $testRoot -Recurse -Force}}

