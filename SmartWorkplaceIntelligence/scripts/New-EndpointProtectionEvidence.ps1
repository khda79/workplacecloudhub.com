#Requires -Version 7.0
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$DataRoot,
    [Parameter(Mandatory)][string]$InventoryEvidencePath,
    [Parameter(Mandatory)][string]$SystemEvidencePath,
    [Parameter(Mandatory)][string]$PolicyPath,
    [Parameter(Mandatory)][string]$OutputRoot,
    [datetimeoffset]$AsOfUtc = [datetimeoffset]::UtcNow
)
# Staging generator only. Never initializes a tenant, collects or publishes data.
Set-StrictMode -Version Latest
$ErrorActionPreference='Stop'
Import-Module (Join-Path $PSScriptRoot 'EndpointProtectionEvidence.psm1') -Force
$data=(Resolve-Path -LiteralPath $DataRoot).ProviderPath.TrimEnd('\','/')
$output=[IO.Path]::GetFullPath($OutputRoot).TrimEnd('\','/')
if ($output -ieq $data -or $output.StartsWith($data+[IO.Path]::DirectorySeparatorChar,[StringComparison]::OrdinalIgnoreCase) -or $data.StartsWith($output+[IO.Path]::DirectorySeparatorChar,[StringComparison]::OrdinalIgnoreCase)) {
    throw 'Endpoint protection output must be outside and must not contain the captured raw source root.'
}
# Refuse linked output ancestors before any writes.
for ($ancestor=$output; $ancestor; $ancestor=Split-Path -Parent $ancestor) {
    if ((Test-Path -LiteralPath $ancestor) -and ((Get-Item -LiteralPath $ancestor -Force).Attributes -band [IO.FileAttributes]::ReparsePoint)) { throw 'Linked output paths are not supported.' }
}
$raw=Get-Content -LiteralPath $PolicyPath -Raw | ConvertFrom-Json
$policy=ConvertTo-EndpointProtectionPolicy -Configuration @{TenantKey=$raw.TenantKey;EndpointProtectionPolicy=$raw} -TenantKey $raw.TenantKey
if (-not $policy.Enabled) { throw 'Generator requires an explicitly enabled policy.' }
$inventory=@(Import-Csv -LiteralPath $InventoryEvidencePath)
$system=if (Test-Path -LiteralPath $SystemEvidencePath -PathType Leaf) {@(Import-Csv -LiteralPath $SystemEvidencePath)} else {@()}
$defenderPath=Join-Path $data 'DATA-LAST/Intune_EndpointSecurity_DefenderAgents.csv'
$defender=if (Test-Path -LiteralPath $defenderPath -PathType Leaf) {@(Import-Csv -LiteralPath $defenderPath)} else {@()}
$policyRows=@(New-EndpointProtectionPolicyRows $policy)
$evidence=@(New-EndpointProtectionEvidence -Policy $policy -InventoryRows $inventory -SystemRows $system -DefenderRows $defender -AsOfUtc $AsOfUtc)
# Both datasets are computed/validated before either staging output is written.
$outputs=@('EndpointProtectionPolicy.csv','EndpointProtectionEvidence.csv')
foreach ($name in $outputs) {
    $target=[IO.Path]::GetFullPath((Join-Path $output $name))
    foreach ($inputPath in @($PolicyPath,$InventoryEvidencePath,$SystemEvidencePath,$defenderPath)) {
        if ($target -ieq [IO.Path]::GetFullPath($inputPath)) { throw 'Output would overwrite an input file.' }
    }
    if ((Test-Path -LiteralPath $target) -and ((Get-Item -LiteralPath $target -Force).Attributes -band [IO.FileAttributes]::ReparsePoint)) { throw 'Linked output files are not supported.' }
}
New-Item -ItemType Directory -Path $output -Force | Out-Null
function Export-EPDataset([object[]]$Rows,[string[]]$Columns,[string]$Name) {
    $path=Join-Path $output $Name
    if ($Rows.Count) { $Rows | Select-Object $Columns | Export-Csv -LiteralPath $path -NoTypeInformation -Encoding utf8 }
    else {
        $empty=[ordered]@{}; foreach ($column in $Columns) {$empty[$column]=''}
        $header=@([pscustomobject]$empty | ConvertTo-Csv -NoTypeInformation)[0]
        Set-Content -LiteralPath $path -Value $header -Encoding utf8
    }
}
Export-EPDataset $policyRows (Get-EndpointProtectionPolicyColumns) $outputs[0]
Export-EPDataset $evidence (Get-EndpointProtectionEvidenceColumns) $outputs[1]
$known=@($inventory | ForEach-Object {$_.'Device Source ID'})
$unmatched=@($policy.ScopeRules | ForEach-Object {$_.DeviceSourceIds} | Where-Object {$_ -notin $known} | Sort-Object -Unique)
if ($unmatched.Count) { Write-Warning ('Policy scope contains {0} device IDs absent from this inventory; review policy CSV scope IDs.' -f $unmatched.Count) }
Write-Host ('Endpoint protection staging: {0} policy rows, {1} evaluations. No publication.' -f $policyRows.Count,$evidence.Count)

