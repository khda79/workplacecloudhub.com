[CmdletBinding()]
param([string]$PipelinePath=(Join-Path $PSScriptRoot 'PreparedEvidencePipeline.psm1'))
$ErrorActionPreference='Stop'
Set-StrictMode -Version Latest
$pipelineModule=Import-Module -Name $PipelinePath -Force -PassThru
$root=Join-Path ([IO.Path]::GetTempPath()) ('ExchangeInfrastructureTest-'+[guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $root|Out-Null
$checks=0
function Check([bool]$Condition,[string]$Message){if(-not $Condition){throw $Message};$script:checks++}
function Scan([string]$Path){& $pipelineModule {param($Csv) Test-PreparedTenant -Path $Csv -TenantKey 'synthetic'} $Path}
function Reject([scriptblock]$Action,[string]$Message){$failed=$false;try{& $Action|Out-Null}catch{$failed=$true};Check $failed $Message}
try{
    $names=@('Servers_Inventory','Servers_Compute','Servers_LogicalDisks','Servers_DiskDrives',
        'Servers_RemoteAccess','Infrastructure_PerServerSummary','MigrationReadiness_Config',
        'Servers_Inventory_Summary','Servers_ServiceHealth','MailboxDatabases_Paths',
        'HealthChecker_Summary','HealthChecker_Findings')
    foreach($name in $names){
        $path=Join-Path $root "Exchange_OnPrem_$name.csv"
        '"TenantKey";"Name";"Detail"','"synthetic";"mail-one";"quoted; delimiter"'|Set-Content -LiteralPath $path
        $scan=Scan $path
        Check ($scan.Rows -eq 1 -and $scan.HasTenantKey) "Declared semicolon source failed: $name"
    }
    foreach($name in @('Exchange_Hybrid_FreeBusy_Summary','Exchange_Hybrid_FreeBusy_Findings')){
        $path=Join-Path $root "$name.csv"
        '"TenantKey";"Name";"Detail"','"synthetic";"mail-one";"quoted; delimiter"'|Set-Content -LiteralPath $path
        $scan=Scan $path
        Check ($scan.Rows -eq 1 -and $scan.HasTenantKey) "Declared semicolon free/busy source failed: $name"
    }
    $path=Join-Path $root 'Exchange_OnPrem_Servers_Compute.csv'
    foreach($bad in @(
        ('"TenantKey";"Name"'+"`n"+'"foreign";"mail-one"'),
        ('"TenantKey";"Name"'+"`n"+'"";"mail-one"'),
        ('"OtherKey";"Name"'+"`n"+'"synthetic";"mail-one"'),
        ('"TenantKey";"TenantKey"'+"`n"+'"synthetic";"synthetic"'),
        ('"TenantKey";"Name"'+"`n"+'"synthetic";"mail-one";"extra"')
    )){
        Set-Content -LiteralPath $path -Value $bad
        Reject {Scan $path} 'Invalid semicolon infrastructure passed tenant validation.'
    }
    $unknown=Join-Path $root 'Exchange_OnPrem_Unapproved.csv'
    '"TenantKey";"Name"','"synthetic";"mail-one"'|Set-Content -LiteralPath $unknown
    Reject {Scan $unknown} 'Unknown Exchange file acquired an inferred semicolon delimiter.'
    $comma=Join-Path $root 'M365_Licenses_ReportSkuCapacity.csv'
    '"TenantKey","Name"','"synthetic","one"'|Set-Content -LiteralPath $comma
    Check ((Scan $comma).Rows -eq 1) 'Existing comma optional source regressed.'
    # A blank logical line leaves the strict tokenizer subset and exercises its reference fallback.
    '"TenantKey";"Name"', '', '"synthetic";"mail-one"'|Set-Content -LiteralPath $path
    $scan=Scan $path
    Check ($scan.Rows -eq 1 -and $scan.HasTenantKey) 'Reference parser semicolon fallback regressed.'
    Check ((& $pipelineModule {$script:PreparedTenantReferenceParses}) -gt 0) 'Reference fallback was not exercised.'
    "Exchange infrastructure source checks passed: $checks"
}finally{
    $resolved=[IO.Path]::GetFullPath($root)
    $temp=[IO.Path]::GetFullPath([IO.Path]::GetTempPath()).TrimEnd('\')+'\'
    if($resolved.StartsWith($temp,[StringComparison]::OrdinalIgnoreCase) -and
       (Split-Path $resolved -Leaf) -match '^ExchangeInfrastructureTest-[a-f0-9]{32}$'){
        Remove-Item -LiteralPath $resolved -Recurse -Force
    }
}

