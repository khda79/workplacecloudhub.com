#Requires -Version 7.0
# Version: 0.1.0
[CmdletBinding()]
param([Parameter(Mandatory)][string]$TestRoot)
# Synthetic immutable manifests only; no tenant, network or preparation run.
Set-StrictMode -Version Latest
$ErrorActionPreference='Stop'
Import-Module (Join-Path $PSScriptRoot 'NativeEvidence.psm1') -Force
Import-Module (Join-Path $PSScriptRoot 'EndpointProtectionEvidence.psm1') -Force
Import-Module (Join-Path $PSScriptRoot 'PreparedSharePointTransfer.psm1') -Force
$root=Join-Path ([IO.Path]::GetFullPath($TestRoot)) ('migration-transfer-'+[guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $root -Force | Out-Null
$script:checks=0
function Check([bool]$Pass,[string]$Message){if(-not $Pass){throw $Message};$script:checks++}
function Reject([scriptblock]$Action,[string]$Expected){
    $message=''
    try{& $Action | Out-Null}catch{$message=$_.Exception.Message}
    Check ($message -like $Expected) ('Expected rejection '+$Expected+'; received '+$message)
}
function CopyValue($Value){$Value | ConvertTo-Json -Depth 30 | ConvertFrom-Json}
function HashValue($Value){
    $bytes=[Text.UTF8Encoding]::new($false).GetBytes(($Value | ConvertTo-Json -Depth 20))
    [Convert]::ToHexString([Security.Cryptography.SHA256]::HashData($bytes))
}
function SaveValue([string]$Path,$Value){[IO.File]::WriteAllText($Path,($Value | ConvertTo-Json -Depth 20),[Text.UTF8Encoding]::new($false))}
$config=Join-Path $PSScriptRoot '../config'
$basePath=Join-Path $config 'prepared-evidence-contract.json.txt'
$base=Get-Content -LiteralPath $basePath -Raw | ConvertFrom-Json
$groups=@{}
foreach($pair in @(
    @('NativeEvidence','native-output-contract.json.txt'),
    @('IntuneOperations','intune-operational-contract.json.txt'),
    @('SharePointMigration','sharepoint-migration-contract.json.txt'),
    @('MailboxMigrationExceptions','mailbox-migration-exceptions-contract.json.txt'),
    @('EndpointProtection','endpoint-protection-contract.json.txt')
)){
    $path=Join-Path $config $pair[1]
    $groups[$pair[0]]=@{Contract=(Get-Content -LiteralPath $path -Raw | ConvertFrom-Json);Hash=(Get-FileHash -LiteralPath $path).Hash}
}
$module=Get-Module PreparedSharePointTransfer
function Resolve($Manifest,[string]$Path=$basePath){& $module {param($m,$p) Resolve-PreparedTransferContract -Manifest $m -ContractPath $p} $Manifest $Path}
function MakeManifest($Contract,[bool]$Migration,[bool]$Exceptions,[bool]$Endpoint){
    $proof=@{}
    foreach($key in @('NativeEvidence','IntuneOperations')){$proof[$key]=@{ContractSHA256=$groups[$key].Hash}}
    if($Migration){$proof.SharePointMigration=@{ContractSHA256=$groups.SharePointMigration.Hash;Audit=@{Enabled=$true}}}
    if($Exceptions){$proof.MailboxMigrationExceptions=@{ContractSHA256=$groups.MailboxMigrationExceptions.Hash}}
    if($Endpoint){$proof.EndpointProtectionPolicy=@{PolicyVersion='synthetic-v1';SHA256=('a'*64)}}
    CopyValue @{Files=@($Contract.tables | ForEach-Object {@{File=$_.file}});Provenance=$proof;ContractSHA256=(HashValue $Contract)}
}
# Follow the production assembly order exactly: base/native/migration/mailbox/endpoint.
foreach($migrationEnabled in @($false,$true)){
    foreach($exceptionsEnabled in @($false,$true)){
        foreach($endpointEnabled in @($false,$true)){
            # The resolver imports these helpers in its own module scope.
            Import-Module (Join-Path $PSScriptRoot 'NativeEvidence.psm1') -Force
            Import-Module (Join-Path $PSScriptRoot 'EndpointProtectionEvidence.psm1') -Force
            $contract=Merge-NativeEvidenceContract (CopyValue $base)
            if($migrationEnabled){$contract.tables=@($contract.tables)+@($groups.SharePointMigration.Contract.tables)}
            if($exceptionsEnabled){$contract.tables=@($contract.tables)+@($groups.MailboxMigrationExceptions.Contract.tables)}
            if($endpointEnabled){$contract=Merge-EndpointProtectionContract $contract $groups.EndpointProtection.Contract}
            $manifest=MakeManifest $contract $migrationEnabled $exceptionsEnabled $endpointEnabled
            $resolved=Resolve $manifest
            Check ((HashValue $resolved) -ceq $manifest.ContractSHA256) 'Reconstructed contract differs from immutable publication hash/order'
            $supplied=Join-Path $root 'effective.json.txt';SaveValue $supplied $contract
            Check ((HashValue (Resolve $manifest $supplied)) -ceq $manifest.ContractSHA256) 'Effective supplied contract must remain unchanged'
            if(-not $migrationEnabled){continue}
            $disabled=CopyValue $manifest;$disabled.Provenance.SharePointMigration.Audit.Enabled=$false
            Check ((HashValue (Resolve $disabled)) -ceq $manifest.ContractSHA256) 'Disabled feature still retains its nine typed outputs'
            $bad=CopyValue $manifest;$bad.Files=@($bad.Files | Where-Object File -ne $groups.SharePointMigration.Contract.tables[0].file)
            Reject {Resolve $bad} '*Incomplete SharePoint migration file set*'
            $bad=CopyValue $manifest
            # Duplicate a migration entry while preserving the total group count.
            $entries=@($bad.Files | Where-Object File -in $groups.SharePointMigration.Contract.tables.file)
            $entries[0].File=$entries[1].File
            Reject {Resolve $bad} '*Incomplete SharePoint migration file set*'
            $bad=CopyValue $manifest;$bad.Provenance.PSObject.Properties.Remove('SharePointMigration')
            Reject {Resolve $bad} '*SharePoint migration contract provenance mismatch*'
            $bad=CopyValue $manifest;$bad.Provenance.SharePointMigration.ContractSHA256=('0'*64)
            Reject {Resolve $bad} '*SharePoint migration contract provenance mismatch*'
            $bad=CopyValue $manifest;$bad.Provenance.SharePointMigration.PSObject.Properties.Remove('ContractSHA256')
            Reject {Resolve $bad} '*SharePoint migration contract provenance mismatch*'
            $bad=CopyValue $manifest;$bad.Files=@($bad.Files | Where-Object File -notin $groups.SharePointMigration.Contract.tables.file)
            Reject {Resolve $bad} '*Incomplete SharePoint migration file set*'
            $bad=CopyValue $manifest;$bad.ContractSHA256=('0'*64)
            Reject {Resolve $bad} '*contract hash mismatch*'
            $partial=CopyValue $base;$partial.tables+=@($groups.SharePointMigration.Contract.tables[0])
            $partialPath=Join-Path $root 'partial.json.txt';SaveValue $partialPath $partial
            Reject {Resolve $manifest $partialPath} '*Incomplete supplied SharePoint migration contract*'
            $duplicate=CopyValue $contract
            $entries=@($duplicate.tables | Where-Object file -in $groups.SharePointMigration.Contract.tables.file)
            $entries[0].file=$entries[1].file
            $duplicatePath=Join-Path $root 'duplicate.json.txt';SaveValue $duplicatePath $duplicate
            Reject {Resolve $manifest $duplicatePath} '*Incomplete supplied SharePoint migration contract*'
        }
    }
}
[pscustomobject]@{Status='Passed';Checks=$script:checks;TestRoot=$root}

