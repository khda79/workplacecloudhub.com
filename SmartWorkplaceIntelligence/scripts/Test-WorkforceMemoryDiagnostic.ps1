[CmdletBinding()]
param([Parameter(Mandatory)][string]$TestRoot)
# Synthetic workers and static checks only. No tenant setup or real inventory run.
$ErrorActionPreference='Stop'
$root=Join-Path ([IO.Path]::GetFullPath($TestRoot)) ([guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $root -Force | Out-Null
$module=Import-Module (Join-Path $PSScriptRoot 'WorkforceMemoryDiagnostic.psm1') -Force -PassThru
$script:checks=0
function Check([bool]$Condition,[string]$Message){if(-not $Condition){throw $Message};$script:checks++}
function Reject([scriptblock]$Action,[string]$Pattern){$message='';try{& $Action | Out-Null}catch{$message=$_.Exception.Message};Check ($message -match $Pattern) "Expected '$Pattern', got '$message'"}
try {
    $worker=Join-Path $root 'synthetic worker.ps1'
    [IO.File]::WriteAllText($worker,@'
param([string]$StagePath,[int]$RequestedExit)
@{Utc=[datetime]::UtcNow.ToString('O');Stage='Synthetic allocation';ProcessId=$PID} | ConvertTo-Json -Compress | Set-Content -LiteralPath $StagePath
$buffer=[byte[]]::new(4194304)
Write-Output 'synthetic stdout'
[Console]::Error.WriteLine('synthetic stderr')
Start-Sleep -Seconds 6
exit $RequestedExit
'@)
    foreach($exitCode in 0,17){
        $run=Join-Path $root "run $exitCode";New-Item -ItemType Directory -Path $run | Out-Null
        $result=& $module {param($p,$a,$r) Invoke-MonitoredWorkforceProcess -WorkerPath $p -WorkerArguments $a -RunRoot $r} $worker @('-StagePath',(Join-Path $run 'stages.ndjson'),'-RequestedExit',[string]$exitCode) $run
        Check ($result.ExitCode -eq $exitCode) 'Worker exit code lost'
        Check ($result.Samples -ge 2) 'External memory samples missing'
        Check ($result.LastStage -eq 'Synthetic allocation') 'Last stage lost'
        Check ($result.SampledPeakPrivateBytes -gt 0 -and -not $result.Publication) 'Process memory or no-publication flag incorrect'
        Check (Test-Path (Join-Path $run 'result.json')) 'Result missing after worker exit'
        Check ((Get-Content (Join-Path $run 'worker.stdout.log') -Raw) -match 'synthetic stdout') 'stdout capture failed'
        Check ((Get-Content (Join-Path $run 'worker.stderr.log') -Raw) -match 'synthetic stderr') 'stderr capture failed'
        $samples=@(Import-Csv (Join-Path $run 'memory.csv'))
        Check ($samples[-1].Exited -eq 'True') 'Terminal sample missing'
        $environment=Get-Content (Join-Path $run 'environment.json') -Raw | ConvertFrom-Json
        Check ($environment.Is64BitProcess -and $environment.SampleIntervalSeconds -eq 5) 'Wrong measurement runtime or frequency'
    }
    # Load only the instrumentation helper via AST, never the business script.
    $path=Join-Path $PSScriptRoot 'New-WorkforceIdentityEvidence.ps1'
    $tokens=$null;$errors=$null
    $ast=[Management.Automation.Language.Parser]::ParseFile($path,[ref]$tokens,[ref]$errors)
    Check ($errors.Count -eq 0) 'Workforce syntax failed'
    $node=$ast.Find({param($n) $n -is [Management.Automation.Language.FunctionDefinitionAst] -and $n.Name -eq 'Write-WorkforceDiagnostic'},$true)
    . ([scriptblock]::Create($node.Extent.Text))
    $DiagnosticStagePath=$null
    Check (@(Write-WorkforceDiagnostic 'Disabled').Count -eq 0) 'Disabled instrumentation emitted pipeline data'
    $DiagnosticStagePath=Join-Path $root 'stages-test.ndjson'
    Write-WorkforceDiagnostic 'Synthetic step'
    $event=Get-Content $DiagnosticStagePath -Raw | ConvertFrom-Json
    Check ($event.Stage -eq 'Synthetic step' -and $event.ProcessId -eq $PID -and $event.ManagedBytes -gt 0) 'Stage instrumentation failed'
    Check (@($event.PSObject.Properties.Name).Count -eq 6) 'Unexpected stage fields'
    # Static safety constraints: parent can wait, never force-stop the worker.
    $body=[IO.File]::ReadAllText((Join-Path $PSScriptRoot 'WorkforceMemoryDiagnostic.psm1'))
    Check ($body -notmatch 'Stop-Process|\.Kill\(|Publish-PreparedEvidenceBatch|Invoke-PreparedEvidencePipeline|GC\]::Collect') 'Diagnostic contains mutation/cancellation or forced GC'
    Check ($body -match '-WindowStyle Hidden' -and $body -match 'WaitForExit\(5000\)') 'Worker visibility/sampling policy changed'
    $raw=Join-Path $root 'raw';New-Item -ItemType Directory -Path $raw | Out-Null
    Reject {Invoke-WorkforceMemoryDiagnostic -DataRoot $raw -WorkRoot (Join-Path $raw 'diagnostic') -AccountClassificationConfigPath 'unused'} 'roots must be disjoint'
    Reject {Invoke-WorkforceMemoryDiagnostic -DataRoot $raw -WorkRoot $root -AccountClassificationConfigPath 'unused'} 'roots must be disjoint'
    # Inspect the real public wiring without running the business worker.
    $config=Join-Path $raw 'AccountClassification.psd1';[IO.File]::WriteAllText($config,'@{}')
    foreach($name in 'SmartWorkplaceIntelligence-PersonaClassification.xlsx','SmartWorkplaceIntelligence-SiteClassification.xlsx'){[IO.File]::WriteAllText((Join-Path $raw $name),'synthetic')}
    $guard=Join-Path $raw 'keep.csv';[IO.File]::WriteAllText($guard,'synthetic unchanged');$guardHash=(Get-FileHash $guard).Hash
    & $module {function script:Invoke-MonitoredWorkforceProcess {param($WorkerPath,$WorkerArguments,$RunRoot) [pscustomobject]@{WorkerPath=$WorkerPath;Arguments=$WorkerArguments;RunRoot=$RunRoot}}}
    $work=Join-Path $root 'work'
    $wired=Invoke-WorkforceMemoryDiagnostic -DataRoot $raw -WorkRoot $work -AccountClassificationConfigPath $config
    Check ([IO.Path]::GetFileName($wired.WorkerPath) -eq 'New-WorkforceIdentityEvidence.ps1') 'Wrong domain invoked'
    Check ($wired.Arguments -notcontains '-SkipHistory' -and $wired.Arguments -notcontains '-ReuseStagedWorkforce') 'Diagnostic truncates or reuses history'
    foreach($parameter in '-UserOutputPath','-HistoryOutputPath','-TrendOutputPath','-IdentityOutputPath','-SignalsOutputPath'){
        $index=[array]::IndexOf($wired.Arguments,$parameter)
        Check ($index -ge 0 -and $wired.Arguments[$index+1].StartsWith((Join-Path $wired.RunRoot 'outputs')+'\')) 'Business output not isolated'
    }
    Check ((Get-FileHash $guard).Hash -eq $guardHash -and -not(Test-Path (Join-Path $raw 'DATA-POWERBI'))) 'Diagnostic changed source or created production output'
    $lock=[IO.File]::Open((Join-Path $raw '.prepared-source.lock'),'Open','ReadWrite','None');$lock.Dispose()
    Check ($true) 'Diagnostic source lock released'
    # Simulate unavailable counters; absence must remain null, not a false zero.
    & $module {function script:Get-CimInstance {throw 'synthetic counter failure'}}
    $memory=& $module {Get-WorkforceSystemMemory}
    Check ($null -eq $memory.AvailableBytes -and $null -eq $memory.CommitLimitBytes -and $memory.Error) 'Missing counters misreported'
    Write-Host "PASS: $script:checks diagnostic instrumentation, external samples, success/failure exits, log capture and safety checks. Synthetic workers only."
} finally {Remove-Module $module}

