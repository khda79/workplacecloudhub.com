[CmdletBinding()]
param([Parameter(Mandatory)][string]$TestRoot)
Set-StrictMode -Version Latest
$ErrorActionPreference='Stop'

# Execute only the real initialization and schema guard, never the full generator.
$tokens=$null;$parseErrors=$null
$ast=[Management.Automation.Language.Parser]::ParseFile((Join-Path $PSScriptRoot 'New-WorkforceIdentityEvidence.ps1'),[ref]$tokens,[ref]$parseErrors)
if($parseErrors.Count){throw 'Generator syntax is invalid.'}
$statements=@($ast.EndBlock.Statements)
$matches=@(0..($statements.Count-1) | Where-Object {
    $statements[$_] -is [Management.Automation.Language.AssignmentStatementAst] -and
    $statements[$_].Left.Extent.Text -eq '$resumeHistoryRows'
})
if($matches.Count -ne 1){throw 'History initialization must have exactly one assignment.'}
$index=$matches[0]
if($statements[$index+1] -isnot [Management.Automation.Language.IfStatementAst]){throw 'History schema guard not found.'}
$initialize=[scriptblock]::Create($statements[$index].Extent.Text+"`n"+$statements[$index+1].Extent.Text)
$run=Join-Path ([IO.Path]::GetFullPath($TestRoot)) ([guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $run -Force | Out-Null
$validRows=@(
    [pscustomobject][ordered]@{'User Principal Name'='synthetic1@example.invalid';'Confirmed Human'='True';'Week Label'='2026-W01'},
    [pscustomobject][ordered]@{'User Principal Name'='synthetic2@example.invalid';'Confirmed Human'='False';'Week Label'='2026-W02'}
)
$cases=@(
    @{Name='absent';Kind='absent';Expected=0},
    @{Name='empty';Kind='empty';Expected=0},
    @{Name='headers-only';Kind='headers';Expected=0},
    @{Name='single-row';Kind='rows';Rows=@($validRows[0]);Expected=1},
    @{Name='multiple-rows';Kind='rows';Rows=$validRows;Expected=2},
    @{Name='missing-human-column';Kind='rows';Rows=@([pscustomobject]@{'User Principal Name'='synthetic@example.invalid'});Reject=$true},
    @{Name='missing-upn-column';Kind='rows';Rows=@([pscustomobject]@{'Confirmed Human'='True'});Reject=$true},
    @{Name='obsolete-columns';Kind='rows';Rows=@([pscustomobject]@{Legacy='synthetic'});Reject=$true}
)
foreach($case in $cases){
    $historyTemporaryPath=Join-Path $run ($case.Name+'.csv.tmp')
    switch($case.Kind){
        'empty' {[IO.File]::WriteAllText($historyTemporaryPath,'')}
        'headers' {[IO.File]::WriteAllText($historyTemporaryPath,'"User Principal Name","Confirmed Human","Week Label"'+"`r`n")}
        'rows' {$case.Rows | Export-Csv -LiteralPath $historyTemporaryPath -NoTypeInformation -Encoding utf8}
    }
    $beforeHash=if(Test-Path -LiteralPath $historyTemporaryPath){(Get-FileHash -LiteralPath $historyTemporaryPath).Hash}else{$null}
    $resumeHistoryRows=$null;$caught=$null
    try {. $initialize} catch {$caught=$_}
    if($case.ContainsKey('Reject')){
        if($null -eq $caught -or $caught.Exception.Message -notlike 'Historical staging schema is obsolete.*'){throw "Schema rejection failed: $($case.Name)"}
    } else {
        if($null -ne $caught){throw $caught}
        if($resumeHistoryRows -isnot [array] -or $resumeHistoryRows.Count -ne $case.Expected){throw "Array/count regression: $($case.Name)"}
        if($case.Kind -eq 'rows'){
            for($i=0;$i -lt $case.Expected;$i++){
                foreach($property in $case.Rows[$i].PSObject.Properties){
                    if($resumeHistoryRows[$i].PSObject.Properties[$property.Name].Value -cne $property.Value){throw "Row/order/value changed: $($case.Name)"}
                }
            }
        }
    }
    $afterHash=if(Test-Path -LiteralPath $historyTemporaryPath){(Get-FileHash -LiteralPath $historyTemporaryPath).Hash}else{$null}
    if($beforeHash -cne $afterHash){throw "Input modified: $($case.Name)"}
}
'PASS: 8 history initialization cases; strict-mode arrays, row/order/value preservation, obsolete schema rejection, unchanged inputs. Synthetic fixtures only.'

