#Requires -Version 7.0
<#
.SYNOPSIS
Prepares only Device System evidence from existing local CSVs in a private staging directory.
.NOTES
No collection, batch activation, Power BI connection, refresh or publication.
#>
[CmdletBinding()]
param([Parameter(Mandatory)][string]$DataRoot,
      [Parameter(Mandatory)][string]$OutputRoot,
      [string]$PreparedInventoryPath,
      [Nullable[double]]$MaxObservationAgeHours,
      [string]$OffsetlessGraphTimeZoneId)
Set-StrictMode -Version Latest
$ErrorActionPreference='Stop'
Import-Module (Join-Path $PSScriptRoot 'DeviceSystemEvidence.psm1') -Force
$data=(Resolve-Path -LiteralPath $DataRoot).ProviderPath.TrimEnd('\')
$output=[IO.Path]::GetFullPath($OutputRoot).TrimEnd('\')
if ($output -eq $data -or $output.StartsWith($data+'\',[StringComparison]::OrdinalIgnoreCase)) {throw 'Use a private staging directory outside the raw data and active batch root.'}
$paths=@{System=Join-Path $data 'DATA-LAST\Intune_Devices_LocalSystem.csv';Inventory=Join-Path $data 'DATA-LAST\Intune_Devices_Inventory.csv';Users=Join-Path $data 'DATA-LAST\M365_Users_Active.csv'}
if ($PreparedInventoryPath) {$paths.Prepared=[IO.Path]::GetFullPath($PreparedInventoryPath)}
Assert-DeviceSystemCsvSchema -Path $paths.System
$before=@{}; $rows=@{}
foreach ($name in $paths.Keys) {
    $before[$name]=(Get-FileHash -LiteralPath $paths[$name] -Algorithm SHA256).Hash
    $rows[$name]=@(Import-Csv -LiteralPath $paths[$name])
}
$args=@{SystemRows=$rows.System;InventoryRows=$rows.Inventory;UserRows=$rows.Users;MaxObservationAgeHours=$MaxObservationAgeHours;OffsetlessGraphTimeZoneId=$OffsetlessGraphTimeZoneId}
if ($PreparedInventoryPath) {$args.PreparedInventoryRows=$rows.Prepared}
$evidence=@(New-DeviceSystemEvidence @args)
foreach ($name in $paths.Keys) {
    if ($before[$name] -ne (Get-FileHash -LiteralPath $paths[$name] -Algorithm SHA256).Hash) {throw 'Source changed during offline preparation. Nothing was staged.'}
}
New-Item -ItemType Directory -Path $output -Force | Out-Null
$target=Join-Path $output 'DeviceSystemEvidence.csv'
if (Test-Path -LiteralPath $target) {throw 'Staged Device System output already exists. Choose a new staging directory.'}
if ($evidence.Count) {$evidence | Export-Csv -LiteralPath $target -NoTypeInformation -Encoding utf8NoBOM}
else {
    $empty=[ordered]@{}; foreach ($column in Get-DeviceSystemEvidenceColumns) {$empty[$column]=''}
    $header=([pscustomobject]$empty | ConvertTo-Csv -NoTypeInformation)[0]
    [IO.File]::WriteAllText($target,$header+[Environment]::NewLine,[Text.UTF8Encoding]::new($false))
}
$audit=[ordered]@{PreparedUtc=[datetime]::UtcNow.ToString('o');Rows=$evidence.Count;SourceHashes=$before;OutputSHA256=(Get-FileHash -LiteralPath $target).Hash;MaxObservationAgeHours=$MaxObservationAgeHours;OffsetlessGraphTimeZoneId=$OffsetlessGraphTimeZoneId;Activation=$false;
    ExpectedAV=@($evidence | Group-Object 'Expected AV State' | ForEach-Object {@{State=$_.Name;Rows=$_.Count}});
    Freshness=@($evidence | Group-Object Freshness | ForEach-Object {@{State=$_.Name;Rows=$_.Count}});
    MissingInventory=@($evidence | Where-Object 'Inventory Match' -eq 'Unmatched').Count;
    MissingPreparedInventory=@($evidence | Where-Object 'Prepared Inventory Match' -eq 'Unmatched').Count;
    EncryptionConflicts=@($evidence | Where-Object 'Encryption Comparison' -eq 'Conflict').Count;
    BootAliasConflicts=@($evidence | Where-Object 'Last Boot Quality' -eq 'Conflicting aliases').Count}
$json=$audit | ConvertTo-Json -Depth 6
[IO.File]::WriteAllText((Join-Path $output 'DeviceSystemAudit.json.txt'),$json,[Text.UTF8Encoding]::new($false))
$json

